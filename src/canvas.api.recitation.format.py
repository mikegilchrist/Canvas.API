#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.recitation.format.py
# Version:      1.0.0
# Created:      2026-08-19
# Purpose:      Put the activity recitation pages into the settled format:
#               Readings, Slides, Worksheets -- in that order.
#
# The pages already used these sections, but in varied order and spelling
# ("Worksheet" singular, Slides before Readings, and so on).  This normalizes
# them WITHOUT discarding anything: each section keeps its own content, a
# missing one is added as "To be posted", and any extra section a page carries
# (Key, Optional Recommended Readings & Videos, Team Resources, External
# Resources) is preserved and appended after the standard three.
#
# SAFETY: the file links are the point of these pages -- they are how a
# student reaches the worksheet.  The script counts instructure_file_link
# occurrences before and after and REFUSES to write that page if the count
# would drop.  Nothing is ever silently lost.
#
# Only ACTIVITY recitations are touched.  R01 (photos/CATME), R06 and R12
# (Pre-Exam Q&A, which carry generated board links) and R07/R13 (Post-Exam)
# are session types with their own shape, and forcing three empty headings on
# them would be worse than leaving them.
#
# Usage:        canvas.recitation.format.py [--apply] [-v]
# Options:      -a/--apply   perform the writes (default is a DRY RUN)
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import html
import os
import pathlib
import re
import sys
import urllib.parse

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
STANDARD = ["Readings", "Slides", "Worksheets"]
ACTIVITIES = ["R02", "R03", "R04", "R05", "R08", "R09", "R10", "R11", "R14"]

# Existing heading (lowercased, stripped) -> which standard section it is.
ALIAS = {"reading": "Readings", "readings": "Readings",
         "slide": "Slides", "slides": "Slides",
         "worksheet": "Worksheets", "worksheets": "Worksheets",
         "activity": "Worksheets"}


def split_sections(body):
    """[(heading or None, html)] in document order; None is the preamble."""
    parts, last, out = list(re.finditer(r"<h[23][^>]*>(.*?)</h[23]>", body, re.S)), 0, []
    if not parts:
        return [(None, body)]
    if parts[0].start() > 0:
        out.append((None, body[:parts[0].start()]))
    for i, m in enumerate(parts):
        head = re.sub(r"<[^>]+>", "", m.group(1))
        head = html.unescape(head).replace("\xa0", " ").strip()
        end = parts[i + 1].start() if i + 1 < len(parts) else len(body)
        out.append((head, body[m.end():end]))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    global BASE, COURSE
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id

    pages = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/pages?per_page=100", tok)
    for p in sorted(pages, key=lambda x: x["title"]):
        if p["title"][:3] not in ACTIVITIES:
            continue
        r = canvas_http.http_get_json(
            f'{BASE}/api/v1/courses/{COURSE}/pages/'
            f'{urllib.parse.quote(p["url"], safe="")}', tok)
        d = r[0] if isinstance(r, tuple) else r
        body = d.get("body") or ""

        std, extra, pre = {}, [], ""
        for head, chunk in split_sections(body):
            if head is None:
                pre += chunk
                continue
            key = ALIAS.get(head.lower())
            if key:
                std[key] = std.get(key, "") + chunk      # duplicates merge
            else:
                extra.append((head, chunk))

        new = pre
        for s in STANDARD:
            new += f"<h2>{s}</h2>\n" + (std.get(s) or "<p>To be posted</p>\n")
        for head, chunk in extra:
            new += f"<h2>{html.escape(head)}</h2>\n" + chunk

        before = len(re.findall(r"instructure_file_link", body))
        after = len(re.findall(r"instructure_file_link", new))
        order = [h for h, _ in split_sections(new) if h]
        if after < before:
            print(f"  REFUSE  {p['title'][:44]}: {before} file link(s) -> {after}")
            continue
        if order == STANDARD + [h for h, _ in extra] and set(std) >= set(STANDARD) \
                and body.strip() == new.strip():
            if a.verbose:
                print(f"  ok      {p['title'][:44]}  already in format")
            continue
        added = [s for s in STANDARD if s not in std]
        print(f"  {tag}FORMAT  {p['title'][:44]:<44} links {before}->{after}  "
              f"order {order}" + (f"  added {added}" if added else ""))
        if a.apply:
            canvas_http.http_put_json(
                f'{BASE}/api/v1/courses/{COURSE}/pages/'
                f'{urllib.parse.quote(p["url"], safe="")}', tok,
                {"wiki_page": {"body": new}})
    return 0


if __name__ == "__main__":
    sys.exit(main())
