# Version:      1.1.0
# Created:      2026-08-18
# Revised:      2026-10-13
# Purpose:      Build one Canvas page per 2026 lecture, from schedule_2026.tsv.
#
# The pages inherited from prior years carry the OLD numbering (L10a, L16b,
# two different L21b) and old titles, so they no longer line up with the 26
# lectures the 2026 schedule actually teaches.  This regenerates them from the
# schedule, so page title == board title == schedule topic.
#
# NEVER TOUCHES L01 (MG, 2026-08-18): it is the hand-built model, with real
# file links, and is the shape the others grow into.
#
# CREATES AND UPDATES ONLY -- it never deletes.  Eight of the inherited pages
# carry real file links to uploaded slides and readings, and those links are
# the only record of which deck belongs to which lecture.  Orphaned pages are
# REPORTED at the end so they can be ported by hand and retired deliberately.
#
# New pages are created UNPUBLISHED.  Publishing follows the course schedule
# and is a separate decision.
#
# Usage:        canvas.api.lecture.pages.py [--apply] [-v]
# Input:        F.2026/Syllabus/schedule_2026.tsv; token at ~/.api/canvas_token
# Output:       Stdout: one line per page, then the orphan report
#
# Options:
#   -a, --apply    Perform the writes (default is a dry run)
#   -v, --verbose  Show pages that are already correct
#   -h, --help     Show this help message
#
