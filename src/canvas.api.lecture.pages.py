import argparse
import csv
import html
import os
import pathlib
import re
import sys
import urllib.parse

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
TSV = None   # set in main(): paths.schedule_tsv in canvas.course.json
SKIP = {1}                      # L01 is MG's; leave it exactly as it is.

TBP = "To be posted"


# The standard is Readings / Slides / Clickers and NOTHING ELSE.  Worksheets
# are used on only a few lectures (MG, 2026-08-19), so that heading is added by
# hand where it is needed -- L08 carries one for the sex-linked cross activity
# -- and must NOT be added to the skeleton.  A page holding a real file link is
# left alone by this script, which is what protects those exceptions.


def body_for(readings):
    """The standard lecture-page format (MG, 2026-08-18).

    Three sections, in this order, and the two placeholders say WHEN the thing
    arrives rather than just that it is missing -- slides before the lecture,
    clickers after it.
    """
    return (f"<h2>Readings</h2>\n<p>{html.escape(readings) if readings else TBP}</p>\n"
            f"<h2>Slides</h2>\n<p>To be posted before lecture</p>\n"
            f"<h2>Clickers</h2>\n<p>To be posted after lecture</p>")


def plain(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html.unescape(s or ""))).strip()


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    global BASE, COURSE, TSV
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    TSV = cfg.path("schedule_tsv")

    want = []
    for r in csv.DictReader(open(TSV), delimiter="\t"):
        n = r["lecture"].strip()
        if n.isdigit():
            want.append((int(n), r["topic"].strip(), r["readings"].strip()))

    pages = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/pages?per_page=100", tok)
    by_title = {p["title"]: p for p in pages}

    made = upd = kept = 0
    for n, topic, readings in want:
        title = f"L{n:02d}: {topic}"
        if n in SKIP:
            print(f"  SKIP    {title[:56]}  (left untouched by request)")
            continue
        body = body_for(readings)
        cur = by_title.get(title)
        if cur is None:
            print(f"  {tag}CREATE  {title[:56]}")
            made += 1
            if a.apply:
                canvas_http.http_post_json(
                    f"{BASE}/api/v1/courses/{COURSE}/pages", tok,
                    {"wiki_page": {"title": title, "body": body,
                                   "published": False}})
            continue
        r = canvas_http.http_get_json(
            f'{BASE}/api/v1/courses/{COURSE}/pages/'
            f'{urllib.parse.quote(cur["url"], safe="")}', tok)
        d = r[0] if isinstance(r, tuple) else r
        if plain(d.get("body")) == plain(body):
            kept += 1
            if a.verbose:
                print(f"          {title[:56]}  already correct")
        elif re.search(r"instructure_file_link", d.get("body") or ""):
            print(f"  KEEP    {title[:56]}  (has file links; not overwritten)")
            kept += 1
        else:
            print(f"  {tag}UPDATE  {title[:56]}")
            upd += 1
            if a.apply:
                canvas_http.http_put_json(
                    f'{BASE}/api/v1/courses/{COURSE}/pages/'
                    f'{urllib.parse.quote(cur["url"], safe="")}', tok,
                    {"wiki_page": {"body": body}})

    print(f"\n{tag}{made} created, {upd} updated, {kept} left as-is")

    # Anything that looks like a lecture page but is not one of the 26.
    keep_titles = {f"L{n:02d}: {t}" for n, t, _ in want}
    orphans = [p for p in pages
               if re.match(r"L\d", p["title"]) and p["title"] not in keep_titles]
    if orphans:
        print(f"\n{len(orphans)} inherited page(s) no longer named by the schedule."
              f"  NOT deleted:")
        for p in sorted(orphans, key=lambda x: x["title"]):
            r = canvas_http.http_get_json(
                f'{BASE}/api/v1/courses/{COURSE}/pages/'
                f'{urllib.parse.quote(p["url"], safe="")}', tok)
            d = r[0] if isinstance(r, tuple) else r
            links = len(re.findall(r"instructure_file_link", d.get("body") or ""))
            note = f"  <-- {links} FILE LINK(S) to port by hand" if links else ""
            print(f"    {p['title'][:56]:<56} pub={p['published']!s:<5}{note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
