# Script:       canvas.api.gradebook.configure.py
# Version:      1.1.0
# Created:      2026-08-10
# Revised:      2026-10-13
# Purpose:      Configure a course's Canvas gradebook so its running Total is
#               a real grade students can read all semester.
#
# Applies the weighting described in Course.Conventions/canvas.gradebook.setup.md:
# one assignment group per distinct weight, group weights taken from the
# `adopted` scheme in bin/grade.schemes.json (now carried in
# the course's canvas.course.json under "gradebook"), a grading standard using the
# LITERAL syllabus cutoffs, automatic grade posting, and omit_from_final_grade
# on the items that are inputs rather than grades.
#
# Idempotent: re-running converges on the same state and reports no changes.
# Dry run by DEFAULT -- nothing is written without --apply.
#
# Usage:        canvas.api.gradebook.configure.py [--course-id N | --course-config FILE] [COURSE_ID] [--apply] [-v]
# Input:        canvas.course.json "gradebook" section (groups, cutoffs, ...)
#               and paths.grade_engine_config; Canvas token
# Output:       Stdout: a per-step plan, then a verification summary
#
# Options:
#       --course-id N     Canvas course id (also --course; positional COURSE_ID
#                         also works; else canvas.course.json)
#       --course-config FILE  canvas.course.json to use
#       --year Y          year for {year} in paths and the engine config key
#   -a, --apply       Write the changes (default is a dry run)
#   -v, --verbose     Show every API call
#   -h, --help        Show this help message
#
# Requirements:
#   - python3 (stdlib only)
#   - a Canvas API token with teacher rights on the course
