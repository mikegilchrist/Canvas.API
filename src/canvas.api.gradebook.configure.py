import argparse
import json
import pathlib
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

import os
sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import canvas_course  # noqa: E402

BASE = None    # set in main() from canvas.course.json
# Course-specific plan, read in main() from canvas.course.json "gradebook":
GROUPS = {}            # name -> {"weight": pct, "drop_lowest": n}; sums to 100
STANDARD_NAME = ""
CUTOFFS = []           # [(letter, lower bound)]
OMIT_PATTERNS = []     # inputs to the grade, not grades
SHOW_STUDENTS = []     # omitted from total but scores stay visible
MOVE_RULES = []        # [(regex, group)] exam placement
UNMOVED_GROUP = None   # group the import lands exams in
ENGINE_GROUPS = {}     # grade-engine column key -> Canvas group name
ENGINE_CFG = None      # path to the grade engine's column-regex JSON
ENGINE_YEAR = None


def load_plan(cfg):
    """Fill the plan globals from cfg.data["gradebook"]; exit cleanly if absent."""
    global GROUPS, STANDARD_NAME, CUTOFFS, OMIT_PATTERNS, SHOW_STUDENTS
    global MOVE_RULES, UNMOVED_GROUP, ENGINE_GROUPS, ENGINE_CFG, ENGINE_YEAR
    gb = cfg.data.get("gradebook")
    if not gb:
        sys.exit(f"[FAIL] no \"gradebook\" section in {cfg.source or 'canvas.course.json'}")
    try:
        GROUPS = {g["name"]: {k: v for k, v in g.items() if k != "name"}
                  for g in gb["groups"]}
        STANDARD_NAME = gb["standard_name"]
        CUTOFFS = [tuple(c) for c in gb["cutoffs"]]
    except KeyError as e:
        sys.exit(f"[FAIL] gradebook section lacks {e}")
    OMIT_PATTERNS = list(gb.get("omit_patterns", []))
    SHOW_STUDENTS = list(gb.get("show_students", []))
    MOVE_RULES = [tuple(m) for m in gb.get("move_rules", [])]
    UNMOVED_GROUP = gb.get("unmoved_group")
    ENGINE_GROUPS = dict(gb.get("engine_groups", {}))
    ENGINE_YEAR = str(cfg.year) if cfg.year is not None else None
    try:
        ENGINE_CFG = pathlib.Path(cfg.path("grade_engine_config"))
    except canvas_course.CourseConfigError:
        ENGINE_CFG = None   # engine reconciliation is then skipped, loudly


def engine_pattern(key, year=None):
    """A column regex from bin/grade.gradebook.config.json.

    Read from the grade engine's own config rather than restated here, so the
    Canvas gradebook and the end-of-term calculation cannot drift apart.
    """
    cfg = ENGINE_CFG
    year = year or ENGINE_YEAR
    if cfg is None:
        print("    (no paths.grade_engine_config in the course config)")
        return None
    try:
        cols = json.loads(cfg.read_text())["years"][year]["columns"]
    except (OSError, KeyError, json.JSONDecodeError) as e:
        print(f"    (could not read {cfg.name} for year {year}: {e})")
        return None
    return cols.get(key)


class API:
    def __init__(self, tok, verbose=False):
        self.tok, self.verbose = tok, verbose

    def _call(self, method, path, fields=None):
        url = path if path.startswith("http") else f"{BASE}/api/v1{path}"
        data = None
        if fields:
            data = urllib.parse.urlencode(fields, doseq=True).encode()
        req = urllib.request.Request(url, data=data, method=method)
        req.add_header("Authorization", f"Bearer {self.tok}")
        if self.verbose:
            print(f"    [{method}] {url}")
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                body = r.read().decode()
                link = r.headers.get("Link", "")
            return (json.loads(body) if body else None), link
        except urllib.error.HTTPError as e:
            sys.exit(f"API {method} {url} failed: {e.code} {e.read().decode()[:300]}")

    def get(self, path):
        return self._call("GET", path)[0]

    def get_all(self, path):
        """Follow rel=next so a 100-item page cannot silently truncate."""
        sep = "&" if "?" in path else "?"
        out, url = [], f"{path}{sep}per_page=100"
        while url:
            page, link = self._call("GET", url)
            out += page
            url = None
            for part in link.split(","):
                if 'rel="next"' in part:
                    url = part.split(";")[0].strip().strip("<>")
        return out

    def post(self, path, fields):
        return self._call("POST", path, fields)[0]

    def set_post_policy(self, assignment_id, post_manually):
        """Set an assignment's posting policy.

        This MUST go through GraphQL.  The REST assignment update accepts
        `assignment[post_manually]`, returns 200, and silently does nothing --
        so a script that used REST would report success every run while the
        grades stayed hidden from students forever.
        """
        q = ('mutation { setAssignmentPostPolicy(input: {assignmentId: "%s", '
             'postManually: %s}) { postPolicy { postManually } '
             'errors { message } } }' % (assignment_id,
                                         "true" if post_manually else "false"))
        body = json.dumps({"query": q}).encode()
        req = urllib.request.Request(f"{BASE}/api/graphql", data=body,
                                     method="POST")
        req.add_header("Authorization", f"Bearer {self.tok}")
        req.add_header("Content-Type", "application/json")
        if self.verbose:
            print(f"    [GraphQL] setAssignmentPostPolicy {assignment_id}")
        with urllib.request.urlopen(req, timeout=60) as r:
            d = json.loads(r.read().decode())
        res = (d.get("data") or {}).get("setAssignmentPostPolicy") or {}
        if res.get("errors"):
            sys.exit(f"setAssignmentPostPolicy {assignment_id}: {res['errors']}")
        return ((res.get("postPolicy") or {}).get("postManually"))

    def put(self, path, fields):
        return self._call("PUT", path, fields)[0]


def main():
    ap = argparse.ArgumentParser(
        description="Configure a Canvas gradebook (dry run unless --apply).")
    ap.add_argument("course", nargs="?", type=int, default=None)
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-e", "--equalize-homework", action="store_true",
                    help="set every engine-matched homework to 100 points "
                         "(refuses once any of them has a score)")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    args = ap.parse_args()
    if args.course is not None and args.course_id is None:
        args.course_id = args.course     # positional COURSE_ID
    global BASE
    cfg, BASE, tok = canvas_course.setup(args)
    load_plan(cfg)
    course = cfg.course_id
    api = API(tok, args.verbose)
    apply_ = args.apply
    tag = "APPLY" if apply_ else "dry run"

    total = round(sum(g["weight"] for g in GROUPS.values()), 6)
    if total != 100.0:
        sys.exit(f"group weights sum to {total}, not 100 -- refusing to run")

    print(f"course {course}  ({tag})")
    print(f"group weights sum to {total:.2f}\n")

    changes = 0

    # -- 0. refuse to touch a course that is still importing --------------
    migs = api.get_all(f"/courses/{course}/content_migrations")
    running = [m for m in migs if m.get("workflow_state") in ("running", "queued", "pre_processing")]
    if running:
        print("REFUSING: a content migration is still running:")
        for m in running:
            print(f"    id={m['id']} state={m['workflow_state']} started={m.get('started_at')}")
        print("\nAssignments are still arriving.  Groups created now would be")
        print("reshuffled by the import, and points possible must be settled")
        print("BEFORE any equalization.  Re-run when the migration reports")
        print("'completed'.")
        sys.exit(1)

    # -- 1. assignment groups ---------------------------------------------
    print("[1] assignment groups")
    existing = {g["name"]: g for g in api.get_all(f"/courses/{course}/assignment_groups")}

    # Canvas refuses a drop rule that is >= the number of assignments in the
    # group ("Drop rules cannot be higher than the number of assignments").
    # The Clickers group is EMPTY until PointSolutions uploads create its
    # assignments during the semester, so its drop_lowest:2 cannot be set yet.
    # Count first, and defer the rule rather than failing the whole run.
    all_assigns = api.get_all(f"/courses/{course}/assignments")
    per_group = {}
    for a in all_assigns:
        per_group[a.get("assignment_group_id")] = \
            per_group.get(a.get("assignment_group_id"), 0) + 1
    deferred = []
    for name, spec in GROUPS.items():
        want_w, want_drop = spec["weight"], spec.get("drop_lowest")
        g = existing.get(name)
        if g is None:
            print(f"    CREATE  {name:<30} weight={want_w}"
                  + (f" drop_lowest={want_drop}" if want_drop else ""))
            if apply_:
                f = {"name": name, "group_weight": want_w}
                if want_drop:
                    f["rules"] = f"drop_lowest:{want_drop}"
                api.post(f"/courses/{course}/assignment_groups", f)
            changes += 1
            continue
        have_w = float(g.get("group_weight") or 0)
        have_drop = (g.get("rules") or {}).get("drop_lowest")
        n_items = per_group.get(g["id"], 0)
        # Only touch `rules` when Canvas will accept it; a group with too few
        # assignments would 400 and abort the run.
        can_set_drop = (want_drop is None) or (n_items > want_drop)
        if want_drop and not can_set_drop:
            deferred.append((name, want_drop, n_items, have_drop))
        if have_w != want_w or (have_drop != want_drop and can_set_drop):
            note = ""
            if have_drop != want_drop and can_set_drop:
                note = f", drop_lowest {have_drop} -> {want_drop}"
            print(f"    UPDATE  {name:<30} weight {have_w} -> {want_w}{note}")
            if apply_:
                f = {"name": name, "group_weight": want_w}
                if can_set_drop:
                    f["rules"] = f"drop_lowest:{want_drop}" if want_drop else ""
                api.put(f"/courses/{course}/assignment_groups/{g['id']}", f)
            changes += 1
        else:
            print(f"    ok      {name:<30} weight={have_w}")

    if deferred:
        print("\n    DROP RULES DEFERRED -- Canvas rejects a drop rule that is not")
        print("    smaller than the group's assignment count:")
        for n, d, c, have in deferred:
            state = (f"already drop_lowest={have}" if have is not None
                     else "NO drop rule currently set")
            print(f"      {n}: wants drop_lowest={d}, has {c} assignment(s);"
                  f" {state}")
        print("    The rule could not be WRITTEN, which is not the same as it")
        print("    being absent -- a rule inherited from the import survives an")
        print("    empty group.  Re-run once those assignments exist (clicker")
        print("    sessions are created by the PointSolutions upload, during")
        print("    the semester) and check the state reported above.")

    unknown = [n for n in existing if n not in GROUPS]
    if unknown:
        print("\n    NOT IN THE PLAN -- these carry whatever weight they have:")
        for n in unknown:
            print(f"      {n!r} (weight={existing[n].get('group_weight')})")
        print("      Assign them a weight above or move their items, or they")
        print("      will be excluded from the total without warning.")

    # -- 1b. move exams out of the single `Exams` group -------------------
    print("\n[1b] exam placement")
    groups_now = {g["name"]: g for g in api.get_all(f"/courses/{course}/assignment_groups")}
    by_id = {g["id"]: n for n, g in groups_now.items()}
    assigns = api.get_all(f"/courses/{course}/assignments")
    landed = {}
    for a in assigns:
        target = next((t for pat, t in MOVE_RULES if re.match(pat, a["name"])), None)
        if not target:
            continue
        landed.setdefault(target, []).append(a["name"])
        here = by_id.get(a.get("assignment_group_id"))
        if here == target:
            continue
        gid = groups_now.get(target, {}).get("id")
        print(f"    MOVE    {a['name'][:50]:<50} {here} -> {target}")
        if apply_ and gid:
            api.put(f"/courses/{course}/assignments/{a['id']}",
                    {"assignment[assignment_group_id]": gid})
        changes += 1

    stranded = [a["name"] for a in assigns
                if UNMOVED_GROUP and by_id.get(a.get("assignment_group_id")) == UNMOVED_GROUP
                and not any(re.match(p, a["name"]) for p, _ in MOVE_RULES)]
    if stranded:
        print(f"\n    STRANDED in {UNMOVED_GROUP!r} -- matched no rule, so they would be")
        print("    excluded from the total without warning:")
        for n in stranded:
            print(f"      {n}")
    if landed:
        print("\n    REVIEW -- items now counting in each exam group.  Within a")
        print("    group Canvas combines by POINTS, so a Raw column sitting")
        print("    beside its Curved twin would be averaged in, not ignored:")
        for t in sorted(landed):
            for n in landed[t]:
                print(f"      {t:<22} <- {n}")
    elif not stranded:
        print("    no exam assignments present yet")

    # -- 1c. equalize homework points -------------------------------------
    # The engine treats the eleven homeworks as equal 0-100 scores.  Canvas
    # combines within a group by POINTS, so as imported (100 to 220) HW07 would
    # count 2.2x HW02.  Changing points possible AFTER grading does not rescale
    # scores already entered -- a 180/220 silently becomes 180/100 -- so this
    # is only safe while the column is empty.
    print("\n[1c] homework points")
    hw_re = engine_pattern("homework")
    hw = [a for a in assigns if re.search(hw_re, a["name"])] if hw_re else []
    off = [a for a in hw if (a.get("points_possible") or 0) != 100]
    if not hw:
        print(f"    no assignment matched the engine pattern {hw_re!r}")
    elif not off:
        print(f"    ok      all {len(hw)} homeworks already at 100 points")
    elif not args.equalize_homework:
        print(f"    {len(off)} of {len(hw)} homeworks are not 100 points:")
        for a in sorted(off, key=lambda z: z["name"]):
            print(f"      {a.get('points_possible'):>6} -> 100   {a['name'][:56]}")
        print("    NOT changed.  Pass --equalize-homework to rescale them.")
        print("    This window closes the moment any homework is graded.")
    else:
        scored = []
        for a in off:
            subs = api.get_all(f"/courses/{course}/assignments/{a['id']}/submissions")
            if any(s.get("score") is not None for s in subs):
                scored.append(a["name"])
        if scored:
            print("    REFUSING to rescale -- these already carry scores, and")
            print("    changing points possible would not rescale them:")
            for n in scored:
                print(f"      {n}")
        else:
            for a in sorted(off, key=lambda z: z["name"]):
                print(f"    RESCALE {a.get('points_possible'):>6} -> 100   {a['name'][:52]}")
                if apply_:
                    api.put(f"/courses/{course}/assignments/{a['id']}",
                            {"assignment[points_possible]": 100})
                changes += 1

    # -- 2. the master switch ---------------------------------------------
    print("\n[2] apply_assignment_group_weights")
    c = api.get(f"/courses/{course}")
    if not c.get("apply_assignment_group_weights"):
        print("    UPDATE  false -> true   (until this is on, weights are ignored")
        print("                             and Total is raw points/points)")
        if apply_:
            api.put(f"/courses/{course}", {"course[apply_assignment_group_weights]": "true"})
        changes += 1
    else:
        print("    ok      already true")

    # -- 3. grading standard ----------------------------------------------
    print(f"\n[3] grading standard  ({STANDARD_NAME}, literal syllabus cutoffs)")
    stds = api.get_all(f"/courses/{course}/grading_standards")
    std = next((s for s in stds if s.get("title") == STANDARD_NAME), None)
    if std is None:
        print("    CREATE  " + "  ".join(f"{n}>={v}" for n, v in CUTOFFS[:6]) + " ...")
        if apply_:
            # Canvas wants REPEATED `grading_scheme_entry[][name]` /
            # `[][value]` pairs, matched up by position -- indexed keys like
            # `grading_scheme_entry[0][name]` return a 500, not a 400, so the
            # error does not tell you what is wrong.  A list of 2-tuples keeps
            # the interleaving that pairing depends on.
            f = [("title", STANDARD_NAME)]
            for n, v in CUTOFFS:
                f.append(("grading_scheme_entry[][name]", n))
                f.append(("grading_scheme_entry[][value]", v))
            std = api.post(f"/courses/{course}/grading_standards", f)
        changes += 1
    else:
        print(f"    ok      exists (id={std['id']})")

    if std and (not c.get("grading_standard_id") or c.get("grading_standard_id") != std.get("id")):
        print(f"    UPDATE  attach standard to course, enable letter grades")
        if apply_:
            api.put(f"/courses/{course}", {
                "course[grading_standard_id]": std["id"],
                "course[grading_standard_enabled]": "true"})
        changes += 1
    elif std:
        print("    ok      already attached")

    # -- 4. per-assignment flags ------------------------------------------
    print("\n[4] assignments: posting policy and omit_from_final_grade")
    assigns = api.get_all(f"/courses/{course}/assignments")
    n_post = n_omit = 0
    for a in assigns:
        name = a["name"]
        should_omit = any(p.lower() in name.lower() for p in OMIT_PATTERNS)
        fields = {}
        if should_omit and not a.get("omit_from_final_grade"):
            fields["assignment[omit_from_final_grade]"] = "true"
            print(f"    OMIT    {name[:62]}")
            n_omit += 1
        # A manually-posted grade is invisible to the student AND excluded from
        # the total they see -- so the instructor reads a total the student
        # cannot.  That defeats the entire point of weighting the gradebook.
        show = any(p.lower() in name.lower() for p in SHOW_STUDENTS)
        want_auto = a.get("post_manually") and (not should_omit or show)
        if fields and apply_:
            api.put(f"/courses/{course}/assignments/{a['id']}", fields)
        if want_auto:
            n_post += 1
            if apply_:
                api.set_post_policy(a["id"], False)
        changes += bool(fields) or bool(want_auto)
    print(f"    {len(assigns)} assignments: {n_post} switched to automatic posting,"
          f" {n_omit} marked omit_from_final_grade")

    # Anything sitting in a group with no planned weight contributes nothing.
    zero_named = {n for n, s in GROUPS.items() if s["weight"] == 0.0}
    dark = [a["name"] for a in assigns
            if by_id.get(a.get("assignment_group_id")) not in GROUPS
            or by_id.get(a.get("assignment_group_id")) in zero_named]
    dark = [n for n in dark if not any(p.lower() in n.lower() for p in OMIT_PATTERNS)]
    if dark:
        print(f"\n    {len(dark)} assignment(s) in a zero-weight or unplanned group;")
        print("    they will not affect any student's total:")
        for n in sorted(dark)[:15]:
            print(f"      {n[:70]}")
        if len(dark) > 15:
            print(f"      ... and {len(dark) - 15} more")

    # -- 5. reconcile Canvas groups against the grade engine ---------------
    # A category that Canvas and the engine populate differently produces a
    # running total that disagrees with the final grade all semester, and
    # nothing reports it: both sides look internally consistent.
    print("\n[5] Canvas group membership vs. the grade engine")
    fresh = {g["id"]: g["name"]
             for g in api.get_all(f"/courses/{course}/assignment_groups")}
    for key, group in ENGINE_GROUPS.items():
        pat = engine_pattern(key)
        if not pat:
            continue
        in_group = {a["name"] for a in assigns
                    if fresh.get(a.get("assignment_group_id")) == group
                    and not any(p.lower() in a["name"].lower() for p in OMIT_PATTERNS)}
        matched = {a["name"] for a in assigns if re.search(pat, a["name"])}
        only_canvas = sorted(in_group - matched)
        only_engine = sorted(matched - in_group)
        if not only_canvas and not only_engine:
            print(f"    ok      {group}: {len(in_group)} items, both sides agree")
            continue
        print(f"    MISMATCH {group}: Canvas counts {len(in_group)},"
              f" the engine counts {len(matched)}")
        for n in only_canvas:
            print(f"      Canvas only  {n[:64]}")
            print(f"                   (fails engine pattern {pat!r})")
        for n in only_engine:
            print(f"      engine only  {n[:64]}")
        print("      Move it out of the group, mark it omit_from_final_grade,")
        print("      or rename it so both sides see the same set.")

    print(f"\n{changes} change(s) {'applied' if apply_ else 'pending -- re-run with --apply'}")
    if not apply_:
        print("\nNothing was written.")


if __name__ == "__main__":
    main()
