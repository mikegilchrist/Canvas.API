#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.exam.pdfs.repair.py
# Version:      1.2.0
# Created:      2026-08-28
# Revised:      2026-10-13
# Purpose:      Restore the prior-year exam PDFs the F.2026 Canvas course
#               links to but does not contain, and repoint the links that
#               never resolved.
#
# The "Exam Materials" module is PUBLISHED and so are all thirteen pages in
# it, so every one of these was a dead link a student could click.  Two
# distinct failures were found on 2026-08-28:
#
#   1. Twelve links carried a /files/<id> whose file 404s -- every 2024 and
#      every 2025 exam.  The 2016, 2018 and 2023 files survived, so the
#      course copy that built this shell dropped only the newest batch.
#      These need the PDF uploaded and the id rewritten.
#
#   2. Three links on the 2018/2016 final page use the legacy Blackboard-era
#      /file_contents/course%20files/Exams/<name> form, which Canvas does not
#      resolve at all.  Those three files need NO upload: the content is
#      already in the course under its uncorrected-looking name.  Verified by
#      md5 -- Canvas's final.16.pdf and final.16.key.pdf are byte-identical
#      to Sp.2016's corrected pair, and Canvas's final.18.key.pdf is the
#      15-page corrected key, not the 14-page as-given one.  So these are
#      repointed at the existing ids rather than duplicated.
#
# The link TEXT is left alone in case 2.  It names what the document is (the
# corrected 2016 final) and that is still true; only the target was wrong.
#
# Sources are named one by one below.  They are never taken from a directory
# scan -- the exam folders hold keys, 2x1 instructor n-ups, as-given variants
# and scans of student work, and a sweep would eventually publish one.
#
# Usage:        canvas.api.exam.pdfs.repair.py [--course-id N] [--course-config FILE] [--apply] [-v]
# Input:        canvas.course.json (folders.exams, paths.course_root, exam_pdfs_repair);
#               Canvas API token
# Options:      -a/--apply   perform the writes (default is a DRY RUN)
#               -v/--verbose show each link rewrite
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import json
import mimetypes
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http      # noqa: E402
import canvas_course    # noqa: E402

VERSION = "1.2.0"

BASE = COURSE = None        # set in main() from canvas.course.json
EXAMS_FOLDER = None         # course files/Exams (folders.exams)
ROOT = None                 # paths.course_root

# The page/file lists are course-specific data in canvas.course.json under
# "exam_pdfs_repair" (read in main()):
#   uploads   [dead id, page slug, source relative to ROOT]  (case 1: dead
#             /files/<id>, PDF must be uploaded; the uploaded name is the
#             source's own basename, which matches the link text on the page)
#   final_page, repoints  [name, id]  (case 2: legacy /file_contents/ link ->
#             an id already in the course; ids verified identical by md5)
UPLOADS = []
FINAL_PAGE = ""
REPOINTS = []


def get_page(tok, slug):
    d, _ = canvas_http.http_get_json(
        f"{BASE}/api/v1/courses/{COURSE}/pages/{slug}", tok)
    return d


def file_live(tok, fid):
    """True if the id resolves.  A link that renders is not evidence of this."""
    try:
        canvas_http.http_get_json(
            f"{BASE}/api/v1/courses/{COURSE}/files/{fid}", tok)
        return True
    except Exception:
        return False


def upload(tok, path):
    """Upload one PDF into course files/Exams, visible to students."""
    data = path.read_bytes()
    ctype = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    init, _ = canvas_http.http_post_json(
        f"{BASE}/api/v1/courses/{COURSE}/files", tok,
        {"name": path.name, "size": len(data), "content_type": ctype,
         "on_duplicate": "overwrite", "parent_folder_id": EXAMS_FOLDER})
    body, hdrs = canvas_http.http_post_multipart_no_auth(
        init["upload_url"], init.get("upload_params", {}),
        {"file": (path.name, data, ctype)})
    f = json.loads(body) if body else None
    if not f or "id" not in f:
        loc = dict(hdrs or {}).get("Location")
        r = canvas_http.http_get_json(loc, tok)
        f = r[0] if isinstance(r, tuple) else r
    # match the 2016/2018/2023 exams already in the folder: visible, unlocked
    canvas_http.http_put_json(f"{BASE}/api/v1/files/{f['id']}", tok,
                              {"locked": False, "hidden": False})
    return f


def swap_id(body, old, new):
    """Repoint one file id, dropping the stale ?verifier= while we are here.

    A verifier is minted for a particular file; carrying the old one over to
    a new id yields a link that 401s instead of one that 404s.
    """
    body = re.sub(r"/files/%d\?[^\"']*" % old, f"/files/{new}?wrap=1", body)
    return body.replace(f"/files/{old}", f"/files/{new}")


def relink_legacy(body, name, fid):
    """Replace a /file_contents/... href with the modern /files/<id> form."""
    pat = re.compile(
        r'href="[^"]*file_contents/[^"]*' + re.escape(name) + r'[^"]*"')
    if not pat.search(body):
        return body, False
    href = (f'href="{BASE}/courses/{COURSE}/files/{fid}?wrap=1" '
            f'data-api-endpoint="{BASE}/api/v1/courses/{COURSE}/files/{fid}" '
            f'data-api-returntype="File"')
    return pat.sub(href, body, count=1), True


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-a", "--apply", action="store_true",
                    help="perform the writes (default is a dry run)")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--version", action="version", version=VERSION)
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    global BASE, COURSE, EXAMS_FOLDER, ROOT, UPLOADS, FINAL_PAGE, REPOINTS
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    try:
        EXAMS_FOLDER = cfg.folder_id("exams")
        ROOT = pathlib.Path(cfg.path("course_root"))
    except canvas_course.CourseConfigError as e:
        sys.exit(f"[FAIL] {e}")
    rp = cfg.data.get("exam_pdfs_repair")
    if not rp:
        sys.exit(f"[FAIL] no exam_pdfs_repair in {cfg.source or 'course config'}")
    UPLOADS = [(int(o), s, src) for o, s, src in rp["uploads"]]
    FINAL_PAGE = rp["final_page"]
    REPOINTS = [(n, int(i)) for n, i in rp["repoints"]]
    dry = "" if a.apply else "  [DRY RUN]"

    print(f"canvas.api.exam.pdfs.repair.py {VERSION}{dry}")
    print(f"course {COURSE}, uploads land in course files/Exams "
          f"(folder {EXAMS_FOLDER}), visible to students\n")

    # ---- 1. check every source exists before touching Canvas --------------
    missing = [s for _, _, s in UPLOADS if not (ROOT / s).is_file()]
    if missing:
        print("REFUSING -- source PDFs not found:")
        for m in missing:
            print("   ", m)
        return 1

    # ---- 2. read the pages FIRST -----------------------------------------
    # Idempotency keys on the PAGE, not on the dead id.  A dead id stays dead
    # for ever, so "is the old file gone?" is true on every future run and a
    # second --apply would upload twelve duplicates.  "Does the page still
    # point at it?" goes false as soon as the repair lands.
    pages = {slug: None for _old, slug, _src in UPLOADS}
    pages[FINAL_PAGE] = None
    for slug in pages:
        pages[slug] = get_page(tok, slug)["body"] or ""

    # ---- 3. upload and repoint -------------------------------------------
    changed = {}
    for old, slug, src in UPLOADS:
        path = ROOT / src
        size = path.stat().st_size
        if f"/files/{old}" not in pages[slug]:
            print(f"  {path.name:42s} already repaired -- page no longer "
                  f"references {old}")
            continue
        if file_live(tok, old):
            print(f"  file {old} is LIVE -- skipping {path.name}")
            continue
        if not a.apply:
            print(f"  would upload {path.name:42s} {size:>9,} B  "
                  f"from {src}  (replaces dead {old})")
            continue
        f = upload(tok, path)
        pages[slug] = swap_id(pages[slug], old, f["id"])
        changed[slug] = True
        print(f"  uploaded {path.name:42s} {size:>9,} B  "
              f"{old} -> {f['id']}")

    body = pages[FINAL_PAGE]
    for name, fid in REPOINTS:
        if not file_live(tok, fid):
            print(f"  REFUSING repoint of {name}: target {fid} is not live")
            return 1
        body, hit = relink_legacy(body, name, fid)
        if hit:
            print(f"  {'legacy' if a.apply else 'would repoint legacy'} "
                  f"{name:30s} -> file {fid}")
        else:
            print(f"  legacy link {name} not found (already fixed?)")
    if body != pages[FINAL_PAGE]:
        pages[FINAL_PAGE], changed[FINAL_PAGE] = body, True

    if a.apply:
        for slug in changed:
            canvas_http.http_put_json(
                f"{BASE}/api/v1/courses/{COURSE}/pages/{slug}", tok,
                {"wiki_page": {"body": pages[slug]}})
            print(f"  wrote page {slug[:60]}")
    print("\nDone." if a.apply else "\nDry run -- nothing written. "
          "Re-run with --apply.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
