#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.syllabus.publish.py
# Version:      1.1.0
# Created:      2026-08-19
# Revised:      2026-10-13
# Purpose:      Publish a new syllabus/schedule version to Canvas: upload the
#               PDFs, repoint the Syllabus page, and refresh the L01 handout
#               link -- retiring the superseded version rather than deleting.
#
# The syllabus is revised several times a semester and every revision touches
# the same four places.  Doing it by hand is how the L01 page ended up still
# advertising v-0.8 after the Syllabus page had moved on.
#
# WHAT IT DOES NOT DO: it never deletes the old PDF.  The superseded link is
# MOVED under the Syllabus page's "Previous versions" heading, because a
# student who downloaded the old one needs to be able to see what changed.
#
# The uploaded file keeps its versioned filename, so "which one am I reading"
# is answerable from the filename alone and matches the stamp on page 1.
#
# Usage:  canvas.api.syllabus.publish.py --version 1.0 [--announcement URL]
#                                    [--folder NAME] [--apply] [-v]
#                                    [--course-id ID] [--course-config FILE] [--year YYYY]
#
# Input:   <paths.syllabus_dir>/syllabus.and.schedule_<year>_v-<V>.pdf
#          <paths.syllabus_dir>/schedule_<year>_v-<V>.pdf
#          (syllabus_dir, pages.l01 come from canvas.course.json)
#          Canvas token (see canvas_course.py)
# Output:  Stdout: one line per action; a diff of the Syllabus page body
#
# Options:
#   --version V        Version to publish, e.g. 1.0 (required)
#   --announcement URL Canvas announcement to link from the L01 page
#   --folder NAME      Canvas Files folder (default: "Syllabus & Schedule")
#   --page URL         L01 page url-slug to update (default: pages.l01
#                      in canvas.course.json)
#   --course-id ID, --course-config FILE, --year YYYY  course selection
#   -a, --apply        Perform the writes (default is a DRY RUN)
#   -v, --verbose      Show the full before/after page bodies
#   -h, --help         Show this help message
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import html
import json
import mimetypes
import os
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
CUR_H = "Current Course Syllabus &amp; Schedule"
PREV_H = "Previous versions"


def upload(tok, path, folder):
    """Upload one file, unlocked and visible, into `folder`."""
    data = path.read_bytes()
    ctype = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    init, _ = canvas_http.http_post_json(
        f"{BASE}/api/v1/courses/{COURSE}/files", tok,
        {"name": path.name, "size": len(data), "content_type": ctype,
         "parent_folder_path": folder, "on_duplicate": "overwrite"})
    body, hdrs = canvas_http.http_post_multipart_no_auth(
        init["upload_url"], init.get("upload_params", {}),
        {"file": (path.name, data, ctype)})
    f = json.loads(body) if body else None
    if not f or "id" not in f:
        loc = dict(hdrs or {}).get("Location")
        r = canvas_http.http_get_json(loc, tok)
        f = r[0] if isinstance(r, tuple) else r
    canvas_http.http_put_json(f"{BASE}/api/v1/files/{f['id']}", tok,
                              {"locked": False, "hidden": False})
    return f


def flink(fid, name):
    """A Canvas file link in the form the RCE itself produces."""
    n = html.escape(name)
    return (f'<a class="instructure_file_link instructure_scribd_file '
            f'inline_disabled" title="{n}" '
            f'href="{BASE}/courses/{COURSE}/files/{fid}?wrap=1" '
            f'target="_blank" '
            f'data-api-endpoint="{BASE}/api/v1/courses/{COURSE}/files/{fid}" '
            f'data-api-returntype="File">{n}</a>')


def section(body, heading):
    """(start, end) of the content between <h2>heading</h2> and the next <h2>."""
    m = re.search(rf"<h2[^>]*>\s*{re.escape(heading)}\s*</h2>(.*?)(?=<h2|$)",
                  body, re.S)
    return m


def main():
    global BASE, COURSE
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True)
    ap.add_argument("--announcement")
    ap.add_argument("--folder", default="Syllabus & Schedule")
    ap.add_argument("--page", default=None,
                    help="L01 page url-slug (default: pages.l01 in canvas.course.json)")
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    try:
        syldir = cfg.path("syllabus_dir")
    except canvas_course.CourseConfigError as e:
        sys.exit(f"[FAIL] {e}")
    if a.page is None:
        a.page = cfg.data.get("pages", {}).get("l01")
        if not a.page:
            sys.exit("[FAIL] no --page given and no pages.l01 in "
                     f"{cfg.source or 'canvas.course.json'}")

    combined = pathlib.Path(syldir, f"syllabus.and.schedule_{cfg.year}_v-{a.version}.pdf")
    schedule = pathlib.Path(syldir, f"schedule_{cfg.year}_v-{a.version}.pdf")
    for p in (combined, schedule):
        if not p.is_file():
            sys.exit(f"no such file: {p}")

    # ---- read current state -------------------------------------------------
    course, _ = canvas_http.http_get_json(
        f"{BASE}/api/v1/courses/{COURSE}?include[]=syllabus_body", tok)
    sbody = course.get("syllabus_body") or ""
    page, _ = canvas_http.http_get_json(
        f"{BASE}/api/v1/courses/{COURSE}/pages/{a.page}", tok)
    pbody = page.get("body") or ""

    cur = section(sbody, CUR_H)
    prev = section(sbody, PREV_H)
    if not cur or not prev:
        sys.exit("Syllabus page is not in the expected "
                 f"'{CUR_H}' / '{PREV_H}' form; refusing to guess")
    superseded = cur.group(1).strip()
    old_names = re.findall(r"syllabus\.and\.schedule[^\"<]*\.pdf", superseded)
    print(f"  currently posted: {old_names[0] if old_names else '(none)'}")
    if f"v-{a.version}.pdf" in superseded:
        sys.exit(f"v-{a.version} is already the posted version; nothing to do")

    hm = section(pbody, "Handout")
    if not hm:
        sys.exit(f"page {a.page!r} has no 'Handout' section")

    print(f"  {tag}UPLOAD  {combined.name} ({combined.stat().st_size:,} B) "
          f"-> Files/{a.folder}")
    print(f"  {tag}UPLOAD  {schedule.name} ({schedule.stat().st_size:,} B) "
          f"-> Files/{a.folder}")
    print(f"  {tag}SYLLABUS PAGE: '{CUR_H}' -> v-{a.version}; "
          f"move superseded link under '{PREV_H}'")
    print(f"  {tag}L01 PAGE '{page['title']}': Handout -> v-{a.version}")
    if a.announcement:
        print(f"  {tag}L01 PAGE: add announcement link {a.announcement}")
    if not a.apply:
        print("\n  dry run -- nothing written.  Re-run with --apply")
        return 0

    # ---- writes -------------------------------------------------------------
    fc = upload(tok, combined, a.folder)
    fs = upload(tok, schedule, a.folder)
    print(f"  uploaded: combined id={fc['id']}  schedule id={fs['id']}")

    new_cur = (f"\n<p>{flink(fc['id'], combined.name)}</p>\n"
               f"<p>{flink(fs['id'], schedule.name)} "
               f"(schedule only, one page)</p>\n")
    # PREPEND, never replace: this heading is the archive, and every version
    # retired before this one has to survive the write.  Newest first.
    new_prev = (f"\n<p>{superseded}</p>\n" + prev.group(1).lstrip("\n")
                if superseded else prev.group(1))
    # Rebuild back-to-front so the earlier span offsets stay valid.
    out = (sbody[:prev.start(1)] + new_prev + sbody[prev.end(1):])
    out = (out[:cur.start(1)] + new_cur + out[cur.end(1):])
    canvas_http.http_put_json(f"{BASE}/api/v1/courses/{COURSE}", tok,
                              {"course": {"syllabus_body": out}})
    print("  syllabus page updated")

    hnew = f"\n<p>{flink(fc['id'], combined.name)}</p>\n"
    if a.announcement:
        hnew += (f'<p><a href="{html.escape(a.announcement)}">'
                 f'What changed in v{a.version}</a></p>\n')
    npbody = pbody[:hm.start(1)] + hnew + pbody[hm.end(1):]
    canvas_http.http_put_json(
        f"{BASE}/api/v1/courses/{COURSE}/pages/{a.page}", tok,
        {"wiki_page": {"body": npbody}})
    print(f"  L01 page updated")
    if a.verbose:
        print("\n---- syllabus_body ----\n" + out)
        print("\n---- L01 body ----\n" + npbody)
    return 0


if __name__ == "__main__":
    sys.exit(main())
