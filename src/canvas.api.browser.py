def ensure_profile(path):
    os.makedirs(path, mode=0o700, exist_ok=True)
    try:
        os.chmod(path, 0o700)
    except OSError:
        pass
    return path


def launch(profile, headless):
    from playwright.sync_api import sync_playwright
    pw = sync_playwright().start()
    ctx = pw.chromium.launch_persistent_context(
        ensure_profile(profile),
        headless=headless,
        viewport={"width": 1440, "height": 900},
        args=["--disable-blink-features=AutomationControlled"],
    )
    return pw, ctx


def state_path(profile):
    return os.path.join(profile, "state.json")


def save_state(ctx, profile):
    """Persist the login.

    A persistent profile directory is NOT enough on its own: Canvas issues
    `canvas_session` and `_normandy_session` as session cookies, which
    Chromium drops when the browser closes.  storage_state() serialises them
    anyway, so it is what actually carries the login between runs.
    """
    ctx.storage_state(path=state_path(profile))
    try:
        os.chmod(state_path(profile), 0o600)
    except OSError:
        pass


def restore_state(ctx, profile, verbose=False):
    p = state_path(profile)
    if not os.path.isfile(p):
        return False
    try:
        with open(p) as fh:
            cookies = json.load(fh).get("cookies") or []
        if cookies:
            ctx.add_cookies(cookies)
        if verbose:
            print(f"  restored {len(cookies)} cookies from {p}")
        return True
    except Exception as exc:
        print(f"warning: could not restore {p}: {exc}", file=sys.stderr)
        return False


def wait_for_login(ctx, base, timeout, verbose=False):
    """Poll until the browser is authenticated, or give up."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        time.sleep(3)
        who = whoami(ctx, base)
        if who:
            return who
    return None


def authenticate(ctx, base, profile, headless, timeout, verbose=False):
    """Get to an authenticated context, re-prompting if the session died.

    Canvas sessions expire, so 'run login again' would be a recurring chore.
    Headed runs just ask; headless runs cannot, and say so.
    """
    restore_state(ctx, profile, verbose)
    who = whoami(ctx, base)
    if who:
        return who
    if headless:
        raise BrowserError(
            "saved session is not authenticated, and --headless cannot "
            "prompt.  Run 'login' first.")
    page = ctx.pages[0] if ctx.pages else ctx.new_page()
    page.goto(base, wait_until="domcontentloaded")
    if whoami(ctx, base):
        save_state(ctx, profile)
        return whoami(ctx, base)
    print(f"session expired -- sign in again in the open window "
          f"(waiting up to {timeout}s) ...")
    who = wait_for_login(ctx, base, timeout)
    if not who:
        raise BrowserError("timed out waiting for sign-in")
    save_state(ctx, profile)
    return who


def whoami(ctx, base):
    """The signed-in user, via a same-origin API call that rides the cookies.

    Returns None when the session is dead, which is the only reliable signal
    -- Canvas answers an unauthenticated page request with a login redirect
    rather than an error.
    """
    try:
        r = ctx.request.get(f"{base}/api/v1/users/self", timeout=20000)
        if not r.ok:
            return None
        d = r.json()
        return d if isinstance(d, dict) and d.get("id") else None
    except Exception:
        return None


def stamp():
    return datetime.datetime.now().strftime("%Y-%m-%dT%H%M%S")


def capture(page, outdir, label, verbose=False):
    """Screenshot plus the text of the page and of every Roll Call frame."""
    os.makedirs(outdir, exist_ok=True)
    base = os.path.join(outdir, f"{stamp()}_{label}")
    png, txt = f"{base}.png", f"{base}.txt"
    page.screenshot(path=png, full_page=True)

    parts = [f"url: {page.url}", f"title: {page.title()}", ""]
    for fr in page.frames:
        try:
            body = fr.locator("body").inner_text(timeout=5000)
        except Exception as exc:
            body = f"<could not read: {type(exc).__name__}>"
        tag = "PAGE" if fr is page.main_frame else f"FRAME {fr.url}"
        parts += [f"--- {tag} ---", body, ""]
    with open(txt, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    if verbose:
        print(f"  captured {png}")
        print(f"           {txt}")
    return png, txt


