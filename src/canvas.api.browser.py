def parse_args(argv=None):
    ap = argparse.ArgumentParser(
        description="Drive Canvas in a real browser for what the REST API "
                    "cannot reach.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="Commands:\n"
               "  login                 sign in by hand once; the session is "
               "reused afterwards\n"
               "  status                is the saved session still good?\n"
               "  rollcall COURSE_ID    launch Attendance and report what it "
               "created\n"
               "  open URL              navigate, screenshot, dump text\n\n"
               "  canvas.api.browser.py login\n"
               "  canvas.api.browser.py rollcall 261062\n"
               "  canvas.api.browser.py open /courses/261062/assignments\n")
    ap.add_argument("command", choices=sorted(COMMANDS))
    ap.add_argument("arg", nargs="?", help="COURSE_ID or URL, per the command")
    ap.add_argument("-o", "--outdir", default=os.path.join(REPO, "output"),
                    help="where screenshots and dumps go")
    ap.add_argument("--profile", default=DEFAULT_PROFILE,
                    help="browser profile directory")
    ap.add_argument("--base-url", help="Canvas base URL")
    ap.add_argument("--token-file", help="Canvas API token file")
    ap.add_argument("--headless", action="store_true",
                    help="no visible window (login is always headed)")
    ap.add_argument("--timeout", type=int, default=300,
                    help="seconds to wait for a manual login")
    ap.add_argument("--no-diff", action="store_true",
                    help="skip the before/after assignment comparison")
    ap.add_argument("--settings", action="store_true",
                    help="rollcall: also open and capture the tool's settings "
                         "panel, where the Late percentage lives")
    ap.add_argument("-n", "--dry-run", action="store_true",
                    help="report what would happen, touch nothing")
    ap.add_argument("-v", "--verbose", action="store_true")
    return ap.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    base, token_file = resolve(args)
    if args.verbose:
        print(f"base    {base}")
        print(f"profile {args.profile}")
        print(f"outdir  {args.outdir}")
    return COMMANDS[args.command](args, base, token_file)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except BrowserError as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(1)
    except KeyboardInterrupt:
        sys.exit(130)
