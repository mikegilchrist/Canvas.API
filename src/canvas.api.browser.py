def cmd_login(args, base, token_file):
    if args.dry_run:
        print(f"would open {base} headed and wait up to {args.timeout}s "
              f"for you to sign in; profile {args.profile}")
        return 0
    pw, ctx = launch(args.profile, headless=False)
    try:
        restore_state(ctx, args.profile, args.verbose)
        page = ctx.pages[0] if ctx.pages else ctx.new_page()
        page.goto(base, wait_until="domcontentloaded")
        who = whoami(ctx, base)
        if who:
            save_state(ctx, args.profile)
            print(f"already signed in as {who.get('name')}")
            return 0
        print(f"Sign in to Canvas in the window that just opened "
              f"(SSO + Duo).\nWaiting up to {args.timeout}s ...")
        who = wait_for_login(ctx, base, args.timeout)
        if not who:
            print("timed out waiting for sign-in", file=sys.stderr)
            return 1
        save_state(ctx, args.profile)
        print(f"signed in as {who.get('name')}")
        print(f"session saved in {state_path(args.profile)}")
        return 0
    finally:
        ctx.close()
        pw.stop()


def cmd_status(args, base, token_file):
    if args.dry_run:
        print(f"would check the saved session in {args.profile} against {base}")
        return 0
    if not os.path.isdir(args.profile):
        print(f"no saved session at {args.profile}; run 'login' first")
        return 1
    pw, ctx = launch(args.profile, headless=True)
    try:
        restore_state(ctx, args.profile, args.verbose)
        who = whoami(ctx, base)
        if who:
            print(f"signed in as {who.get('name')}")
            return 0
        print("saved session is not authenticated; run 'login'")
        return 1
    finally:
        ctx.close()
        pw.stop()


def cmd_rollcall(args, base, token_file):
    course = args.arg
    if not course:
        raise BrowserError("rollcall needs a COURSE_ID")
    url = f"{base}/courses/{course}/external_tools/{ATTENDANCE_TOOL_ID}"

    if args.dry_run:
        print(f"would open {url}\n"
              f"  Launching is non-mutating: Roll Call creates its gradebook "
              f"assignment on the first MARK, not on launch (verified "
              f"2026-08-11, course 261062).")
        return 0

    token = read_token(token_file)
    before = {}
    if token and not args.no_diff:
        before = assignment_snapshot(base, token, course)
        print(f"{len(before)} assignments before launch")
    elif not args.no_diff:
        print(f"no API token at {token_file}; skipping the assignment diff",
              file=sys.stderr)

    pw, ctx = launch(args.profile, headless=args.headless)
    try:
        who = authenticate(ctx, base, args.profile, args.headless,
                           args.timeout, args.verbose)
        print(f"signed in as {who.get('name')}")
        page = ctx.pages[0] if ctx.pages else ctx.new_page()
        print(f"opening {url}")
        page.goto(url, wait_until="domcontentloaded", timeout=60000)

        # The tool renders in an iframe; give it time to hand off.
        found = False
        for _ in range(20):
            if any(ROLLCALL_HOST in f.url for f in page.frames):
                found = True
                break
            page.wait_for_timeout(1000)
        page.wait_for_timeout(3000)
        if found:
            print(f"Roll Call frame loaded")
        else:
            print(f"WARNING: no {ROLLCALL_HOST} frame appeared -- the capture "
                  f"below will show what did", file=sys.stderr)

        png, txt = capture(page, args.outdir, f"rollcall_{course}",
                           args.verbose)
        print(f"screenshot {png}")
        print(f"text       {txt}")

        if args.settings and found:
            # The Late percentage lives only in the tool's own settings
            # panel; there is no API for it.
            # Two clicks, not one: the gear opens a menu whose items
            # ("Roll Call Settings", "Attendance Report") are not clickable
            # until it is open.
            fr = next(f for f in page.frames if ROLLCALL_HOST in f.url)
            for label in ("Settings", "Roll Call Settings"):
                try:
                    fr.get_by_text(label, exact=True).first.click(timeout=5000)
                    page.wait_for_timeout(2500)
                except Exception as exc:
                    print(f"could not click {label!r}: {type(exc).__name__}",
                          file=sys.stderr)
            spng, stxt = capture(page, args.outdir,
                                 f"rollcall_{course}_settings", args.verbose)
            print(f"settings   {spng}")
            print(f"           {stxt}")
    finally:
        ctx.close()
        pw.stop()

    if token and not args.no_diff:
        after = assignment_snapshot(base, token, course)
        created, removed, changed = diff_assignments(before, after)
        print(f"\n{len(after)} assignments after launch")
        if not (created or removed or changed):
            print("  no assignment was created or changed by the launch")
        for i, a in created:
            print(f"  CREATED {i}  {a['name']!r}  {a['points']} pts  "
                  f"group {a['group']}  {a['types']}")
        for i, a in removed:
            print(f"  REMOVED {i}  {a['name']!r}")
        for i, name, fields in changed:
            print(f"  CHANGED {i}  {name!r}")
            for k, (b, a) in fields.items():
                print(f"            {k}: {b!r} -> {a!r}")
    return 0


def cmd_open(args, base, token_file):
    target = args.arg
    if not target:
        raise BrowserError("open needs a URL")
    if "://" not in target:
        target = f"{base}/{target.lstrip('/')}"
    if args.dry_run:
        print(f"would open {target}")
        return 0
    pw, ctx = launch(args.profile, headless=args.headless)
    try:
        authenticate(ctx, base, args.profile, args.headless, args.timeout,
                     args.verbose)
        page = ctx.pages[0] if ctx.pages else ctx.new_page()
        page.goto(target, wait_until="domcontentloaded", timeout=60000)
        page.wait_for_timeout(2000)
        png, txt = capture(page, args.outdir, "page", args.verbose)
        print(f"screenshot {png}")
        print(f"text       {txt}")
        return 0
    finally:
        ctx.close()
        pw.stop()


COMMANDS = {"login": cmd_login, "status": cmd_status,
            "rollcall": cmd_rollcall, "open": cmd_open}


# ---------------------------------------------------------------------------
# CLI
