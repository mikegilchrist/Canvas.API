#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.browser.py
# Version:      1.1.0
# Date:         2026-08-11
# Purpose:      Drive Canvas in a real browser for the things the REST API
#               cannot reach -- LTI tools such as Roll Call (Attendance),
#               whose state lives in the tool's own service and is only
#               visible once the tool has been launched from inside Canvas.
#
# Authentication is the whole difficulty. UTK sits behind SSO + Duo, which
# cannot be scripted and should not be. So this keeps a DEDICATED Playwright
# browser profile at ~/.canvas_browser/: you log in by hand once, headed, and
# every later run reuses it.
#
# The profile DIRECTORY alone is not enough, and assuming it was cost a run:
# Canvas issues `canvas_session` and `_normandy_session` as session cookies,
# which Chromium discards when the browser closes, so a saved profile comes
# back with fourteen cookies and none of them from Canvas. The login is
# actually carried by `state.json` inside the profile, written with
# storage_state(), which serialises session cookies too.
#
# Sessions still expire. Rather than fail with "run login first", a headed
# command re-prompts in the window it already has open and re-saves. Headless
# cannot prompt, so it says so.
#
# The profile is a credential store. It is outside every repository, mode
# 0700, and must never be committed or synced.
#
# This does not replace the API scripts. Anything the REST API can answer
# should be asked of the REST API -- it is faster, scriptable, and does not
# depend on a session. Reach for this only for LTI tools and UI-only settings.
#
# Usage:        canvas.api.browser.py [OPTIONS] COMMAND [ARGS]
#
# Commands:
#   login                 Open headed and wait for you to finish SSO, then
#                         verify and save the session
#   status                Report whether the saved session still authenticates
#   rollcall COURSE_ID    Launch the Attendance (Roll Call) tool in a course,
#                         dump what it shows, and report every assignment the
#                         launch created or changed
#   open URL              Navigate, screenshot, and dump the page text
#
# Input:        ~/.canvas.api.conf for base_url and token_file
#               ~/.canvas_browser/ for the saved browser session
# Output:       Screenshots and text dumps under --outdir
#
# Options:
#   -o, --outdir DIR      Where to write screenshots and dumps
#                         (default: <repo>/output)
#       --profile DIR     Browser profile directory
#                         (default: ~/.canvas_browser)
#       --base-url URL    Canvas base URL (default: from ~/.canvas.api.conf)
#       --token-file FILE Canvas API token, for the assignment diff
#       --headless        Run without a visible window; login never does
#       --timeout SECS    How long to wait for a manual login (default 300)
#       --no-diff         Skip the before/after assignment comparison
#       --settings        rollcall: also capture the tool's settings panel
#   -n, --dry-run         Report what would happen, touch nothing
#   -v, --verbose         Detailed progress
#   -h, --help            Show this help message
#
# Requirements:
#   - python3, playwright  (pip install playwright)
#   - playwright install chromium  +  playwright install-deps chromium
#
# Session:      Claude Code session (Roll Call and the recitation penalty)
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import datetime
import json
import os
import sys
import time
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)

DEFAULT_PROFILE = os.path.expanduser("~/.canvas_browser")
ROLLCALL_HOST = "rollcall.instructure.com"

# The Attendance tool is installed at the account level; in a course it is
# reached as an external tool by id.  3 is UTK's.
ATTENDANCE_TOOL_ID = 3


class BrowserError(Exception):
    pass


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

def load_profile_config():
    try:
        from io_utils import load_profile
        return load_profile() or {}
    except Exception:
        return {}


def resolve(args):
    cfg = load_profile_config()
    base = args.base_url or cfg.get("base_url")
    if not base:
        raise BrowserError(
            "no base_url: set it in ~/.canvas.api.conf or pass --base-url")
    token_file = args.token_file or cfg.get("token_file") or "~/.canvas_token"
    return base.rstrip("/"), os.path.expanduser(token_file)


def read_token(path):
    try:
        with open(path) as fh:
            return fh.read().strip()
    except OSError:
        return None


def api_get(base, token, path):
    """A plain REST GET, used only for the before/after assignment diff."""
    req = urllib.request.Request(f"{base}/api/v1{path}",
                                 headers={"Authorization": f"Bearer {token}"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def assignment_snapshot(base, token, course_id):
    out = {}
    for a in api_get(base, token,
                     f"/courses/{course_id}/assignments?per_page=200"):
        out[a["id"]] = {
            "name": a["name"],
            "points": a.get("points_possible"),
            "group": a.get("assignment_group_id"),
            "types": tuple(a.get("submission_types") or ()),
            "omit": a.get("omit_from_final_grade"),
            "url": ((a.get("external_tool_tag_attributes") or {})
                    .get("url")),
        }
    return out


def diff_assignments(before, after):
    created = [(i, after[i]) for i in after if i not in before]
    removed = [(i, before[i]) for i in before if i not in after]
    changed = []
    for i in after:
        if i in before and before[i] != after[i]:
            fields = {k: (before[i][k], after[i][k])
                      for k in after[i] if before[i][k] != after[i][k]}
            changed.append((i, after[i]["name"], fields))
    return created, removed, changed


