import argparse
import html
import mimetypes
import os
import pathlib
import re
import sys
import urllib.parse
from datetime import datetime
from zoneinfo import ZoneInfo

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
LOCAL_TZ = ZoneInfo("America/New_York")


def parse_release_dt(s):
    """--unlock-at value -> ISO8601 string for the Canvas API.

    A bare value (no UTC offset) is assumed to be Eastern local time, since
    "release at midnight" means Knoxville midnight for this course, not UTC.
    """
    try:
        dt = datetime.fromisoformat(s)
    except ValueError:
        sys.exit(f"bad --unlock-at value {s!r}; use YYYY-MM-DD or "
                  f"YYYY-MM-DDTHH:MM[:SS][+HH:MM]")
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=LOCAL_TZ)
    return dt.isoformat()


def ensure_folder(tok, spec):
    """Return the id of a "/"-nested Canvas folder, creating what is missing.

    parent_folder_path on the upload endpoint creates intermediate folders
    itself, but only the CALLER knows whether that is intended, and a typo
    silently produces a new tree rather than an error.  Resolving up front
    means the dry run can say "would create" before anything is written.
    """
    have = {f["full_name"]: f["id"] for f in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/folders?per_page=100", tok)}
    full, parent, created = "course files", have["course files"], []
    for part in [p for p in spec.split("/") if p]:
        full = f"{full}/{part}"
        if full in have:
            parent = have[full]
            continue
        created.append(full)
        r, _ = canvas_http.http_post_json(
            f"{BASE}/api/v1/folders/{parent}/folders", tok, {"name": part})
        have[full], parent = r["id"], r["id"]
    return parent, created


def folder_exists(tok, spec):
    """(exists, full_name) without creating anything -- for the dry run."""
    have = {f["full_name"] for f in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/folders?per_page=100", tok)}
    full = "course files/" + spec.strip("/")
    return full in have, full


def link_state(tok, section_html):
    """Resolve every file id linked in a section: [(id, live, name)].

    A dead id is the failure mode that looks like success -- the page renders
    a normal link and only a fetch tells you the file is gone.
    """
    out = []
    for fid in dict.fromkeys(re.findall(r"/files/(\d+)", section_html)):
        try:
            f, _ = canvas_http.http_get_json(
                f"{BASE}/api/v1/courses/{COURSE}/files/{fid}", tok)
            out.append((fid, True, f.get("display_name", "?")))
        except Exception:
            out.append((fid, False, None))
    return out


def upload(tok, path, folder, locked, unlock_at=None):
    data = path.read_bytes()
    ctype = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    where = ({"parent_folder_id": folder} if isinstance(folder, int)
             else {"parent_folder_path": folder})
    init, _ = canvas_http.http_post_json(
        f"{BASE}/api/v1/courses/{COURSE}/files", tok,
        {"name": path.name, "size": len(data), "content_type": ctype,
         "on_duplicate": "overwrite", **where})
    body, hdrs = canvas_http.http_post_multipart_no_auth(
        init["upload_url"], init.get("upload_params", {}),
        {"file": (path.name, data, ctype)})
    import json
    f = json.loads(body) if body else None
    if not f or "id" not in f:
        loc = dict(hdrs or {}).get("Location")
        r = canvas_http.http_get_json(loc, tok)
        f = r[0] if isinstance(r, tuple) else r
    patch = {"locked": bool(locked), "hidden": False}
    if unlock_at:
        patch["unlock_at"] = unlock_at
    canvas_http.http_put_json(f"{BASE}/api/v1/files/{f['id']}", tok, patch)
    return f


def main():
    ap = argparse.ArgumentParser()
    target = ap.add_mutually_exclusive_group(required=True)
    target.add_argument("--page", help="Canvas page title or url slug")
    target.add_argument("--assignment", metavar="ID", type=int,
                        help="Canvas assignment id (for homework keys)")
    ap.add_argument("--section", required=True)
    ap.add_argument("--file", required=True)
    ap.add_argument("--folder", default="Recitation")
    ap.add_argument("--replace", action="store_true",
                    help="replace the section's contents instead of appending")
    release = ap.add_mutually_exclusive_group()
    release.add_argument("--publish", action="store_true",
                         help="upload visible to students immediately")
    release.add_argument("--unlock-at", metavar="DATETIME",
                         help="upload locked, auto-visible starting this "
                              "date/time (bare values assumed Eastern local)")
    ap.add_argument("-a", "--apply", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    global BASE, COURSE
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    path = pathlib.Path(a.file)
    if not path.is_file():
        sys.exit(f"no such file: {path}")
    if re.search(r"-\dx\d", path.name):
        sys.exit(f"refusing {path.name}: n-up PDFs are instructor-only")
    unlock_at = parse_release_dt(a.unlock_at) if a.unlock_at else None
    locked = not a.publish and not unlock_at

    if a.page:
        kind, name = "page", a.page
        url = (f'{BASE}/api/v1/courses/{COURSE}/pages/'
               f'{urllib.parse.quote(a.page, safe="")}')
        body_field, wrap_key = "body", "wiki_page"
    else:
        kind, name = "assignment", str(a.assignment)
        url = f'{BASE}/api/v1/courses/{COURSE}/assignments/{a.assignment}'
        body_field, wrap_key = "description", "assignment"
    r = canvas_http.http_get_json(url, tok)
    d = r[0] if isinstance(r, tuple) else r
    body = d.get(body_field) or ""
    title = d.get("title") or d.get("name") or name
    m = re.search(rf"<h(?P<lvl>[1-6])[^>]*>\s*{re.escape(a.section)}\s*"
                  rf"</h(?P=lvl)>(?P<content>.*?)(?=<h[1-6]|$)", body, re.S)
    if not m:
        sys.exit(f"{kind} {name!r} has no section {a.section!r}")
    if unlock_at:
        state = f"visible to students starting {unlock_at}"
    elif a.publish:
        state = "visible to students"
    else:
        state = "students CANNOT open it"
    exists, full = folder_exists(tok, a.folder)
    print(f"  {tag}UPLOAD  {path.name}  ({len(path.read_bytes()):,} bytes)")
    print(f"            -> {full}{'' if exists else '   (WOULD BE CREATED)'}"
          f"; {state}")

    # Report what is already linked here, and whether it still resolves.
    existing = link_state(tok, m.group("content"))
    if existing:
        for fid, live, fname in existing:
            print(f"            existing link {fid}: "
                  + (f"live -- {fname}" if live else "*** DEAD (404) ***"))
    dead = [f for f, live, _ in existing if not live]
    verb = "REPLACE" if a.replace else "APPEND TO"
    print(f"  {tag}{verb} section '{a.section}' on {title[:44]}")
    if dead and not a.replace:
        print(f"            NOTE: {len(dead)} dead link(s) here will be LEFT "
              f"IN PLACE. Re-run with --replace to drop them.")
    if not d.get("published"):
        print(f"            NOTE: the {kind} is UNPUBLISHED -- students will "
              "not see this until it is published.")
    if not a.apply:
        print("  (dry run: nothing written)")
        return 0

    folder_id, created = ensure_folder(tok, a.folder)
    for c in created:
        print(f"  created folder {c}")
    f = upload(tok, path, folder_id, locked=locked, unlock_at=unlock_at)
    link = (f'<p><a class="instructure_file_link inline_disabled" '
            f'title="{html.escape(path.name)}" '
            f'href="{BASE}/courses/{COURSE}/files/{f["id"]}?wrap=1" '
            f'target="_blank" '
            f'data-api-endpoint="{BASE}/api/v1/courses/{COURSE}/files/{f["id"]}" '
            f'data-api-returntype="File">{html.escape(path.name)}</a></p>\n')
    old = m.group("content")
    placeholder = re.match(r"^\s*<p>\s*(not yet|to be) posted",
                           old.strip(), re.I)
    new_sec = ("\n" + link if a.replace or placeholder else old + link)
    new_body = (body[:m.start("content")] + new_sec
                + body[m.end("content"):])
    canvas_http.http_put_json(url, tok, {wrap_key: {body_field: new_body}})
    extra = f"  unlock_at={unlock_at}" if unlock_at else ""
    print(f"  file id {f['id']}  locked={locked}{extra}  folder={a.folder}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
