#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.material.upload.py
# Version:      1.1.0
# Created:      2026-08-19
# Revised:      2026-10-13
# Purpose:      Upload one course file and link it into a section of a Canvas
#               page or assignment, replacing that section's "not yet
#               posted"/"to be posted" placeholder.
#
# This is the recurring job once the page structure is settled: material gets
# written, and it has to reach the right heading on the right page.
#
# --assignment ID targets an Assignment's description instead of a Page's
# body -- homework keys live there (found 2026-09-01: HW01's "Key" section
# was in the assignment description, not a page section at all).  Exactly
# one of --page/--assignment is required.  Assignment descriptions used <h3>
# for these headings where pages use <h2>; all 11 HW assignments were
# converted to <h2> on 2026-09-01 for consistency (MG: no reason to differ).
# Section headings are still matched at any level (h1-h6) rather than hard-
# coded to h2, so a stray h3 doesn't silently fail to match.
#
# --unpublished uploads the file LOCKED, so it exists and is linked but no
# student can open it.  Publishing later is one click in Canvas Files, or
# re-run with --publish.  That separation matters: a worksheet often wants to
# be in place well before it is released.
#
# --unlock-at schedules the release instead of doing it by hand: the file
# uploads locked=False with Canvas's own unlock_at set, so Canvas itself
# starts showing it at that moment -- no cron job or second run needed.  A
# bare value (no UTC offset) is read as America/New_York local time, since
# this is a UTK course and "release at midnight" means Knoxville midnight.
# Mutually exclusive with --publish (immediate) -- pick one release policy.
#
# Verified 2026-09-01: once unlock_at is in the future, Canvas's file GET
# always reports "hidden": true regardless of what you PUT for that field --
# it is a computed "currently invisible" flag, not an independent setting.
# Don't chase that as a bug; unlock_at is still the thing governing access,
# and Canvas evaluates it at request time, so the file opens on its own the
# moment the date passes.
#
# --replace REPLACES the section's contents instead of appending to it.  Use
# it when a heading already holds a link to a superseded file.  Without it,
# v1.0.0 appended in every case except a literal "not yet posted" placeholder,
# so re-posting a corrected file left the OLD link sitting above the new one
# with nothing to say which was current.
#
# Whatever the mode, every file link already under the heading is RESOLVED
# against the API first and reported as live or DEAD.  This is not a nicety:
# on 2026-08-20 the Grade Estimator page was found linking to file 32637628,
# which had been deleted -- the page rendered a perfectly ordinary file link
# and the course contained no estimator at all.  A link that looks right is
# not evidence the file is there.
#
# The file is named explicitly.  It is never taken from a directory scan --
# the activity folders hold keys, notes, n-up instructor PDFs and LaTeX
# sources, and a sweep would eventually publish one of them.
#
# Usage:  canvas.api.material.upload.py --page TITLE --section NAME --file PATH
#                                   [--folder NAME] [--replace]
#                                   [--unpublished | --publish | --unlock-at DT]
#                                   [--apply]
#
# Options:
#   --page TITLE     Canvas page title or url slug, e.g. "grade-estimator"
#   --assignment ID  Canvas assignment id (numeric); use instead of --page
#                    for homework keys, whose "Key" section is in the
#                    assignment description
#   --section NAME   Heading to link under, e.g. Worksheets
#   --file PATH      Local file to upload
#   --folder NAME    Canvas Files folder, "/"-nested and created as needed
#                    (default: Recitation).  Grading tools belong in
#                    "Evaluation/Tools", not with the syllabus (MG,
#                    2026-08-20)
#   --replace        Replace the section's contents rather than append
#   --unpublished    Upload locked, so students cannot open it (default)
#   --publish        Upload visible to students
#   --unlock-at DT   Upload locked, auto-visible starting DT (YYYY-MM-DD or
#                    YYYY-MM-DDTHH:MM[:SS][+HH:MM]; bare values are Eastern
#                    local).  Mutually exclusive with --publish
#   -a, --apply      Perform the writes (default is a DRY RUN)
#
