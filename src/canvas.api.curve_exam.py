# Purpose:      Curve a Canvas exam by adding a fixed offset so that the mean
#               or median reaches a target percentage, then upload the results
#               as a new assignment column.
#
# Usage:        canvas.api.curve_exam.py COURSE_ID MATCH
#                   --target N [--stat mean|median]
#                   [--output-name NAME] [--group-id ID]
#                   [--base-url URL] [--token TOKEN | --token-file FILE]
#                   [--dry-run] [--verbose] [--help]
#
# Input:        Canvas API token + course_id + assignment name substring
# Output:       New Canvas assignment with curved scores; summary to stdout
#
# Options:
#   COURSE_ID               Canvas numeric course ID
#   MATCH                   Case-insensitive substring to match assignment name
#   --target N              Target percentage 0-100 (required)
#   --stat mean|median      Statistic to bring to target (default: median)
#   --output-name NAME      Name for new curved assignment
#                           (default: "<source name> (Curved)")
#   --group-id ID           Assignment group for new assignment
#                           (default: same as source)
#   --base-url URL          Canvas instance URL
#   --token TOKEN           Inline API token
#   --token-file FILE       Path to token file
#   -n, --dry-run           Show what would be done without making changes
#   -v, --verbose           Show detailed API output
