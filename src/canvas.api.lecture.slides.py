#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.lecture.slides.py
# Version:      1.1.0
# Created:      2026-08-19
# Revised:      2026-10-13
# Purpose:      Put each lecture's exported slide PDFs on its Canvas page, and
#               keep the Slides section neutral until they exist.
#
# The two names already carry everything needed, so nothing has to be recorded
# on the page as a contract (MG, 2026-08-19):
#
#   folder prefix -> the lecture.  L14_DNA.Structure/ is L14, whose page is
#                    "L14: <schedule topic>".  L01a_ and L01b_ both feed L01.
#   file name     -> the role.  L14_2026_dna.structure.pdf is a 2026 export.
#
# This REPLACES canvas.lecture.placeholders.py, which wrote the expected
# filename into the page as the contract.  That leaked a filename to students
# the moment a page was published, and MG does not want slide filenames shown
# before the slides exist.
#
# It does NOT sweep a directory.  It matches only L*_2026_*.pdf -- the symlink
# you create by hand when a deck is exported and ready.  slides_2026_*.odp,
# keys, n-up instructor PDFs and LaTeX sources do not match, so nothing is
# published by accident.  The symlink's EXISTENCE is the ready signal.
#
# With no matching file, the section is reset to "To be posted before
# lecture" -- the same text whether the page is published or not.
#
# TWO PAGE SHAPES (2026-09-08).  L06-L25 split the Slides section by year:
#
#     <h2>Slides</h2>
#       <h3>Current Year</h3>    <- this year's decks go here, and ONLY here
#       <h3>Previous Years</h3>  <- prior-year decks, never touched
#
# so those pages are written through the h3, not the h2.  Matching the h2
# spans both subsections, and the consequences are not cosmetic: an upload
# appends, so a 2026 deck would land at the BOTTOM of the prior-year list,
# and a reset would replace the prior-year links with placeholder text.
# L01-L05 and L26 are still flat, with decks directly under <h2>Slides</h2>,
# so both shapes are supported and the h3 wins where it exists.
#
# A page carrying h3 subsections but no "Current Year" is SKIPPED rather
# than guessed at -- writing into the h2 there is the bug above.
#
# Prior-year links are outside the written region, so they no longer read as
# "a file not named L*_2026_*" and no longer make the tool inert on L06-L25.
# Their presence is reported, so a run says what it left alone.
#
# ALREADY POSTED UNDER ANOTHER NAME (2026-09-10).  A posted deck is matched
# by its link title, which is the name it was uploaded under.  Renaming the
# posting symlink afterwards (L04: slides-L04_2026_... -> L04_2026_...) made
# the deck look missing, and --apply posted it a second time.  So before
# uploading, a local PDF is compared with every file already linked in the
# section -- size first, then the downloaded bytes -- and an identical one
# is reported as POSTED ... AS <name> and left alone.
#
# EXPLICIT SCOPE (2026-09-10).  --apply acts only on the lectures named with
# --lecture, or on every page with --all.  A dry run reports every lecture
# unless --lecture narrows it.  Without this, posting one lecture's slides
# also posted whatever else happened to be pending.  The arguments are
# checked before the Canvas token is read.
#
# Usage:        canvas.api.lecture.slides.py [--lecture Lnn ...] [--all] [--apply] [-v]
# Options:      -l/--lecture Lnn  act on this lecture (L07, L06b, 7); repeatable.
#                                 Pages are per NUMBER, so L06a and L06b are one
#               --all             act on every lecture page (required for a
#                                 course-wide --apply)
#               -a/--apply        perform the writes (default is a DRY RUN)
#               -v/--verbose      show pages already correct
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse, csv, html, json, mimetypes, os, pathlib, re, sys, urllib.parse
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
LEC = TSV = YEAR = None   # set in main() from canvas.course.json
NEUTRAL = "<p>To be posted before lecture</p>"
# Both wordings are in use -- 19 pages say "prior to", L26 says "before".
# Recognise either as an untouched placeholder, so a run does not churn the
# wording of every page it visits.
NEUTRAL_TEXTS = {"to be posted before lecture", "to be posted prior to lecture"}

CUR_H3 = re.compile(r"(<h3[^>]*>\s*Current Year\s*</h3>)(.*?)(?=<h[1-3][ >]|$)",
                    re.S | re.I)
SLIDES_H2 = re.compile(r"(<h2[^>]*>\s*Slides\s*</h2>)(.*?)(?=<h2[ >]|$)", re.S | re.I)
PREV_H3 = re.compile(r"<h3[^>]*>\s*Previous Years\s*</h3>", re.I)


def slides_section(body):
    """Region that holds THIS year's decks -> (match, note) or (None, why).

    The h3 wins where it exists; see the two page shapes in the header.
    """
    m = CUR_H3.search(body)
    if m:
        return m, "Current Year"
    m = SLIDES_H2.search(body)
    if m and re.search(r"<h3[ >]", m.group(2)):
        return None, "has Slides subsections but no 'Current Year'"
    if not m:
        return None, "no Slides section"
    return m, "Slides"


def is_neutral(fragment):
    """True if the section is only placeholder text, in either wording."""
    plain = re.sub(r"<[^>]+>", " ", html.unescape(fragment))
    return re.sub(r"\s+", " ", plain).strip().lower() in NEUTRAL_TEXTS


def upload(tok, path):
    data = path.read_bytes(); ct = mimetypes.guess_type(path.name)[0] or "application/pdf"
    init, _ = canvas_http.http_post_json(f"{BASE}/api/v1/courses/{COURSE}/files", tok,
        {"name": path.name, "size": len(data), "content_type": ct,
         "parent_folder_path": "Slides", "on_duplicate": "overwrite"})
    body, hdrs = canvas_http.http_post_multipart_no_auth(
        init["upload_url"], init.get("upload_params", {}), {"file": (path.name, data, ct)})
    f = json.loads(body) if body else None
    if not f or "id" not in f:
        r = canvas_http.http_get_json(dict(hdrs or {}).get("Location"), tok)
        f = r[0] if isinstance(r, tuple) else r
    canvas_http.http_put_json(f"{BASE}/api/v1/files/{f['id']}", tok,
                              {"locked": False, "hidden": False})
    return f


def lecture_number(arg):
    """'L07', 'l06b', '7' -> 7.  The letter is dropped: pages are per number."""
    m = re.fullmatch(r"[Ll]?(\d{1,2})[a-e]?", arg.strip())
    if not m:
        raise argparse.ArgumentTypeError(f"not a lecture: {arg!r} (use L07, L06b or 7)")
    return int(m.group(1))


def posted_as(tok, path, section, cache):
    """Name under which PATH's exact bytes are already linked in SECTION, or None.

    Size first, so only a same-size candidate is downloaded.  CACHE holds file
    metadata per id for the run.
    """
    data = None
    for fid in re.findall(r"/api/v1/(?:courses/\d+/)?files/(\d+)", section):
        if fid not in cache:
            r = canvas_http.http_get_json(f"{BASE}/api/v1/files/{fid}", tok)
            cache[fid] = r[0] if isinstance(r, tuple) else r
        f = cache[fid]
        if not f or f.get("size") != path.stat().st_size:
            continue
        data = data if data is not None else path.read_bytes()
        if canvas_http.http_get_raw(f["url"]) == data:
            return f["display_name"]
    return None


def link(f):
    return (f'<p><a class="instructure_file_link inline_disabled" '
            f'title="{html.escape(f["display_name"])}" '
            f'href="{BASE}/courses/{COURSE}/files/{f["id"]}?wrap=1" target="_blank" '
            f'data-api-endpoint="{BASE}/api/v1/courses/{COURSE}/files/{f["id"]}" '
            f'data-api-returntype="File">{html.escape(f["display_name"])}</a></p>\n')


def main():
    global BASE, COURSE, LEC, TSV, YEAR
    ap = argparse.ArgumentParser()
    ap.add_argument("-l", "--lecture", action="append", type=lecture_number, default=[])
    ap.add_argument("--all", action="store_true")
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    if a.lecture and a.all:
        ap.error("--lecture and --all are alternatives; pass one")
    if a.apply and not (a.lecture or a.all):
        ap.error("--apply needs --lecture Lnn (repeatable) or --all")
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    YEAR = cfg.year
    LEC = pathlib.Path(cfg.path("lectures_dir"))
    TSV = cfg.path("schedule_tsv")

    tag = "" if a.apply else "[DRY-RUN] "
    topics = {int(r["lecture"]): r["topic"].strip()
              for r in csv.DictReader(open(TSV), delimiter="\t")
              if r["lecture"].strip().isdigit()}
    # lecture number -> the exported PDFs sitting in its folder(s)
    found = {n: [] for n in topics}
    for d in sorted(LEC.iterdir()):
        m = re.match(r"L(\d\d)[a-e]?_", d.name)
        if not (d.is_dir() and m):
            continue
        n = int(m.group(1))
        if n in found:
            found[n] += sorted(p for p in d.iterdir()
                               if re.match(rf"L\d\d[a-e]?_{YEAR}_.*\.pdf$", p.name))

    unknown = sorted(set(a.lecture) - set(topics))
    if unknown:
        ap.error(f"not in the schedule: {', '.join(f'L{n:02d}' for n in unknown)}")

    # Look pages up by SLUG, not title: Canvas only tolerates a title in the
    # path, and it 404s on some punctuation (L11's '&' was the first to fail).
    slug = {p["title"]: p["url"] for p in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/pages?per_page=100", tok)}

    files = {}
    for n, topic in sorted(topics.items()):
        if a.lecture and n not in a.lecture:
            continue
        title = f"L{n:02d}: {topic}"
        if title not in slug:
            print(f"  MISSING page {title[:46]!r}"); continue
        url = f'{BASE}/api/v1/courses/{COURSE}/pages/{slug[title]}'
        r = canvas_http.http_get_json(url, tok)
        d = r[0] if isinstance(r, tuple) else r
        body = d.get("body") or ""
        sec, note = slides_section(body)
        if not sec:
            print(f"  SKIP    {title[:46]}: {note}"); continue
        # Reported so a run says what it deliberately left alone.
        pv = "  [prior-year block kept]" if PREV_H3.search(body) else ""
        have = set(re.findall(r'title="([^"]+)"', sec.group(2)))
        want = [p for p in found[n]]
        if not want:
            if is_neutral(sec.group(2)):
                if a.verbose:
                    print(f"          {title[:46]}  neutral, no export yet{pv}")
                continue
            if "instructure_file_link" in sec.group(2):
                print(f"  KEEP    {title[:46]}: links a file not named L*_{YEAR}_*"); continue
            print(f"  {tag}RESET   {title[:46]}  -> neutral ({note}){pv}")
            if a.apply:
                canvas_http.http_put_json(url, tok, {"wiki_page": {"body":
                    body[:sec.end(1)] + "\n" + NEUTRAL + "\n" + body[sec.end(2):]}})
            continue
        missing = []
        for p in want:
            if p.name in have:
                continue
            old = posted_as(tok, p, sec.group(2), files)
            if old:
                print(f"  POSTED  {title[:46]}  {p.name} AS {old}  (identical bytes)")
            else:
                missing.append(p)
        if not missing:
            if a.verbose: print(f"          {title[:46]}  {len(want)} deck(s) already linked")
            continue
        print(f"  {tag}UPLOAD  {title[:46]}  {[p.name for p in missing]}"
              f"  -> {note}{pv}")
        if a.apply:
            links = "".join(link(upload(tok, p)) for p in missing)
            keep = "" if not re.search(r"instructure_file_link", sec.group(2)) \
                   else sec.group(2).rstrip()
            canvas_http.http_put_json(url, tok, {"wiki_page": {"body":
                body[:sec.end(1)] + "\n" + keep + links + body[sec.end(2):]}})
    return 0


if __name__ == "__main__":
    sys.exit(main())
