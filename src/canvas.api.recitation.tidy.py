#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.recitation.tidy.py
# Version:      1.1.0
# Created:      2026-08-19
# Revised:      2026-10-13
# Purpose:      Tidy the recitation pages after the format pass: refile content
#               stranded under the wrong heading, drop empty markup, and
#               replace non-ASCII punctuation.
#
# canvas.recitation.format.py deliberately preserved every non-standard section
# verbatim, which left R11's worksheet line sitting under "Listening
# (Optional)" while its own Worksheets section said "To be posted".  Refiling
# is editorial, so it lives here rather than in the format pass.
#
# LOSES NOTHING BY CONSTRUCTION.  Every href and every non-empty run of text in
# the old body must still be present in the new one; the script REFUSES to
# write a page otherwise.  The only exceptions are declared in DROP, and each
# one is printed verbatim as it is removed, so nothing disappears quietly.
#
# Usage:        canvas.api.recitation.tidy.py [--apply]
# Options:      -a/--apply   perform the writes (default is a DRY RUN)
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import html
import os
import pathlib
import re
import sys
import urllib.parse

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
STANDARD = ["Readings", "Slides", "Worksheets"]

# Non-ASCII punctuation -> ASCII, per the repo's ASCII-only convention.
PUNCT = {"–": "-", "—": "--", "：": ":", "‘": "'",
         "’": "'", "“": '"', "”": '"'}

# Labels that duplicate a heading once their content has been refiled.  Each
# is printed as it is dropped.
DROP = ["Recitation Activity:"]


def plain(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html.unescape(s or ""))).strip()


def sections(b):
    ms = list(re.finditer(r"<h[23][^>]*>(.*?)</h[23]>", b, re.S))
    out = []
    if not ms:
        return [(None, b)]
    if ms[0].start():
        out.append((None, b[:ms[0].start()]))
    for i, m in enumerate(ms):
        h = html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).replace("\xa0", " ").strip()
        end = ms[i + 1].start() if i + 1 < len(ms) else len(b)
        out.append((h, b[m.end():end]))
    return out


def target(text):
    low = text.lower()
    if "worksheet" in low and "key" not in low:
        return "Worksheets"
    if "key" in low:
        return "Key"
    if "slide" in low:
        return "Slides"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-a", "--apply", action="store_true")
    canvas_course.add_arguments(ap)
    args = ap.parse_args()
    tag = "" if args.apply else "[DRY-RUN] "
    global BASE, COURSE
    cfg, BASE, tok = canvas_course.setup(args)
    COURSE = cfg.course_id

    pages = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/pages?per_page=100", tok)
    for p in sorted(pages, key=lambda x: x["title"]):
        if not re.match(r"R(\d\d|XX)", p["title"]):
            continue
        url = (f'{BASE}/api/v1/courses/{COURSE}/pages/'
               f'{urllib.parse.quote(p["url"], safe="")}')
        r = canvas_http.http_get_json(url, tok)
        d = r[0] if isinstance(r, tuple) else r
        body = d.get("body") or ""

        secs = [[h, c] for h, c in sections(body)]
        names = [h for h, _ in secs]
        notes, moved = [], []

        for s in secs:
            h, c = s
            keep = []
            for m in re.finditer(r"<p[^>]*>.*?</p>", c, re.S):
                frag = m.group(0)
                txt = plain(frag)
                if not txt:
                    notes.append("dropped an empty paragraph")
                    continue
                if any(txt.rstrip().rstrip(":") == lbl.rstrip(":") for lbl in DROP):
                    notes.append(f"dropped label {txt!r}")
                    continue
                t = target(txt)
                if t and h and t != h and t in names:
                    moved.append((frag, t, h, txt))
                    continue
                keep.append(frag)
            rest = re.sub(r"<p[^>]*>.*?</p>", "", c, flags=re.S)
            s[1] = "".join(keep) + ("" if not plain(rest) else rest)

        for frag, t, src, txt in moved:
            for s in secs:
                if s[0] == t:
                    if plain(s[1]).lower().startswith("to be posted"):
                        s[1] = ""
                    s[1] += frag

        new = ""
        for h, c in secs:
            new += (f"<h2>{html.escape(h)}</h2>\n" if h else "") + c.strip() + "\n"
        for bad, good in PUNCT.items():
            if bad in new:
                notes.append(f"replaced {bad!r} with {good!r}")
                new = new.replace(bad, good)

        if plain(new) == plain(body) and not moved and not notes:
            continue

        # Safety: no href and no word of text may vanish.
        lost_href = set(re.findall(r'href="([^"]+)"', body)) - set(
            re.findall(r'href="([^"]+)"', new))
        old_words = [w for w in plain(body).split() if len(w) > 3]
        for bad, good in PUNCT.items():
            old_words = [w.replace(bad, good) for w in old_words]
        dropped_txt = " ".join(n.split("dropped label ")[-1] for n in notes
                               if n.startswith("dropped label"))
        missing = [w for w in old_words
                   if w not in plain(new).split() and w not in dropped_txt]
        if lost_href or missing:
            print(f"  REFUSE  {p['title'][:44]}: would lose "
                  f"{len(lost_href)} link(s), {len(missing)} word(s): {missing[:6]}")
            continue

        print(f"  {tag}TIDY    {p['title'][:44]}")
        for frag, t, src, txt in moved:
            print(f"            moved to {t!r} from {src!r}: {txt[:56]}")
        for n in sorted(set(notes)):
            print(f"            {n}")
        if args.apply:
            canvas_http.http_put_json(url, tok, {"wiki_page": {"body": new}})
    return 0


if __name__ == "__main__":
    sys.exit(main())
