import json
import os
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import io_utils  # noqa: E402

CONFIG_NAME = "canvas.course.json"
ENV_VAR = "CANVAS_COURSE_CONFIG"


class CourseConfigError(Exception):
    """Raised when no usable course configuration can be resolved."""


def _walk_up(start):
    d = pathlib.Path(start).resolve()
    for p in [d] + list(d.parents):
        cand = p / CONFIG_NAME
        if cand.is_file():
            return cand
    return None


_OVERRIDE = None


def use_config(path):
    """Make find_config() return `path` from now on (None to clear).  Lets a
    tool that already resolved its config (for example from --course-config)
    hand the same file to modules such as db_paths that find it themselves."""
    global _OVERRIDE
    _OVERRIDE = pathlib.Path(path).resolve() if path else None


def find_config(start=None):
    """First canvas.course.json found walking up from `start` (default: the
    current directory); failing that, walking up from the directory of the
    script that was INVOKED (sys.argv[0], symlinks not followed), so a tool run
    through a symlink in a course repo's bin/ finds that repo's config from any
    working directory.  Returns a path or None."""
    if _OVERRIDE is not None and start is None:
        return _OVERRIDE
    hit = _walk_up(start or os.getcwd())
    if hit or start is not None:
        return hit
    if sys.argv and sys.argv[0]:
        script_dir = os.path.dirname(os.path.abspath(sys.argv[0]))
        return _walk_up(script_dir)
    return None


def _merge(parent, child):
    out = dict(parent)
    for k, v in child.items():
        if k == "extends":
            continue
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = {**out[k], **v}
        else:
            out[k] = v
    return out


def load_config(path, _seen=None):
    """Load a config file, following `extends` (cycle-safe)."""
    path = pathlib.Path(os.path.expanduser(str(path))).resolve()
    seen = set(_seen or ())
    if path in seen:
        raise CourseConfigError(f"extends cycle at {path}")
    seen.add(path)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise CourseConfigError(f"course config not found: {path}")
    except json.JSONDecodeError as e:
        raise CourseConfigError(f"{path}: invalid JSON: {e}")
    if "extends" in data:
        ext = pathlib.Path(os.path.expanduser(data["extends"]))
        if not ext.is_absolute():
            ext = path.parent / ext
        data = _merge(load_config(ext, seen), data)
    return data


class CourseConfig:
    def __init__(self, data, source=None, course_id=None):
        self.data = data
        self.source = source
        cid = course_id if course_id is not None else data.get("course_id")
        if cid is None:
            raise CourseConfigError(
                "no course id: pass --course-id or add \"course_id\" to "
                f"{CONFIG_NAME}")
        self.course_id = int(cid)
        self.name = data.get("name", "")
        self.base_url = data.get("base_url")
        self.year = data.get("year")
        self.folders = dict(data.get("folders", {}))

    def folder_id(self, key):
        if key not in self.folders:
            raise CourseConfigError(
                f"no folders.{key} in {self.source or CONFIG_NAME}; "
                "pass the folder id on the command line")
        return int(self.folders[key])

    def repo_dirs(self, key, year=None):
        """Directories for repos[key], with {year} filled in, ~ expanded.
        A value may be a string or a list of strings."""
        raw = self.data.get("repos", {}).get(key)
        if raw is None:
            raise CourseConfigError(
                f"no repos.{key} in {self.source or CONFIG_NAME}")
        y = year if year is not None else self.year
        out = []
        for t in ([raw] if isinstance(raw, str) else raw):
            if "{year}" in t and y is None:
                raise CourseConfigError(
                    f"repos.{key} needs a year: pass --year or set \"year\"")
            out.append(os.path.expanduser(t.format(year=y)))
        return out


    def path(self, key, year=None):
        """One path from "paths"[key] with {year} filled in and ~ expanded."""
        raw = self.data.get("paths", {}).get(key)
        if raw is None:
            raise CourseConfigError(
                f"no paths.{key} in {self.source or CONFIG_NAME}")
        y = year if year is not None else self.year
        if "{year}" in raw and y is None:
            raise CourseConfigError(
                f"paths.{key} needs a year: pass --year or set \"year\"")
        return os.path.expanduser(raw.format(year=y))


def add_arguments(parser):
    g = parser.add_argument_group("course selection")
    g.add_argument("--course-id", "--course", dest="course_id", type=int, default=None,
                   help=f"Canvas course id (overrides {CONFIG_NAME})")
    g.add_argument("--course-config", default=None, metavar="FILE",
                   help=f"path to a {CONFIG_NAME} (default: ${ENV_VAR}, "
                        "else search upward from the current directory)")
    g.add_argument("--year", type=int, default=None,
                   help="teaching year used to fill {year} in repo paths")
    return parser


def resolve(args, start=None):
    """Build a CourseConfig from parsed args.  Raises CourseConfigError."""
    path = getattr(args, "course_config", None) or os.environ.get(ENV_VAR)
    path = pathlib.Path(os.path.expanduser(path)) if path else find_config(start)
    data = load_config(path) if path else {}
    year = getattr(args, "year", None)
    if year is not None:
        data = {**data, "year": year}
    return CourseConfig(data, source=path,
                        course_id=getattr(args, "course_id", None))


def connect(cfg, token_file=None, profile=None):
    """Return (base_url, token) for `cfg`.

    base_url: config, else ~/.canvas.api.conf.  Token file: the argument, else
    the profile's token_file, else ~/.api/canvas_token.  Raises
    CourseConfigError (never returns a guessed value)."""
    profile = io_utils.load_profile() if profile is None else profile
    base = (cfg.base_url or profile.get("base_url") or "").rstrip("/")
    if not base:
        raise CourseConfigError(
            "no base_url: set it in canvas.course.json or ~/.canvas.api.conf")
    path = token_file or profile.get("token_file") or "~/.api/canvas_token"
    path = os.path.expanduser(path)
    try:
        tok = pathlib.Path(path).read_text(encoding="utf-8").strip()
    except OSError as e:
        raise CourseConfigError(f"cannot read token file {path}: {e}")
    if not tok:
        raise CourseConfigError(f"token file {path} is empty")
    return base, tok


def setup(args):
    """resolve() + connect() with a clean [FAIL] exit instead of a traceback.
    Returns (cfg, base_url, token)."""
    try:
        cfg = resolve(args)
        base, tok = connect(cfg, token_file=getattr(args, "token_file", None))
    except CourseConfigError as e:
        sys.exit(f"[FAIL] {e}")
    return cfg, base, tok
