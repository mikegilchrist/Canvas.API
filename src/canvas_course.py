# Revised:      2026-10-13
# Purpose:      Resolve WHICH Canvas course and WHICH local repos a tool acts
#               on, so the canvas.api.* tools work for any course that has a
#               similar layout (BIOL240, EEB403, ...) instead of hard-coding
#               course id 261062 and ~/Repositories/... paths.
#
# A course repo carries a small `canvas.course.json` at its root:
#
#   {
#     "course_id": 261062,
#     "name": "BIOL240 F2026",
#     "base_url": "https://utk.instructure.com",     (optional)
#     "folders": {"recitation": 4000104},            (optional Canvas folder ids)
#     "repos": {"recitations": "~/Repositories/discussions_biol240/{year}"},
#     "paths": {"schedule_tsv": "~/x/F.{year}/schedule_{year}.tsv"},
#     "year": 2026,                                  (optional default)
#     "extends": "~/Courses/Genetics/canvas.course.json"   (optional)
#   }
#
# `extends` names another config; the child's keys win, dict keys merge.
# Lookup order for the config: --course-config, $CANVAS_COURSE_CONFIG, then
# walk up from the current directory.  --course-id overrides the id.
# There is deliberately NO built-in default course: a missing id is an error
# (a silent default would act on the wrong course).
#
# Usage:        import canvas_course
#               canvas_course.add_arguments(parser)
#               cfg = canvas_course.resolve(args)
#               cfg.course_id, cfg.repo_dirs("recitations")
# Input:        canvas.course.json (see above)
# Output:       CourseConfig object
# Requirements: Python 3.7+
#
# Session:      BIOL240 R09 -> Canvas.API consolidation
