#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.group.sync.py
# Version:      1.1.0
# Created:      2026-08-18
# Revised:      2026-10-13 -- course-agnostic: course id, base URL, token, group-set
#               name and END_DATE come from canvas.course.json (group_sync.*);
#               --course-id/--course-config added.
# Purpose:      Keep the BIOL240 discussion-board group set equal to the
#               recitation section rosters.
#
# The 26 graded DBs are group discussions against group set 45384, whose six
# groups ARE the six recitation sections.  Canvas then splits each board into
# one section-level child board per group -- 156 in all -- which is how the
# syllabus's "DBs are administered separately for each recitation section"
# is actually delivered.  2025 did the same thing (course 231573, set 38769,
# groups 07..12).
#
# A Canvas group is a STATIC membership list.  It is not a query against the
# section, and nothing tells Canvas to keep the two equal.  So a student who
# adds the course after the groups were built lands in no group, and on a
# group discussion that means they have no board to post in at all.  That is
# what this script repairs, and why it is worth running daily through the
# add/drop window.
#
# Drops need no repair: removing the enrollment removes the person from the
# course, so the stale membership stops mattering.  The script reports them
# anyway and removes them, so the group and the roster stay identical.
#
# SELF-EXPIRING.  After END_DATE (group_sync.end_date) it exits 0 without touching Canvas and says
# so in the log, so a forgotten cron entry cannot quietly keep writing months
# later.  Change END_DATE, do not delete the guard.
#
# On the membership endpoint: adding members is PUT /groups/:id with members[].
# POST /groups/:id/memberships takes a SINGLE user_id, and posting a list to it
# returns HTTP 400 -- which is how the first attempt at this failed silently
# enough to leave six empty groups behind.  Both forms are implemented; the
# bulk one is tried first and the per-student one is the fallback.
#
# Usage:        canvas.api.group.sync.py [--course-id N] [--course-config FILE]
#                  [--apply] [--until YYYY-MM-DD] [-v]
# Input:        canvas.course.json (group_sync.category_name, group_sync.end_date);
#               Canvas token via canvas_course (~/.canvas.api.conf, else
#               ~/.api/canvas_token)
# Output:       Stdout: one line per group, then a summary.  No student names
#               or ids are printed unless a per-student call fails.
#
# Options:
#   -a, --apply         Perform the writes (default is a dry run)
#       --until DATE    Override group_sync.end_date for this run
#       --ignore-until  Run even though the window has closed
#   -v, --verbose       Show groups that are already in sync
#   -h, --help          Show this help message
#
# Requirements: python3, Canvas.API/src on the path, teacher rights
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import datetime
import re
import os
import pathlib
import sys
import urllib.error

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
CATEGORY = None   # set in main(): canvas.course.json group_sync.category_name

# END_DATE (canvas.course.json group_sync.end_date; BIOL240 F2026: 2026-09-01) is
# two weeks from the day the groups were built.  Past this the roster is
# settled and a daily write serves no purpose.


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("--until", type=datetime.date.fromisoformat, default=None)
    ap.add_argument("--ignore-until", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    global BASE, COURSE, CATEGORY
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    gs = cfg.data.get("group_sync")
    if not isinstance(gs, dict) or "category_name" not in gs:
        sys.exit("[FAIL] canvas.course.json needs group_sync.category_name")
    CATEGORY = gs["category_name"]
    if a.until is None:
        if "end_date" not in gs:
            sys.exit("[FAIL] pass --until or set group_sync.end_date in canvas.course.json "
                     "(the self-expiry guard is mandatory)")
        a.until = datetime.date.fromisoformat(gs["end_date"])

    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    today = datetime.date.today()
    if today > a.until and not a.ignore_until:
        print(f"[{stamp}] add/drop window closed on {a.until}; nothing done. "
              f"Remove the cron entry, or pass --ignore-until.")
        return 0

    tag = "" if a.apply else "[DRY-RUN] "

    cats = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/group_categories?per_page=100", tok)
    cat = next((c for c in cats if c["name"] == CATEGORY), None)
    if cat is None:
        print(f"[{stamp}] ERROR: no group set named {CATEGORY!r} in course {COURSE}")
        return 1
    groups = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/group_categories/{cat['id']}/groups?per_page=100", tok)
    secs = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/sections?include[]=students&per_page=100", tok)

    # A group is matched to its section by the trailing digits of both names,
    # so renaming the groups (2025 used '07', not 'BIOL240 Section 007') does
    # not break the mapping.
    def key(name):
        # TRAILING digits only.  A whole-string digit scan reads the 240 in
        # "BIOL240 Section 007" and yields 240007, which matches no group.
        m = re.search(r"(\d+)\s*$", name.strip())
        return str(int(m.group(1))) if m else None

    want = {key(s["name"]): {st["id"] for st in (s.get("students") or [])}
            for s in secs}

    added = removed = insync = 0
    for g in sorted(groups, key=lambda x: x["name"]):
        k = key(g["name"])
        target = want.get(k)
        if target is None:
            print(f"  WARN    group {g['name']!r} matches no section; skipped")
            continue
        have = {u["id"] for u in canvas_http.paginated_get_all(
            f"{BASE}/api/v1/groups/{g['id']}/users?per_page=100", tok)}
        add, drop = sorted(target - have), sorted(have - target)
        if not add and not drop:
            insync += 1
            if a.verbose:
                print(f"  ok      {g['name']}: {len(have)} member(s), in sync")
            continue
        if add:
            print(f"  {tag}ADD     {g['name']}: {len(add)} student(s) "
                  f"(had {len(have)}, section has {len(target)})")
            added += len(add)
            if a.apply:
                try:
                    canvas_http.http_put_json(f"{BASE}/api/v1/groups/{g['id']}",
                                              tok, {"members": sorted(target)})
                except urllib.error.HTTPError as e:
                    print(f"          bulk PUT failed {e.code}; per student")
                    for uid in add:
                        try:
                            canvas_http.http_post_json(
                                f"{BASE}/api/v1/groups/{g['id']}/memberships",
                                tok, {"user_id": uid})
                        except urllib.error.HTTPError as e2:
                            print(f"          user {uid}: HTTP {e2.code}")
        if drop:
            print(f"  {tag}REMOVE  {g['name']}: {len(drop)} no longer in section")
            removed += len(drop)
            if a.apply:
                for uid in drop:
                    try:
                        canvas_http.http_delete(
                            f"{BASE}/api/v1/groups/{g['id']}/users/{uid}", tok)
                    except urllib.error.HTTPError as e:
                        print(f"          user {uid}: HTTP {e.code}")

    print(f"[{stamp}] {tag}{added} added, {removed} removed, "
          f"{insync} group(s) already in sync (window ends {a.until})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
