import argparse
import difflib
import mimetypes
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from canvas_api import get_file, get_page, search_files, update_page
from canvas_http import http_post_json, http_post_multipart_no_auth
from io_utils import load_profile, read_token
import json


def _hesc(s):
    return (s.replace("&", "&amp;").replace('"', "&quot;")
             .replace("<", "&lt;").replace(">", "&gt;"))


def file_link_html(base_url, course_id, file_data):
    """Canvas-native file link paragraph (same form Canvas itself writes)."""
    name = file_data.get("display_name") or file_data.get("filename", "")
    fid = file_data["id"]
    href = (f"{base_url}/courses/{course_id}/files/{fid}"
            f"?verifier={file_data.get('uuid', '')}&amp;wrap=1")
    api_ep = f"{base_url}/api/v1/courses/{course_id}/files/{fid}"
    return (
        f'<p><a class="instructure_file_link instructure_scribd_file '
        f'inline_disabled" title="{_hesc(name)}" href="{href}" '
        f'target="_blank" data-canvas-previewable="false" '
        f'data-api-endpoint="{api_ep}" '
        f'data-api-returntype="File">{_hesc(name)}</a></p>')


def upload_course_file(base_url, token, course_id, path, folder_id,
                       verbose=False):
    """Canvas three-step upload into folder_id, overwriting a same-name file.
    Returns the file dict.  Raises RuntimeError on any failure."""
    path = pathlib.Path(path)
    data = path.read_bytes()
    ctype = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    url = f"{base_url}/api/v1/courses/{course_id}/files"
    pre, _ = http_post_json(url, token, {
        "name": path.name, "size": len(data), "content_type": ctype,
        "parent_folder_id": folder_id, "on_duplicate": "overwrite"})
    upload_url = pre.get("upload_url")
    if not upload_url:
        raise RuntimeError(f"No upload_url in response: {pre}")
    fields = {k: str(v) for k, v in pre.get("upload_params", {}).items()}
    files = {pre.get("file_param", "file"): (path.name, data, ctype)}
    if verbose:
        print(f"  [INFO] uploading {len(data):,} bytes: {path.name}")
    body, _ = http_post_multipart_no_auth(upload_url, fields, files)
    fid = None
    if body:
        try:
            fid = json.loads(body).get("id")
        except ValueError:
            pass
    if fid is None:  # fall back to searching by name in the folder
        hits = [f for f in search_files(base_url, token, course_id, path.name)
                if f.get("folder_id") == folder_id
                and f.get("display_name") == path.name]
        if len(hits) != 1:
            raise RuntimeError(
                f"Upload of {path.name} done but file id not found "
                f"({len(hits)} matches)")
        fid = hits[0]["id"]
    return get_file(base_url, token, course_id, fid)


def replace_h2_section(html, name, new_inner):
    """Replace the content under the <h2>/<h3> heading `name` up to the next heading or EOF.
    Returns (new_html, found)."""
    # Accept <h2> or <h3> headings and singular/plural names (Worksheet/Worksheets):
    # recitation pages differ between instructors and years.
    base = re.escape(name[:-1] if name.endswith("s") else name)
    pat = rf'(<h[23]>\s*(?:<strong></strong>)?{base}s?:?\s*</h[23]>)(.*?)(?=<h[23]>|$)'
    found = [False]

    def _r(m):
        found[0] = True
        return m.group(1) + "\n" + new_inner + "\n"

    return re.sub(pat, _r, html, flags=re.DOTALL | re.IGNORECASE), found[0]


def main():
    ap = argparse.ArgumentParser(
        description="Fill in a Canvas recitation page: upload files and "
                    "write its Readings/Slides/Worksheets/Key sections.")
    ap.add_argument("course_id", type=int)
    ap.add_argument("page_slug")
    ap.add_argument("--date", default=None)
    ap.add_argument("--reading", default=None)
    ap.add_argument("--slides", action="append", default=[])
    ap.add_argument("--worksheet", action="append", default=[])
    ap.add_argument("--key-note", default=None)
    ap.add_argument("--folder-id", type=int, default=None)
    ap.add_argument("--base-url", default=None)
    ap.add_argument("--token", default=None)
    ap.add_argument("--token-file", default=None)
    ap.add_argument("-n", "--dry-run", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    if (args.slides or args.worksheet) and not args.folder_id:
        ap.error("--folder-id is required with --slides/--worksheet")
    for p in args.slides + args.worksheet:
        if not pathlib.Path(p).is_file():
            ap.error(f"no such file: {p}")

    profile = load_profile()
    base_url = (args.base_url or profile.get("base_url") or "").rstrip("/")
    if not base_url:
        ap.error("--base-url required (or base_url in ~/.canvas.api.conf)")
    token = read_token(args.token, args.token_file, profile)

    page = get_page(base_url, token, args.course_id, args.page_slug,
                    verbose=args.verbose)
    old = page.get("body") or ""
    new = old
    print(f"Page      : {page['title']!r}  published={page['published']}")

    if args.date:
        i = new.lower().find("<h2>")
        if i < 0:
            sys.exit("[FAIL] no <h2> in page; cannot place date paragraph")
        new = f"<p>Recitation activities for {_hesc(args.date)}</p>\n" + new[i:]

    sections = []  # (heading, inner html)
    if args.reading:
        sections.append(("Readings", f"<p>{_hesc(args.reading)}</p>"))
    for heading, paths in (("Slides", args.slides),
                           ("Worksheets", args.worksheet)):
        if not paths:
            continue
        inner = ""
        for path in paths:
            name = pathlib.Path(path).name
            if args.dry_run:
                inner += (f'<p>[DRY RUN placeholder link: {_hesc(name)} -- '
                          f'will be uploaded to folder {args.folder_id}]</p>')
            else:
                fd = upload_course_file(base_url, token, args.course_id, path,
                                        args.folder_id, verbose=args.verbose)
                print(f"Uploaded  : {fd['display_name']}  id={fd['id']}")
                inner += file_link_html(base_url, args.course_id, fd)
        sections.append((heading, inner))
    if args.key_note:
        sections.append(("Key", f"<p>{_hesc(args.key_note)}</p>"))

    for heading, inner in sections:
        new, ok = replace_h2_section(new, heading, inner)
        if not ok:
            sys.exit(f"[FAIL] no {heading} section (h2/h3) on the page; "
                     f"nothing written")

    print("---- diff (old -> new) ----")
    sys.stdout.writelines(difflib.unified_diff(
        old.replace("><", ">\n<").splitlines(True),
        new.replace("><", ">\n<").splitlines(True), "old", "new", n=1))
    print()
    if args.dry_run:
        print("[DRY RUN] nothing uploaded, nothing written")
        return
    res = update_page(base_url, token, args.course_id, args.page_slug, new,
                      verbose=args.verbose)
    print(f"Updated   : {base_url}/courses/{args.course_id}/pages/"
          f"{res.get('url')}  published={res.get('published')}")


if __name__ == "__main__":
    main()
