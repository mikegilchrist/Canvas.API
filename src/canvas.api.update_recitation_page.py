# Date:         2026-10-06
# Purpose:      Fill in a Canvas recitation page (BIOL240 style): upload local
#               files to a Canvas folder and write the Readings / Slides /
#               Worksheets / Key sections of the page body.  Recitation pages
#               use <h2> section headings and are addressed by URL slug, not
#               by an S12-style title prefix (see update_lecture_page.py).
#
# Usage:        canvas.api.update_recitation_page.py COURSE_ID PAGE_SLUG
#                   [--date TEXT] [--reading TEXT]
#                   [--slides PATH] [--worksheet PATH]
#                   [--key-note TEXT] [--folder-id ID]
#                   [--base-url URL] [--token-file FILE]
#                   [--dry-run] [--verbose] [--help]
#
# Input:        Canvas course ID, page slug, local files to upload
# Output:       Proposed (dry run) or applied page HTML on stdout.  The page's
#               published state is never changed.
#
# Options:
#   --date TEXT       Replace everything before the first <h2> with
#                     "Recitation activities for TEXT"
#   --reading TEXT    Text for the Readings section
#   --slides PATH     Upload PATH and link it in the Slides section (repeatable)
#   --worksheet PATH  Upload PATH and link it in the Worksheets section (repeatable)
#   --key-note TEXT   Text for the Key section (e.g. "Not yet posted: ...")
#   --folder-id ID    Canvas folder to upload into (required with --slides or
#                     --worksheet)
#   -n, --dry-run     Upload nothing, write nothing; print the proposed body
#   -v, --verbose     Show detailed output
#
# Requirements: Python 3.7+; token with page-edit and file-upload rights;
#               ~/.canvas.api.conf (base_url, token_file)
