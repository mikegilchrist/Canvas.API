# Purpose:      Point the three lecture modules at the 2026 lecture pages, in
#               schedule order.
#
# canvas.lecture.pages.py builds one page per lecture from schedule_2026.tsv.
# The modules still listed the pages inherited from prior years, under the old
# numbering.  This rewires them.
#
# REMOVES MODULE ITEMS, NEVER PAGES.  A module item is a pointer; deleting one
# leaves the page itself untouched and recoverable, which matters because eight
# of the inherited pages carry the only record of which uploaded deck belongs
# to which lecture (MG, 2026-08-18: do not delete the old pages yet).
#
# L01's existing module item is left exactly where it is, in position 1.
#
# The stale exam-scope SubHeaders are removed rather than moved: they were
# placed for the OLD scopes, and 2026 revised them (Exam I L1-9, Exam II
# L10-19, Final L20-26).  Part boundaries and exam boundaries do not coincide
# -- Exam II spans two modules -- so where they belong is a judgement call,
# not something to guess at.
#
# Usage:        canvas.api.lecture.modules.py [--apply] [-v]
# Options:      -a/--apply   perform the writes (default dry run)
#               -v/--verbose show items left alone
