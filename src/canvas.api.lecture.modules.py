import argparse
import csv
import os
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
TSV = None   # set in main(): paths.schedule_tsv in canvas.course.json

# (module id, name it should carry, lectures it holds).  The ranges are the
# Part boundaries in schedule_2026.tsv.
PARTS = []   # set in main(): lecture_modules in canvas.course.json
KEEP_ITEM = {}   # set in main(): keep_module_items


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    global BASE, COURSE, TSV, PARTS, KEEP_ITEM
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    TSV = cfg.path("schedule_tsv")
    PARTS = [(m[0], m[1], range(m[2], m[3] + 1)) for m in cfg.data["lecture_modules"]]
    KEEP_ITEM = {int(k): v for k, v in cfg.data.get("keep_module_items", {}).items()}

    topics = {}
    for r in csv.DictReader(open(TSV), delimiter="\t"):
        if r["lecture"].strip().isdigit():
            topics[int(r["lecture"])] = r["topic"].strip()

    pages = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/pages?per_page=100", tok)
    slug = {p["title"]: p["url"] for p in pages}

    mods = {m["id"]: m for m in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/modules?include[]=items&per_page=100", tok)}

    removed = added = 0
    for mid, name, lectures in PARTS:
        m = mods[mid]
        print(f"\n=== [{mid}] {m['name']}"
              + (f"   -> rename to {name!r}" if m["name"] != name else ""))
        if m["name"] != name and a.apply:
            canvas_http.http_put_json(f"{BASE}/api/v1/courses/{COURSE}/modules/{mid}",
                                      tok, {"module": {"name": name}})
        keep = KEEP_ITEM.get(mid)
        for it in (m.get("items") or []):
            if keep and it.get("page_url") == keep:
                print(f"  KEEP    {it['title'][:52]}  (left in place)")
                continue
            print(f"  {tag}REMOVE  {it['type']:<10} {it['title'][:48]}  (item only)")
            removed += 1
            if a.apply:
                canvas_http.http_delete(
                    f"{BASE}/api/v1/courses/{COURSE}/modules/{mid}/items/{it['id']}", tok)
        pos = 1
        for n in lectures:
            title = f"L{n:02d}: {topics[n]}"
            if keep and slug.get(title) == keep:
                pos += 1
                continue
            u = slug.get(title)
            if not u:
                print(f"  MISSING page for {title!r}; skipped")
                continue
            print(f"  {tag}ADD     pos{pos:>3}  {title[:52]}")
            added += 1
            pos += 1
            if a.apply:
                canvas_http.http_post_json(
                    f"{BASE}/api/v1/courses/{COURSE}/modules/{mid}/items", tok,
                    {"module_item": {"type": "Page", "page_url": u,
                                     "title": title, "position": pos - 1,
                                     "indent": 0}})
    print(f"\n{tag}{removed} item(s) removed, {added} added.  No page was deleted.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
