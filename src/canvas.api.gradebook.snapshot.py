#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.gradebook.snapshot.py
# Version:      1.2.0
# Created:      2026-09-23
# Revised:      2026-10-13
# Purpose:      Keep a copy of the Canvas gradebook before changing it, and
#               prove afterwards that the change touched no grade.
#
# Canvas's own gradebook CSV export is browser-only (the API token gets a
# login page), so this rebuilds it from the REST API: every assignment, every
# submission, and BOTH halves of each checkpointed discussion board.  A blank
# stays blank and 0 stays 0 -- the distinction the DB boards depend on.
#
# Only grade-relevant fields are kept.  The raw API records are ~1.4 KB per
# submission (post text, preview URLs, attachments, and the checkpoint halves
# repeating all of it); a full course was 14.7 MB raw, ~1 MB slim.  --full
# keeps the raw records as well.
#
# STRICTLY READ-ONLY toward Canvas: GET requests only.
#
# Usage:        canvas.api.gradebook.snapshot.py [--course-id N | --course-config FILE] [OPTIONS]
#               canvas.api.gradebook.snapshot.py --compare BEFORE.json AFTER.json
# Output:       canvas.gradebook.snapshot_<year>_<stamp>.json (slim) and .csv
#               (one row per student, one column per assignment and half)
#
# Options:
#       --course-id N    Canvas course id (also --course; else canvas.course.json)
#       --course-config FILE   canvas.course.json to use
#       --year Y         year used in the default output directory
#   -o, --outdir DIR     Output directory (default: config paths.snapshots_dir,
#                        with {year} filled in)
#       --full           Also write the raw API records (_full.json)
#       --compare A B    Report every grade cell that differs between two
#                        snapshots, AND every scored cell whose posted
#                        (student-visible) state changed; exit 1 if any
#                        does.  No Canvas access.
#   -n, --dry-run        List what would be fetched; write nothing
#   -v, --verbose        Print each request
#   -h, --help           Show this help message
#
# Requirements: python3 (stdlib only); canvas_course.py; Canvas token
#
# Session:      Claude Code session (grade estimator / DB block weighting)
# AI Model:     Claude Opus 5.5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5.5
# ============================================================================

import argparse
import csv
import datetime
import json
import os
import sys
import time
import urllib.error
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import canvas_course  # noqa: E402

BASE = None    # "<base_url>/api/v1"; set in main() from canvas.course.json
TOKEN = None   # set in main()

SUB_KEEP = ("user_id", "assignment_id", "score", "entered_score", "grade",
            "entered_grade", "workflow_state", "excused", "late", "missing",
            "late_policy_status", "points_deducted", "posted_at", "graded_at",
            "submitted_at", "grader_id")
HALF_KEEP = ("sub_assignment_tag",) + SUB_KEEP
ASG_KEEP = ("id", "name", "points_possible", "published", "due_at",
            "grading_type", "omit_from_final_grade", "post_manually",
            "assignment_group_id")
TAGS = ("reply_to_topic", "reply_to_entry")

VERBOSE = False


def get(url, tok):
    """GET every page.  Retries only rate limiting; any other error raises,
    so an assignment Canvas refuses is reported, never silently skipped."""
    out = []
    while url:
        for k in range(8):
            try:
                if VERBOSE:
                    print("  GET", url[:140], file=sys.stderr)
                req = urllib.request.Request(
                    url, headers={"Authorization": "Bearer " + tok})
                with urllib.request.urlopen(req, timeout=120) as r:
                    data = json.load(r)
                    link = r.headers.get("Link", "")
                break
            except urllib.error.HTTPError as e:
                body = e.read().decode(errors="replace")[:200]
                if "Rate Limit" not in body or k == 7:
                    raise RuntimeError(f"HTTP {e.code}: {body}")
                time.sleep(15 * (k + 1))
        out += data if isinstance(data, list) else [data]
        url = None
        for part in link.split(","):
            if 'rel="next"' in part:
                url = part[part.find("<") + 1:part.find(">")]
    return out


def slim(rec, keep):
    """Keep only the named fields, and only when set: an absent key reads
    back as None/False through .get(), which is what it was."""
    # Test by IDENTITY: 0 == False in Python, so "not in (None, False)"
    # silently dropped every score of 0 -- turning zeros into blanks, the
    # exact confusion this tool exists to rule out (caught by --compare).
    return {k: rec[k] for k in keep
            if rec.get(k) is not None and rec.get(k) is not False}


def cell(rec):
    """What a gradebook cell shows: EX, a score, or blank (never 0 for
    blank)."""
    if rec is None:
        return ""
    if rec.get("excused"):
        return "EX"
    return "" if rec.get("score") is None else rec["score"]


def cells(snap):
    """{(user, assignment, tag-or-None): cell} for every graded cell."""
    out = {}
    for s in snap["submissions"]:
        out[(s["user_id"], s["assignment_id"], None)] = cell(s)
        for h in s.get("halves") or []:
            out[(s["user_id"], s["assignment_id"],
                 h.get("sub_assignment_tag"))] = cell(h)
    return out


def take(course, outdir, full, dry):
    tok = TOKEN
    groups = get(f"{BASE}/courses/{course}/assignment_groups"
                 f"?include[]=assignments&per_page=50", tok)
    asg = [dict(a, group=g["name"]) for g in groups for a in g["assignments"]]
    print(f"course {course}: {len(asg)} assignments in {len(groups)} groups")
    if dry:
        for a in asg:
            print(f"  would fetch {a['id']}  {a['group'][:24]:<24} {a['name']}")
        print("dry run: nothing written")
        return 0
    students = get(f"{BASE}/courses/{course}/users?enrollment_type[]=student"
                   f"&include[]=enrollments&per_page=100", tok)
    raw, subs, unreadable = [], [], []
    for a in asg:
        try:
            got = get(f"{BASE}/courses/{course}/assignments/{a['id']}"
                      f"/submissions?include[]=sub_assignment_submissions"
                      f"&per_page=100", tok)
        except RuntimeError as e:
            unreadable.append({"id": a["id"], "name": a["name"],
                               "error": str(e)})
            continue
        for s in got:
            s.setdefault("assignment_id", a["id"])
            r = slim(s, SUB_KEEP)
            r["halves"] = [slim(h, HALF_KEEP)
                           for h in s.get("sub_assignment_submissions") or []]
            subs.append(r)
        if full:
            raw += got
    stamp = datetime.datetime.now().strftime("%Y-%m-%dT%H%M")
    year = stamp[:4]
    snap = {"taken_at": stamp, "course": course,
            "assignment_groups": [{k: g.get(k) for k in
                                   ("id", "name", "group_weight", "rules")}
                                  for g in groups],
            "assignments": [dict(slim(a, ASG_KEEP), group=a["group"])
                            for a in asg],
            "students": [{"id": u["id"], "sortable_name": u.get("sortable_name"),
                          "sections": [e.get("course_section_id") for e in
                                       u.get("enrollments", [])]}
                         for u in students],
            "submissions": subs,
            "unreadable_assignments": unreadable}
    os.makedirs(outdir, exist_ok=True)
    stem = os.path.join(outdir, f"canvas.gradebook.snapshot_{year}_{stamp}")
    with open(stem + ".json", "w") as fh:
        json.dump(snap, fh, separators=(",", ":"))
    if full:
        with open(stem + "_full.json", "w") as fh:
            json.dump({"assignments": asg, "students": students,
                       "submissions": raw}, fh)

    idx = cells(snap)
    halves = {(k[1], k[2]) for k in idx if k[2]}
    cols = []
    for a in asg:
        cols.append((a["id"], None, a["name"]))
        cols += [(a["id"], t, f"{a['name']} [{t}]") for t in TAGS
                 if (a["id"], t) in halves]
    with open(stem + ".csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["Student", "ID", "Section"] + [c[2] for c in cols])
        for u in sorted(snap["students"],
                        key=lambda u: u["sortable_name"] or ""):
            w.writerow([u["sortable_name"], u["id"],
                        ";".join(map(str, u["sections"]))]
                       + [idx.get((u["id"], c[0], c[1]), "") for c in cols])

    scored = sum(1 for v in idx.values() if v != "")
    print(f"students {len(students)}  submissions {len(subs)}  "
          f"non-blank cells {scored}")
    print(f"UNREADABLE assignments: {len(unreadable)}")
    for u in unreadable:
        print(f"    {u['id']} {u['name']}: {u['error'][:100]}")
    print(f"wrote {stem}.json ({os.path.getsize(stem + '.json') / 1e6:.2f} MB)")
    print(f"wrote {stem}.csv")
    return 1 if unreadable else 0


def posted(snap):
    """{(user, assignment, tag-or-None): True/False} -- whether a SCORED cell
    is visible to the student.  A score change is not the only way to break a
    gradebook: on 2026-09-23 changing the DB boards' point values un-posted
    296 of 302 grades while every score stayed put, and a score-only compare
    reported "0 cells differ"."""
    out = {}
    for s in snap["submissions"]:
        if s.get("score") is not None:
            out[(s["user_id"], s["assignment_id"], None)] = bool(
                s.get("posted_at"))
        for h in s.get("halves") or []:
            if h.get("score") is not None:
                out[(s["user_id"], s["assignment_id"],
                     h.get("sub_assignment_tag"))] = bool(h.get("posted_at"))
    return out


def compare(a_path, b_path):
    a, b = (json.load(open(p)) for p in (a_path, b_path))
    ca, cb = cells(a), cells(b)
    pa, pb = posted(a), posted(b)
    names = {x["id"]: x["name"] for x in a["assignments"] + b["assignments"]}
    diffs = [(k, ca.get(k, "(absent)"), cb.get(k, "(absent)"))
             for k in sorted(set(ca) | set(cb), key=str)
             if ca.get(k, "(absent)") != cb.get(k, "(absent)")]
    print(f"{a_path}: {len(ca)} cells, {sum(v != '' for v in ca.values())} "
          f"non-blank")
    print(f"{b_path}: {len(cb)} cells, {sum(v != '' for v in cb.values())} "
          f"non-blank")
    for (u, asg, tag), va, vb in diffs:
        print(f"  DIFF user {u}  {names.get(asg, asg)}"
              f"{' [' + tag + ']' if tag else ''}: {va!r} -> {vb!r}")
    print(f"{len(diffs)} cell(s) differ")
    # Posted state, for cells scored in BOTH snapshots (a newly scored cell
    # is already reported above).
    pdiff = [(k, pa[k], pb[k]) for k in sorted(set(pa) & set(pb), key=str)
             if pa[k] != pb[k]]
    by = {}
    for (u, asg, tag), va, vb in pdiff:
        key = (names.get(asg, asg), "posted -> HIDDEN" if va else
               "hidden -> posted")
        by[key] = by.get(key, 0) + 1
    for (name, what), n in sorted(by.items(), key=str):
        print(f"  POSTED {name}: {n} scored cell(s) {what}")
    print(f"{len(pdiff)} scored cell(s) changed posted state")
    return 1 if (diffs or pdiff) else 0


def main():
    global VERBOSE, BASE, TOKEN
    p = argparse.ArgumentParser(
        description="Snapshot the Canvas gradebook (read-only), or compare "
                    "two snapshots cell by cell.")
    canvas_course.add_arguments(p)
    p.add_argument("-o", "--outdir", default=None)
    p.add_argument("--full", action="store_true")
    p.add_argument("--compare", nargs=2, metavar=("BEFORE", "AFTER"))
    p.add_argument("-n", "--dry-run", action="store_true")
    p.add_argument("-v", "--verbose", action="store_true")
    args = p.parse_args()
    VERBOSE = args.verbose
    if args.compare:
        return compare(*args.compare)
    cfg, base, TOKEN = canvas_course.setup(args)
    BASE = base + "/api/v1"
    outdir = args.outdir
    if outdir is None:
        try:
            outdir = cfg.path("snapshots_dir")
        except canvas_course.CourseConfigError as e:
            sys.exit(f"[FAIL] {e}; pass --outdir")
    return take(cfg.course_id, outdir, args.full, args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
