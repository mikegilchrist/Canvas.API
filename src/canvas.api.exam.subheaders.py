# Purpose:      Place the exam-scope SubHeaders in the lecture modules.
#
# Scopes (BIOL240 F2026, from schedule_2026.tsv) are kept in the course config
# (canvas.course.json key exam_subheaders): Exam I L1-9, Exam II L10-19, Final
# L20-26, cumulative with emphasis.  Part boundaries do NOT coincide with
# exam boundaries -- Exam II spans two modules -- so each marker names what
# ENDS and what BEGINS rather than two adjacent headers saying it twice.
#
# canvas.course.json is the one place to edit if a scope moves.  Idempotent.
#
# Usage:        canvas.api.exam.subheaders.py [--course-id N] [--course-config FILE] [--apply]
# Input:        canvas.course.json (exam_subheaders); Canvas API token
# Output:       Stdout: one line per intended change, then a summary
#
# Options:      -a/--apply   perform the writes (default is a DRY RUN)
#               -v/--verbose show items already correct
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http  # noqa: E402
import canvas_course  # noqa: E402

ap = argparse.ArgumentParser(); ap.add_argument("-a", "--apply", action="store_true")
canvas_course.add_arguments(ap)
a = ap.parse_args(); tag = "" if a.apply else "[DRY-RUN] "
cfg, B, tok = canvas_course.setup(a)
C = cfg.course_id

# (module, title, the item title it must sit immediately BEFORE; None = append)
# -- course-specific, read from canvas.course.json "exam_subheaders"
if "exam_subheaders" not in cfg.data:
    sys.exit("[FAIL] no exam_subheaders in %s" % (cfg.source or "course config"))
WANT = [(int(m), title, before) for m, title, before in cfg.data["exam_subheaders"]]
mods = {m["id"]: m for m in canvas_http.paginated_get_all(
    f"{B}/api/v1/courses/{C}/modules?include[]=items&per_page=100", tok)}
for mid, title, before in WANT:
    items = mods[mid].get("items") or []
    if any(i["type"] == "SubHeader" and i["title"].strip() == title for i in items):
        print(f"  ok      [{mid}] already present: {title[:44]}"); continue
    if before is None:
        pos = len(items) + 1
        where = "at the end"
    else:
        m = next((i for i in items if i["title"] == before), None)
        if not m:
            print(f"  MISSING [{mid}] no item titled {before!r}; skipped"); continue
        pos = m["position"]
        where = f"before {before[:34]!r} (pos {pos})"
    print(f"  {tag}ADD  [{mid}] {where}\n           {title}")
    if a.apply:
        canvas_http.http_post_json(
            f"{B}/api/v1/courses/{C}/modules/{mid}/items", tok,
            {"module_item": {"type": "SubHeader", "title": title, "position": pos}})
