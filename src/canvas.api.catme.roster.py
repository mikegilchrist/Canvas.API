#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.catme.roster.py
# Version:      1.2.0
# Created:      2026-08-18
# Revised:      2026-10-13
# Purpose:      Pull the live student roster from Canvas, write it in the
#               column layout CATME's student-list upload expects, and report
#               who has been added and dropped since the previous pull.
#
# WHY THIS EXISTS.  Through F.2025 this was a two-step manual chore: export
# the gradebook from the Canvas web UI by hand, then run
# CATME/Tools/Student.Lists/create.file.for.CATME.upload.sh over the download.
# That shell script cuts fixed COLUMN NUMBERS out of the gradebook export
# (fields 1,2,3,5,6) and rewrites the section with a fixed sed, so it breaks
# silently whenever Canvas changes the export's column order or a section is
# named off-pattern -- and it can only ever see as much of the roster as the
# hand-made export happened to contain.  This asks Canvas directly, by field
# NAME, so the roster is current at the moment it is run and add/drop churn
# during the first weeks costs one command.
#
# ADD/DROP.  Re-running during the add/drop window compares the roster just
# pulled against the most recent previous pull in the same directory and
# writes the DIFFERENCE as its own upload-ready files, so nobody has to eyeball
# two 129-line lists:
#
#   for.catme.add_<date>.csv       enrolled since the last pull -> upload
#   for.catme.drop_<date>.csv      gone since the last pull     -> deactivate
#   for.catme.section_<date>.csv   still enrolled, switched section
#
# Each is written ONLY when it has someone in it, and each carries the same
# header and column layout as the full roster, so the add file can go straight
# into CATME's upload without editing.  Students are matched on CANVAS USER ID,
# not on name or email, so a student who changes their preferred name is a
# change and not a drop-plus-add.  A section switch is called out separately
# because it is neither an add nor a drop, but CATME still has the old section.
#
# OUTPUT FORMAT is deliberately byte-compatible with the F.2025 file that
# CATME accepted (F.2025/CATME/Student.Lists/for.catme_2025-08-19T1431.csv):
#
#   Last, First, ID, Email, Section
#   Abroms, Zoe Joubert,363035,zabroms@vols.utk.edu,012
#
# ID is the CANVAS user id, not the SIS/student number -- that is what the
# 2025 upload carried, and CATME only needs it to be a stable unique key.
#
# EMAIL DOMAIN.  Canvas reports every student's address as @tennessee.edu,
# but the 2025 upload used @vols.utk.edu (the student alias) and CATME's
# survey invitations reached the class.  So @vols.utk.edu is the default and
# the Canvas-reported address is available with --email-domain canvas.  The
# local part is identical either way (verified: 0 of 129 differ).
#
# READ-ONLY.  GET requests only; nothing here writes to Canvas.
#
# Usage:        canvas.api.catme.roster.py [OPTIONS]
# Input:        Canvas REST API; Canvas token (see canvas_course.py);
#               canvas.course.json paths.catme_student_lists (output dir)
# Output:       for.catme_<YYYY-MM-DD>.csv under paths.catme_student_lists,
#               plus the add/drop/section files when they are non-empty
#
# Options:
#       --course-id ID     Canvas course id (alias --course; default from
#                          canvas.course.json)
#       --course-config F  path to canvas.course.json (default: search upward)
#       --year YYYY        year used in the output directory (default: the
#                          config's "year")
#   -o, --output PATH      write somewhere else ('-' for stdout, no diff)
#       --email-domain D   vols (default; or config "catme_email_domain")
#                          | canvas | any literal domain
#       --include-inactive keep inactive/concluded enrollments too
#       --since PATH       diff against this roster instead of the latest
#       --no-diff          write the full roster only
#   -n, --dry-run          report what would be written, write nothing
#   -v, --verbose          per-student detail
#   -h, --help             this message
#
# Requirements: python3, Canvas.API/src on the path, a Canvas API token
#
