import argparse
import datetime
import os
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course   # noqa: E402

BASE = None   # set in main() from canvas.course.json

HEADER = "Last, First, ID, Email, Section"

# A full roster pull.  The trailing underscore keeps this from also matching
# the for.catme.add_ / .drop_ / .section_ files this script writes beside it.
ROSTER_GLOB = "for.catme_*.csv"

# "BIOL240 Section 010" -> "010"; sis "202640-41038-010" -> "010".
SECTION_RE = re.compile(r"(\d+)\s*$")

LAST, FIRST, CID, EMAIL, SECT = range(5)


def section_number(enr, sections):
    """Section as CATME sees it: the trailing digits of the section name.

    Prefer the section's own name over sis_section_id -- the name is what the
    gradebook export carried in 2025, and a section can exist without an SIS
    id (a manually created one does).
    """
    sid = enr.get("course_section_id")
    name = sections.get(sid, "") or enr.get("sis_section_id", "") or ""
    m = SECTION_RE.search(name)
    return m.group(1) if m else name.strip()


def fetch(tok, course, include_inactive, verbose=False):
    states = ["active", "invited"]
    if include_inactive:
        states += ["inactive", "completed"]
    q = "".join(f"&state[]={s}" for s in states)

    secs = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{course}/sections?per_page=100", tok, verbose)
    sections = {s["id"]: s.get("name", "") for s in secs}

    enrs = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{course}/enrollments"
        f"?type[]=StudentEnrollment{q}&per_page=100", tok, verbose)

    emails = {}
    users = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{course}/users"
        f"?enrollment_type[]=student&include[]=email&per_page=100", tok, verbose)
    for u in users:
        if u.get("email"):
            emails[u["id"]] = u["email"]

    return sections, enrs, emails


def rows(sections, enrs, emails, domain, verbose=False):
    """One row per student.  A student enrolled in two sections would appear
    twice in the enrollment list; CATME wants one line per person, so the
    first section seen wins and the duplicate is reported."""
    out, seen, dupes, problems = [], {}, [], []

    for e in enrs:
        u = e.get("user", {})
        uid = u.get("id") or e.get("user_id")
        sortable = (u.get("sortable_name") or "").strip()
        login = (u.get("login_id") or "").strip()

        # Canvas seeds every course with "Student, Test"; it is not a person.
        if sortable == "Student, Test" or u.get("name") == "Test Student":
            continue

        if uid in seen:
            dupes.append((sortable, seen[uid], section_number(e, sections)))
            continue

        if "," in sortable:
            last, first = (p.strip() for p in sortable.split(",", 1))
        else:
            last, first = sortable, ""

        if domain == "canvas":
            email = emails.get(uid, "")
        else:
            email = f"{login}@{domain}" if login else ""

        sect = section_number(e, sections)
        seen[uid] = sect

        if not (last and first and uid and email and sect):
            problems.append(f"{sortable or uid}: "
                            f"last={last!r} first={first!r} id={uid!r} "
                            f"email={email!r} section={sect!r}")

        out.append((last, first, str(uid), email, sect))
        if verbose:
            print(f"  {last}, {first:<24} {uid:>8}  {email:<28} {sect}")

    out.sort(key=lambda r: (r[LAST].casefold(), r[FIRST].casefold()))
    return out, dupes, problems


def render(rows_):
    # Byte-compatible with the 2025 file: ", " between last and first, plain
    # commas elsewhere.  No quoting -- a comma inside a name would corrupt
    # this, which is why check_names() refuses one.
    lines = [HEADER]
    lines += [f"{l}, {f},{i},{e},{s}" for l, f, i, e, s in rows_]
    return "\n".join(lines) + "\n"


def check_names(rows_):
    bad = [r for r in rows_ if any("," in fld or '"' in fld for fld in r)]
    if bad:
        for r in bad:
            print(f"ERROR: unquotable comma/quote in record: {r}", file=sys.stderr)
        sys.exit("refusing to write a file whose fields would be misparsed")


# ---------------------------------------------------------------- add/drop

def read_roster(path):
    """Read a roster this script wrote back into {canvas id: record}.

    Tolerant of the 2025 files, which were produced by the old shell script
    and have the same layout.  A line that does not have exactly 5 fields is
    reported rather than silently dropped -- a roster silently one student
    short would show up as a spurious 'add' on the next run.
    """
    recs, bad = {}, []
    for n, line in enumerate(path.read_text().splitlines(), start=1):
        if n == 1 or not line.strip():
            continue
        f = [x.strip() for x in line.split(",")]
        if len(f) != 5:
            bad.append((n, line))
            continue
        recs[f[CID]] = tuple(f)
    for n, line in bad:
        print(f"WARNING: {path.name}:{n} is not a 5-field record, ignored: "
              f"{line!r}", file=sys.stderr)
    return recs


def latest_roster(directory, exclude):
    """Most recent previous full pull.  Sorted by NAME, not mtime: the stamps
    are ISO so the name sorts chronologically, and mtimes are rewritten by
    every git checkout."""
    cands = sorted(p for p in directory.glob(ROSTER_GLOB)
                   if p.resolve() != exclude.resolve())
    return cands[-1] if cands else None


def diff_rosters(prev, cur):
    """prev/cur are {id: record}.  Matching on the Canvas id means a name
    change is a change, not a drop plus an add."""
    added = [cur[i] for i in cur.keys() - prev.keys()]
    dropped = [prev[i] for i in prev.keys() - cur.keys()]
    moved, renamed = [], []
    for i in cur.keys() & prev.keys():
        if cur[i][SECT] != prev[i][SECT]:
            moved.append((prev[i], cur[i]))
        elif cur[i] != prev[i]:
            renamed.append((prev[i], cur[i]))

    key = lambda r: (r[LAST].casefold(), r[FIRST].casefold())
    added.sort(key=key)
    dropped.sort(key=key)
    moved.sort(key=lambda p: key(p[1]))
    renamed.sort(key=lambda p: key(p[1]))
    return added, dropped, moved, renamed


def name_of(r):
    return f"{r[LAST]}, {r[FIRST]}"


def report_diff(baseline, added, dropped, moved, renamed, prev_n, cur_n):
    print(f"\nsince {baseline.name} ({prev_n} students -> {cur_n}):")
    if not (added or dropped or moved or renamed):
        print("  no changes")
        return
    for label, group in (("ADD ", added), ("DROP", dropped)):
        for r in group:
            print(f"  {label}  {name_of(r):<32} {r[EMAIL]:<28} sect {r[SECT]}")
    for old, new in moved:
        print(f"  SECT  {name_of(new):<32} {new[EMAIL]:<28} "
              f"sect {old[SECT]} -> {new[SECT]}")
    for old, new in renamed:
        print(f"  NAME  {name_of(old)} -> {name_of(new)} "
              f"({old[EMAIL]} -> {new[EMAIL]})")


def out_path(cfg, override=None):
    if override:
        return None if override == "-" else pathlib.Path(override)
    stamp = datetime.date.today().isoformat()
    d = pathlib.Path(cfg.path("catme_student_lists"))
    return d / f"for.catme_{stamp}.csv"


def sibling(path, kind):
    """for.catme_2026-08-25.csv -> for.catme.<kind>_2026-08-25.csv"""
    stem, _, stamp = path.stem.partition("_")
    return path.with_name(f"{stem}.{kind}_{stamp}{path.suffix}")


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Pull the Canvas roster and format it for CATME upload.",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output")
    ap.add_argument("--email-domain", default=None,
                    help="vols (default, or config catme_email_domain) | canvas | a literal domain")
    ap.add_argument("--include-inactive", action="store_true")
    ap.add_argument("--since", help="diff against this roster file")
    ap.add_argument("--no-diff", action="store_true")
    ap.add_argument("-n", "--dry-run", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args(argv)

    global BASE
    cfg, BASE, tok = canvas_course.setup(a)
    a.course = cfg.course_id

    email_domain = a.email_domain or cfg.data.get("catme_email_domain", "vols")
    domain = {"vols": "vols.utk.edu", "utk": "utk.edu"}.get(
        email_domain, email_domain)

    sections, enrs, emails = fetch(tok, a.course, a.include_inactive, a.verbose)
    if a.verbose:
        print(f"{len(sections)} sections, {len(enrs)} student enrollments")

    recs, dupes, problems = rows(sections, enrs, emails, domain, a.verbose)
    check_names(recs)

    for d in dupes:
        print(f"NOTE: {d[0]} enrolled in more than one section "
              f"(kept {d[1]}, dropped {d[2]})", file=sys.stderr)
    for p in problems:
        print(f"WARNING: incomplete record -- {p}", file=sys.stderr)

    text = render(recs)
    try:
        path = out_path(cfg, a.output)
    except canvas_course.CourseConfigError as e:
        sys.exit(f"[FAIL] {e}")

    by_sect = {}
    for r in recs:
        by_sect[r[SECT]] = by_sect.get(r[SECT], 0) + 1
    summary = ", ".join(f"{k}:{v}" for k, v in sorted(by_sect.items()))
    print(f"{len(recs)} students ({summary})")

    if path is None:
        sys.stdout.write(text)
        return 0

    # Work out the add/drop BEFORE writing, so that re-running on a day whose
    # roster file already exists still diffs against the previous pull rather
    # than against the file it is about to overwrite.
    baseline, writes = None, []
    if not a.no_diff:
        if a.since:
            baseline = pathlib.Path(a.since)
            if not baseline.is_file():
                sys.exit(f"ERROR: no such roster: {baseline}")
        else:
            baseline = latest_roster(path.parent, path) if path.parent.is_dir() else None

    if baseline is not None:
        prev = read_roster(baseline)
        cur = {r[CID]: r for r in recs}
        added, dropped, moved, renamed = diff_rosters(prev, cur)
        report_diff(baseline, added, dropped, moved, renamed, len(prev), len(cur))
        # Written only when non-empty: an empty add file in the directory is
        # indistinguishable at a glance from one nobody has looked at yet.
        for kind, group in (("add", added), ("drop", dropped),
                            ("section", [new for _, new in moved])):
            if group:
                writes.append((sibling(path, kind), render(group)))
    elif not a.no_diff:
        print("\nno previous roster in "
              f"{path.parent} -- nothing to compare, this is the baseline")

    if a.dry_run:
        print(f"\n[DRY-RUN] would write {path}")
        for p, _ in writes:
            print(f"[DRY-RUN] would write {p}")
        return 0

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"\nwrote {path}")
    for p, body in writes:
        p.write_text(body)
        print(f"wrote {p}  ({len(body.splitlines()) - 1})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
