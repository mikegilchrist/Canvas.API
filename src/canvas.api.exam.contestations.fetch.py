#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.exam.contestations.fetch.py
# Version:      1.1.0
# Created:      2026-10-01
# Revised:      2026-10-13
# Purpose:      Snapshot the posts on one exam's "Contested Questions" board
#               into a normalized JSON, a readable markdown digest grouped by
#               question number, and a committed _summary.txt, so the
#               contestations can be processed offline -- and re-fetched as
#               often as needed before the decision deadline.
#
# WHY GRAPHQL.  The board has partial anonymity on (students may post
# anonymously).  For an anonymous topic the REST endpoints
# /discussion_topics/<id> and /discussion_topics/<id>/view both return 404,
# so the REST walk used by canvas.db.fetch.py sees nothing.  The Canvas
# GraphQL endpoint does return the entries, flat, with `depth` (1 = a
# thread, 2+ = a reply) and, for anonymous posts, only a per-topic
# pseudonym (`anonymousAuthor`).  Real names of anonymous authors are NOT
# available to this tool and none are requested.
#
# RE-RUNNING.  The current snapshot has one stable name.  Before it is
# overwritten the outgoing copy is moved to Archive/ stamped with ITS fetch
# time, so an edited or deleted post stays recoverable.  Each run also
# diffs against that outgoing copy and marks entries that are new or edited
# since the previous fetch -- the point of running it again before 5pm.
#
# STRICTLY READ-ONLY toward Canvas (one GraphQL query per page, plus one
# REST listing to find the topic).
#
# Question numbers are extracted mechanically from the text: a leading
# "SUBJECT: #26" line, else any "Q26" / "question 26" / "#26" mention.  The
# extraction is a convenience for grouping, not a judgement; entries with no
# number are listed under "no question number found" rather than dropped.
#
# Usage:        canvas.api.exam.contestations.fetch.py [--course-id N]
#               [--course-config FILE] [OPTIONS] EXAM
# Input:        a Canvas course (canvas.course.json: course_id, exam_boards,
#               paths.course_root); Canvas API token
# Output:       <outdir>/contest.posts_<year>_<exam>.json
#               <outdir>/contest.posts_<year>_<exam>.md
#               <outdir>/contest.posts_<year>_<exam>_summary.txt
#               <outdir>/Archive/contest.posts_<year>_<exam>_<stamp>.json
#
# Arguments:
#   EXAM            One | Two | Final  (selects the board by its title)
#
# Options:
#       --topic ID      use this topic id instead of resolving by title
#       --course-id ID  Canvas course id (default: canvas.course.json)
#       --course-config FILE   course config (default: search upward)
#       --year YYYY     year stamp (default: canvas.course.json year)
#   -o, --outdir DIR    output dir (default F.<year>/Exams/<EXAM>/Contestations)
#       --no-archive    do not archive the outgoing snapshot
#   -n, --dry-run       resolve the board and count entries; write nothing
#   -v, --verbose       per-entry detail
#   -h, --help          this message
#
# Requirements: python3 (stdlib only), a Canvas API token, teacher rights
#
