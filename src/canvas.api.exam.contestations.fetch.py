import argparse
import datetime
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import pathlib
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http  # noqa: E402
import canvas_course  # noqa: E402

VERSION = "1.1.0"
BASE = None   # set in main() from canvas.course.json
HERE = None   # course root (paths.course_root); set in main()

# exam -> (board title, short name used in file names): canvas.course.json
# "exam_boards", set in main().  Titles are what the course actually carries;
# unpublished leftovers with the same title exist, so resolution keeps
# published topics only and refuses on ambiguity.
EXAMS = {}

QUERY = """
query($id: ID!, $after: String) {
  legacyNode(_id: $id, type: Discussion) {
    ... on Discussion {
      _id title anonymousState
      discussionEntriesConnection(first: 100, after: $after) {
        nodes {
          _id parentId rootEntryId depth message createdAt updatedAt deleted
          author { _id name }
          anonymousAuthor { shortName id }
        }
        pageInfo { hasNextPage endCursor }
      }
    }
  }
}
"""

def load_strip_html():
    """Reuse the HTML stripper from the board-fetch tool rather than copy it:
    the bodies arrive wrapped in pasted Canvas/AI-chat DOM and that stripper
    is the one already tuned for it.  Found beside this script (Canvas.API) or
    in the course's bin/."""
    here = pathlib.Path(__file__).resolve().parent
    for cand in (here / "canvas.api.db.fetch.py",
                 pathlib.Path(HERE) / "bin" / "canvas.db.fetch.py"):
        if cand.is_file():
            spec = importlib.util.spec_from_file_location("dbfetch", str(cand))
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            return mod.strip_html
    sys.exit("[FAIL] cannot find canvas.api.db.fetch.py (beside this script) "
             "or <course_root>/bin/canvas.db.fetch.py")


def graphql(token, variables):
    req = urllib.request.Request(
        BASE + "/api/graphql",
        data=json.dumps({"query": QUERY, "variables": variables}).encode(),
        method="POST")
    req.add_header("Authorization", "Bearer " + token)
    req.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(req) as resp:
        out = json.load(resp)
    if out.get("errors"):
        sys.exit("GraphQL errors: %s" % json.dumps(out["errors"])[:400])
    return out


def resolve_topic(token, course, exam):
    """Find the published board for EXAM; refuse rather than guess."""
    title = EXAMS[exam][0]
    topics = canvas_http.paginated_get_all(
        "%s/api/v1/courses/%s/discussion_topics?per_page=100" % (BASE, course),
        token)
    hits = [t for t in topics if t.get("title", "").strip() == title
            and t.get("published")]
    if len(hits) != 1:
        ids = [(t["id"], t.get("published")) for t in topics
               if t.get("title", "").strip() == title]
        sys.exit("expected exactly one PUBLISHED topic titled %r, found %d "
                 "(all with that title: %s).  Use --topic ID."
                 % (title, len(hits), ids))
    return hits[0]["id"]


def fetch_entries(token, topic_id, verbose=False):
    nodes, after, meta = [], None, {}
    while True:
        out = graphql(token, {"id": str(topic_id), "after": after})
        d = (out.get("data") or {}).get("legacyNode")
        if not d:
            sys.exit("topic %s not returned by GraphQL (no access, or not a "
                     "discussion)" % topic_id)
        meta = {"title": d["title"], "anonymous_state": d["anonymousState"]}
        conn = d["discussionEntriesConnection"]
        nodes.extend(conn["nodes"])
        if verbose:
            print("  page: +%d entries" % len(conn["nodes"]))
        if not conn["pageInfo"]["hasNextPage"]:
            break
        after = conn["pageInfo"]["endCursor"]
    return meta, nodes


QNUM_PATTERNS = [
    re.compile(r"(?:\bQ(?:uestions?|s)?\.?\s*#?\s*|#\s*)(\d{1,2})\b", re.I),
]


def question_numbers(text):
    """Numbers 1-99 named in the text, in order of first appearance.

    A "SUBJECT: #26" first line is the form most students used, but replies
    and free-form posts mention numbers in running text too, so every match
    is kept; the digest groups a thread by its OWN subject line first.
    """
    seen = []
    for pat in QNUM_PATTERNS:
        for m in pat.finditer(text):
            n = int(m.group(1))
            if 1 <= n <= 99 and n not in seen:
                seen.append(n)
    return seen


def subject_numbers(text):
    m = re.match(r"\s*SUBJECT\s*:\s*(.*?)(?:\s{2,}|$)", text, re.I)
    if not m:
        return None, []
    line = m.group(1)[:120]
    return line, question_numbers(line)


def normalize(nodes, strip_html):
    out = []
    for n in nodes:
        text = strip_html(n.get("message") or "")
        subj, subj_nums = subject_numbers(text)
        a, anon = n.get("author"), n.get("anonymousAuthor")
        out.append({
            "id": n["_id"],
            "parent_id": n.get("parentId"),
            "root_id": n.get("rootEntryId") or n["_id"],
            "depth": n["depth"],
            "kind": "thread" if n["depth"] == 1 else "reply",
            "created_at": n.get("createdAt"),
            "updated_at": n.get("updatedAt"),
            "deleted": bool(n.get("deleted")),
            "author": (a or {}).get("name") or (anon or {}).get("shortName"),
            "author_is_anonymous": bool(anon) and not a,
            "message": n.get("message") or "",
            "text": text,
            "subject_line": subj,
            "question_numbers_in_subject": subj_nums,
            "question_numbers_mentioned": question_numbers(text),
        })
    out.sort(key=lambda r: (r["root_id"] == r["id"] and 0 or 1,
                            r["created_at"] or ""))
    return out


def load_previous(path):
    if not os.path.exists(path):
        return None
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError) as e:
        print("  WARNING: could not read previous snapshot %s: %s (treating "
              "everything as new)" % (path, e), file=sys.stderr)
        return None


def mark_changes(entries, prev):
    """Tag each entry new / edited / unchanged vs the outgoing snapshot.

    Also returns the ids that were in the previous snapshot but are gone now:
    a vanished entry is recorded, not silently absent.
    """
    if prev is None:
        for e in entries:
            e["since_previous"] = "no previous snapshot"
        return []
    old = {e["id"]: e for e in prev.get("entries", [])}
    for e in entries:
        o = old.get(e["id"])
        if o is None:
            e["since_previous"] = "new"
        elif (o.get("updated_at"), o.get("deleted"), o.get("text")) != \
                (e["updated_at"], e["deleted"], e["text"]):
            e["since_previous"] = "edited"
        else:
            e["since_previous"] = "unchanged"
    now = {e["id"] for e in entries}
    return sorted(i for i in old if i not in now)


def group_by_question(entries):
    """thread root id -> question numbers; then question -> list of roots."""
    threads = {e["id"]: e for e in entries if e["kind"] == "thread"}
    by_q, unnumbered = {}, []
    for tid, t in threads.items():
        nums = t["question_numbers_in_subject"] or t["question_numbers_mentioned"]
        if not nums:
            unnumbered.append(tid)
        for n in nums:
            by_q.setdefault(n, []).append(tid)
    return threads, by_q, unnumbered


def render_md(meta, board, entries, vanished):
    threads, by_q, unnumbered = group_by_question(entries)
    replies = {}
    for e in entries:
        if e["kind"] == "reply":
            replies.setdefault(e["root_id"], []).append(e)

    def block(tid):
        t = threads[tid]
        flag = "" if t["since_previous"] in ("unchanged", "no previous snapshot") \
            else " [%s]" % t["since_previous"].upper()
        lines = ["### Thread %s -- %s -- %s%s%s" % (
            tid, t["author"] or "?", t["created_at"] or "?", flag,
            " (DELETED)" if t["deleted"] else ""), "", t["text"], ""]
        for r in sorted(replies.get(tid, []), key=lambda x: x["created_at"] or ""):
            rf = "" if r["since_previous"] in ("unchanged", "no previous snapshot") \
                else " [%s]" % r["since_previous"].upper()
            lines += ["- **Response %s -- %s -- %s%s%s**: %s" % (
                r["id"], r["author"] or "?", r["created_at"] or "?", rf,
                " (DELETED)" if r["deleted"] else "", r["text"]), ""]
        return lines

    out = ["# %s" % meta["title"], "",
           "Fetched %s by canvas.api.exam.contestations.fetch.py v%s.  "
           "Anonymity on this board: %s.  Anonymous authors appear under "
           "their per-topic pseudonym only." % (
               board["fetched_at"], VERSION, meta["anonymous_state"]), ""]
    if vanished:
        out += ["**Entries in the previous snapshot but absent now:** %s"
                % ", ".join(vanished), ""]
    for n in sorted(by_q):
        out += ["## Question %d (%d thread%s)" % (
            n, len(by_q[n]), "" if len(by_q[n]) == 1 else "s"), ""]
        for tid in by_q[n]:
            out += block(tid)
    if unnumbered:
        out += ["## No question number found (%d)" % len(unnumbered), ""]
        for tid in unnumbered:
            out += block(tid)
    return "\n".join(out) + "\n"


def git_head():
    try:
        return subprocess.run(["git", "-C", HERE, "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True).stdout.strip() \
            or "unknown"
    except OSError:
        return "unknown"


def render_summary(meta, board, entries, vanished, paths):
    threads, by_q, unnumbered = group_by_question(entries)
    live = [e for e in entries if not e["deleted"]]
    n_thr = sum(1 for e in live if e["kind"] == "thread")
    n_rep = sum(1 for e in live if e["kind"] == "reply")
    changes = {}
    for e in entries:
        changes[e["since_previous"]] = changes.get(e["since_previous"], 0) + 1
    st = os.stat(paths["json"])
    lines = [
        "Object:        %s" % os.path.relpath(paths["json"], HERE),
        "Produced by:   canvas.api.exam.contestations.fetch.py v%s" % VERSION,
        "Generated:     %s" % board["fetched_at"],
        "Git commit:    %s (script/tree state at generation)" % git_head(),
        "Environment:   python %s" % sys.version.split()[0],
        "Object mtime:  %s, %d bytes" % (
            datetime.datetime.fromtimestamp(st.st_mtime).isoformat(
                timespec="seconds"), st.st_size),
        "",
        "Board:         %s (topic %s, course %s)" % (
            meta["title"], board["topic_id"], board["course"]),
        "Anonymity:     %s" % meta["anonymous_state"],
        "Entries:       %d total; %d threads, %d responses (non-deleted); "
        "%d deleted" % (len(entries), n_thr, n_rep,
                        sum(1 for e in entries if e["deleted"])),
        "Since previous snapshot: %s" % (
            ", ".join("%s=%d" % kv for kv in sorted(changes.items())) or "n/a"),
        "Absent now but present before: %s" % (
            ", ".join(vanished) if vanished else "none"),
        "",
        "Threads per question number (a thread naming several numbers counts "
        "under each):",
    ]
    for n in sorted(by_q):
        lines.append("  Q%-3d %d" % (n, len(by_q[n])))
    lines.append("  no question number found: %d" % len(unnumbered))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(
        description="Snapshot an exam's Contested Questions board to JSON, "
                    "a markdown digest and a summary (read-only).")
    ap.add_argument("exam", nargs="?",
                    help="exam key in canvas.course.json exam_boards (One | Two | Final)")
    ap.add_argument("--topic", type=int, help="topic id (overrides title lookup)")
    ap.add_argument("-o", "--outdir")
    ap.add_argument("--no-archive", action="store_true")
    canvas_course.add_arguments(ap)
    ap.add_argument("-n", "--dry-run", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()
    if not args.exam:
        ap.error("EXAM is required (One, Two or Final)")

    global BASE, HERE, EXAMS
    cfg, BASE, token = canvas_course.setup(args)
    args.course = str(cfg.course_id)
    try:
        HERE = cfg.path("course_root")
    except canvas_course.CourseConfigError as e:
        sys.exit("[FAIL] %s" % e)
    if cfg.year is None:
        sys.exit("[FAIL] no year: pass --year or set \"year\" in the course config")
    args.year = str(cfg.year)
    EXAMS = {k: tuple(v) for k, v in cfg.data.get("exam_boards", {}).items()}
    if args.exam not in EXAMS:
        sys.exit("[FAIL] exam %r not in exam_boards (%s) of %s" % (
            args.exam, ", ".join(sorted(EXAMS)) or "none", cfg.source))
    strip_html = load_strip_html()
    topic_id = args.topic or resolve_topic(token, args.course, args.exam)
    meta, nodes = fetch_entries(token, topic_id, args.verbose)
    entries = normalize(nodes, strip_html)

    short = EXAMS[args.exam][1]
    outdir = args.outdir or os.path.join(
        HERE, "F." + args.year, "Exams", args.exam, "Contestations")
    base = "contest.posts_%s_%s" % (args.year, short)
    paths = {"json": os.path.join(outdir, base + ".json"),
             "md": os.path.join(outdir, base + ".md"),
             "summary": os.path.join(outdir, base + "_summary.txt")}

    prev = load_previous(paths["json"])
    vanished = mark_changes(entries, prev)
    board = {"fetched_at": datetime.datetime.now(datetime.timezone.utc)
             .strftime("%Y-%m-%dT%H:%M:%SZ"),
             "topic_id": topic_id, "course": args.course, "exam": args.exam,
             "script_version": VERSION}

    n_thr = sum(1 for e in entries if e["kind"] == "thread")
    print("%s (topic %s): %d entries (%d threads, %d responses); "
          "anonymity %s" % (meta["title"], topic_id, len(entries), n_thr,
                            len(entries) - n_thr, meta["anonymous_state"]))
    if prev is not None:
        c = {}
        for e in entries:
            c[e["since_previous"]] = c.get(e["since_previous"], 0) + 1
        print("  since previous snapshot (%s): %s; vanished: %d" % (
            prev.get("fetched_at"), c, len(vanished)))
    if args.verbose:
        for e in entries:
            print("  [%s] %s d%d %s %s: %s" % (
                e["id"], e["kind"], e["depth"], e["since_previous"],
                e["author"], e["text"][:80]))
    if args.dry_run:
        print("dry run: would write %s, %s, %s" % (
            paths["json"], paths["md"], paths["summary"]))
        return

    os.makedirs(outdir, exist_ok=True)
    if prev is not None and not args.no_archive:
        arch = os.path.join(outdir, "Archive")
        os.makedirs(arch, exist_ok=True)
        stamp = (prev.get("fetched_at") or "unknown").replace(":", "").replace("-", "")
        dest = os.path.join(arch, "%s_%s.json" % (base, stamp))
        shutil.copy2(paths["json"], dest)
        print("  archived outgoing snapshot -> %s" % os.path.relpath(dest, HERE))

    snapshot = dict(board, title=meta["title"],
                    anonymous_state=meta["anonymous_state"], entries=entries,
                    vanished_since_previous=vanished)
    with open(paths["json"], "w") as f:
        json.dump(snapshot, f, indent=1, ensure_ascii=False)
        f.write("\n")
    with open(paths["md"], "w") as f:
        f.write(render_md(meta, board, entries, vanished))
    with open(paths["summary"], "w") as f:
        f.write(render_summary(meta, board, entries, vanished, paths))
    for k in ("json", "md", "summary"):
        print("  wrote %s" % os.path.relpath(paths[k], HERE))


if __name__ == "__main__":
    main()
