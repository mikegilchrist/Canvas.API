import argparse
import html
import pathlib
import re
import sys
import urllib.parse

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_api      # noqa: E402
import canvas_http     # noqa: E402
import canvas_course   # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json

# (page title, exam name, lectures the exam covers, the Q&A assignment name)
# come from canvas.course.json "exam_qanda_pages" (read in main()).


def link(topic_id, text):
    u = f"{BASE}/courses/{COURSE}/discussion_topics/{topic_id}"
    return (f'<li><a href="{u}" data-api-endpoint="{BASE}/api/v1/courses/'
            f'{COURSE}/discussion_topics/{topic_id}" '
            f'data-api-returntype="Discussion">{html.escape(text)}</a></li>')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-a", "--apply", action="store_true")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    global BASE, COURSE
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    if "exam_qanda_pages" not in cfg.data:
        sys.exit("[FAIL] no exam_qanda_pages in %s" % (cfg.source or "course config"))
    PAGES = [(p["page"], p["exam"], range(p["first"], p["last"] + 1), p["qanda"])
             for p in cfg.data["exam_qanda_pages"]]

    topics = canvas_api.get_discussion_topics(BASE, tok, COURSE)
    by_title = {t["title"]: t for t in topics}
    topics_lec = {}
    for t in topics:
        m = re.match(r"L(\d\d):", t["title"])
        if m:
            topics_lec[int(m.group(1))] = t

    for page, exam, lectures, qanda in PAGES:
        q = next((t for t in topics if qanda in t["title"]), None)
        if not q:
            print(f"  MISSING Q&A board {qanda!r}; {page} skipped"); continue
        items = []
        for n in lectures:
            t = topics_lec.get(n)
            if not t:
                print(f"  MISSING board for L{n:02d}"); continue
            items.append(link(t["id"], t["title"]))
        body = (f"<h3>Pre-Exam Q&amp;A for {exam}</h3>"
                f"<p>Bring questions. Post them ahead of time so your TA can "
                f"prepare.</p>"
                f"<h3>Post your questions here</h3>"
                f"<ul>{link(q['id'], q['title'])}</ul>"
                f"<h3>Team discussion boards covered by {exam}</h3>"
                f"<p>These are the boards your team has been posting to for "
                f"this exam's material.</p>"
                f"<ul>{''.join(items)}</ul>")
        print(f"  {tag}REWRITE {page}: Q&A board + {len(items)} covered board(s) "
              f"(L{min(lectures):02d}-L{max(lectures):02d})")
        if a.apply:
            canvas_http.http_put_json(
                f'{BASE}/api/v1/courses/{COURSE}/pages/'
                f'{urllib.parse.quote(page, safe="")}', tok,
                {"wiki_page": {"body": body}})
    return 0


if __name__ == "__main__":
    sys.exit(main())
