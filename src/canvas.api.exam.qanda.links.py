# Created:      2026-08-19
# Revised:      2026-10-13
# Purpose:      Rebuild the two Pre-Exam Q&A recitation pages so their board
#               lists match the 2026 exam scopes.
#
# R06 and R12 each carry two link lists: the Q&A board students post questions
# to, and the team discussion boards the exam covers.  The second list was
# inherited and listed the OLD scopes -- R06 was missing L05 and wrongly
# included L10, R12 was missing L10 and L13 and wrongly included L20 and L21.
#
# The link TARGETS were already correct, because the boards were renumbered in
# place and a Canvas topic id survives a retitle; only the link TEXT and the
# membership of the lists were stale.  Both are regenerated here from the live
# board titles, so the page cannot drift from the boards again.
#
# Post-exam Q&A pages (R07, R13) deliberately carry no such links (MG,
# 2026-08-19): the exam is over, there is nothing to revise for.
#
# Usage:        canvas.api.exam.qanda.links.py [--course-id N] [--course-config FILE] [--apply]
# Input:        canvas.course.json (exam_qanda_pages); Canvas API token
# Options:      -a/--apply   perform the writes (default is a DRY RUN)
#
