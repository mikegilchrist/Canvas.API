import argparse
import csv
import html
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import canvas_course  # noqa: E402

VERSION = "1.1.0"
BASE = None    # set in main(): <base_url>/api/v1

REPOS = {}     # set in main(): repos in canvas.course.json
TARGETS = []   # set in main(): the keys of REPOS

# Headings on a Canvas page that end the Reading block.
STOP = ["Slides", "Worksheet", "Clickers", "Optional", "Handout", "Video",
        "Problems", "Key", "Notes", "Activity", "Practice", "Listening",
        "Recording", "Assignment", "Due"]


class PullError(Exception):
    pass


# --------------------------------------------------------------------------
# Canvas, read-only
# --------------------------------------------------------------------------

def get(path, tok, params=None, tries=3):
    """One GET, with the Link header followed by the caller."""
    url = f"{BASE}/{path.lstrip('/')}"
    if params:
        url += "?" + "&".join(f"{k}={v}" for k, v in params.items())
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {tok}"})
    for n in range(tries):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.load(r), r.headers.get("Link", "")
        except urllib.error.HTTPError as exc:
            if exc.code in (403, 500, 502, 503) and n < tries - 1:
                time.sleep(2 ** n)
                continue
            raise PullError(f"GET {path} -> HTTP {exc.code}")
        except urllib.error.URLError as exc:
            if n < tries - 1:
                time.sleep(2 ** n)
                continue
            raise PullError(f"GET {path} -> {exc.reason}")
    raise PullError(f"GET {path} failed")


def get_all(path, tok, params=None):
    """Follow rel=next so a course with >100 of anything is not truncated."""
    out, page = [], 1
    while True:
        p = dict(params or {})
        p.update({"per_page": 100, "page": page})
        data, link = get(path, tok, p)
        if not isinstance(data, list):
            raise PullError(f"{path}: expected a list, got {type(data).__name__}")
        out += data
        if 'rel="next"' not in link or not data:
            return out
        page += 1


# --------------------------------------------------------------------------
# parsing
# --------------------------------------------------------------------------

def text_of(body):
    t = re.sub(r"<[^>]+>", "\n", body or "")
    t = html.unescape(html.unescape(t))
    return [x.strip() for x in t.split("\n") if x.strip()]


def reading_of(body):
    """The Reading block of a Canvas page, flattened to one line."""
    lines = text_of(body)
    for i, ln in enumerate(lines):
        if ln.rstrip(":").strip().lower() in ("reading", "readings"):
            buf = []
            for nxt in lines[i + 1:]:
                if any(nxt.startswith(s) for s in STOP):
                    break
                buf.append(nxt)
            return " ".join(buf).strip()
    return ""


def sections(text):
    """The set of book sections a reading names, ranges expanded.

    Compares MEANING rather than wording: the schedule says "Ch 8.3-8.4" and
    Canvas says "Ch 8.3 - 8.4 (skim)", and those should not read as a
    difference.  Only same-chapter ranges are expanded; "Ch 4.1-5.2" would be
    a cross-chapter span and is left as its two endpoints.
    """
    out, s, spans = set(), text or "", []
    for m in re.finditer(r"(\d+)\.(\d+)\s*-\s*(?:(\d+)\.)?(\d+)(?![\d.])", s):
        c1, s1, c2, s2 = m.group(1), int(m.group(2)), m.group(3), int(m.group(4))
        if c2 in (None, c1):
            for k in range(min(s1, s2), max(s1, s2) + 1):
                out.add(f"{c1}.{k}")
        else:
            out.add(f"{c1}.{s1}")
            out.add(f"{c2}.{s2}")
        spans.append(m.span())
    # Bare sections are whatever is left OUTSIDE a matched range.  Excluding
    # them with a lookahead instead threw away the 6.6 in "Ch 6.0-6.4, 6.6 -
    # Note of the multiple mating techniques...", because the prose dash after
    # it looked like the start of a range.
    for m in re.finditer(r"(?<![\d.])(\d+)\.(\d+)(?![\d.])", s):
        if any(a <= m.start() < b for a, b in spans):
            continue
        out.add(f"{m.group(1)}.{m.group(2)}")
    return out


def lecture_no(url):
    m = re.match(r"^l(\d+)", url or "")
    return int(m.group(1)) if m else None


# --------------------------------------------------------------------------
# targets
# --------------------------------------------------------------------------

def pull_pages(tok, course, prefix, verbose=False):
    index = get_all(f"courses/{course}/pages", tok)
    want = [p for p in index if re.match(rf"^{prefix}\d", p.get("url", ""))]
    rows = []
    for p in sorted(want, key=lambda x: x["url"]):
        d, _ = get(f"courses/{course}/pages/{p['url']}", tok)
        r = reading_of(d.get("body"))
        rows.append({"page": p["url"], "title": (d.get("title") or "").strip(),
                     "reading": r, "published": str(d.get("published", "")),
                     "updated_at": (d.get("updated_at") or "")[:10]})
        if verbose:
            print(f"    {p['url']:<52} {r[:48]}")
        time.sleep(0.05)
    return rows, ["page", "title", "reading", "published", "updated_at"]


def pull_homework(tok, course, verbose=False):
    groups = {g["id"]: g["name"]
              for g in get_all(f"courses/{course}/assignment_groups", tok)}
    rows = []
    for a in get_all(f"courses/{course}/assignments", tok):
        rows.append({"id": a.get("id"), "name": (a.get("name") or "").strip(),
                     "group": groups.get(a.get("assignment_group_id"), ""),
                     "points": a.get("points_possible"),
                     "due_at": (a.get("due_at") or "")[:16].replace("T", " "),
                     "published": str(a.get("published", "")),
                     "updated_at": (a.get("updated_at") or "")[:10]})
        if verbose:
            print(f"    {rows[-1]['name'][:52]:<54} {rows[-1]['due_at']}")
    rows.sort(key=lambda r: (r["group"], r["name"]))
    return rows, ["id", "name", "group", "points", "due_at", "published",
                  "updated_at"]


def pull(target, tok, course, verbose=False):
    if target == "lectures":
        return pull_pages(tok, course, "l", verbose)
    if target == "recitations":
        return pull_pages(tok, course, "r", verbose)
    if target == "homework":
        return pull_homework(tok, course, verbose)
    raise PullError(f"unknown target {target!r}")


def out_path(target, year, override=None):
    if override:
        return override
    d = REPOS[target].format(year=year)
    return os.path.join(d, f"canvas.{target}_{year}.tsv")


def write_tsv(rows, cols, path):
    """Sorted, one row per item, so a git diff is about Canvas and not order."""
    d = os.path.dirname(path)
    if d and not os.path.isdir(d):
        raise PullError(f"no such directory: {d}")
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, cols, delimiter="\t", extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    return path


# --------------------------------------------------------------------------
# --check: does the schedule agree with the site?
# --------------------------------------------------------------------------

def check(rows, schedule, verbose=False):
    """Compare readings by book section, per lecture number.

    Canvas splits some lectures the schedule does not (L10a/L10b, L16a/L16b),
    so pages sharing a number are merged before comparing.  Part III is
    numbered differently on the two sides, which this reports rather than
    guesses at.
    """
    with open(schedule, newline="", encoding="utf-8") as fh:
        sched = list(csv.DictReader(fh, delimiter="\t"))
    by_num = {}
    for r in rows:
        n = lecture_no(r["page"])
        if n is None:
            continue
        by_num.setdefault(n, {"pages": [], "secs": set()})
        by_num[n]["pages"].append(r["page"])
        by_num[n]["secs"] |= sections(r["reading"])

    diffs = []
    for s in sched:
        if not s.get("lecture"):
            continue
        n = int(s["lecture"])
        want = sections(s["readings"])
        if n not in by_num:
            diffs.append((n, s["topic"], want, None, "no Canvas page", []))
            continue
        got, pages = by_num[n]["secs"], by_num[n]["pages"]
        if want != got:
            why = "differs" if len(pages) == 1 else \
                f"differs, but {len(pages)} Canvas pages share L{n}"
            diffs.append((n, s["topic"], want, got, why, pages))
        elif verbose:
            print(f"    L{n:<3} ok  {sorted(want)}")
    seen = {int(s["lecture"]) for s in sched if s.get("lecture")}
    extra = sorted(set(by_num) - seen)
    return diffs, extra


def fmt(secs):
    return ", ".join(sorted(secs, key=lambda x: [int(y) for y in x.split(".")])) \
        if secs else "(none)"


# --------------------------------------------------------------------------

def main(argv=None):
    global BASE, REPOS, TARGETS
    ap = argparse.ArgumentParser(
        description="Snapshot the live Canvas course into tracked TSVs "
                    "(read-only).")
    ap.add_argument("targets", nargs="*", default=None,
                    help="any key of repos in canvas.course.json (default: all)")
    canvas_course.add_arguments(ap)
    ap.add_argument("-o", "--output")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--schedule")
    ap.add_argument("-n", "--dry-run", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args(argv)
    cfg, base, tok = canvas_course.setup(a)
    BASE = base + "/api/v1"
    a.course = cfg.course_id
    a.year = cfg.year
    REPOS = {k: (v if isinstance(v, str) else v[0]) for k, v in cfg.data.get("repos", {}).items()}
    REPOS = {k: os.path.expanduser(v) for k, v in REPOS.items()}
    TARGETS = list(REPOS)

    targets = a.targets or TARGETS
    bad = [t for t in targets if t not in TARGETS]
    if bad:
        raise PullError(f"unknown target(s): {', '.join(bad)}")
    if a.output and len(targets) != 1:
        raise PullError("-o takes exactly one target")

    if a.dry_run:
        print(f"--dry-run: course {a.course}, read-only, would fetch and write")
        for t in targets:
            print(f"  {t:<12} -> {out_path(t, a.year, a.output)}")
        return 0

    rc = 0
    for t in targets:
        rows, cols = pull(t, tok, a.course, a.verbose)
        print(f"{t}: {len(rows)} item(s) from course {a.course}")

        if a.check:
            if t == "homework":
                print("  --check compares readings; skipping homework")
                continue
            sched = a.schedule or cfg.path("schedule_tsv")
            if not os.path.exists(sched):
                raise PullError(f"no schedule at {sched}")
            diffs, extra = check(rows, sched, a.verbose)
            for n, topic, want, got, why, pages in diffs:
                rc = 1
                print(f"  L{n} {topic[:44]}: {why}")
                print(f"       schedule: {fmt(want)}")
                if got is not None:
                    print(f"       canvas  : {fmt(got)}")
                    # Name the pages that fed this row.  The join is by
                    # lecture NUMBER, and the two sides do not always agree on
                    # numbering, so the reader has to be able to see when the
                    # comparison is apples-to-oranges rather than a real
                    # difference in what was assigned.
                    print(f"       from    : {', '.join(pages)}")
            if extra:
                print(f"  Canvas pages with no schedule lecture: "
                      f"{', '.join('L%d' % n for n in extra)}")
            if not diffs and not extra:
                print("  readings agree with the schedule")
            continue

        p = write_tsv(rows, cols, out_path(t, a.year, a.output))
        print(f"  wrote {p}")
    return rc


if __name__ == "__main__":
    try:
        sys.exit(main())
    except PullError as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(2)
