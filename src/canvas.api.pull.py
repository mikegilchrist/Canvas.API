# Version:      1.1.0
# Created:      2026-08-12
# Revised:      2026-10-13
# Purpose:      Snapshot what is actually posted on the Canvas course into
#               tracked TSVs, and check the schedule against it.
#
# WHY THIS EXISTS.  The .imscc cartridge was imported once and is now frozen,
# so every edit MG makes on the Canvas site afterwards lives only on Canvas
# and is invisible to version control.  That is how the schedule and the site
# drift apart without anyone noticing: on 2026-08-12 a comparison against the
# cartridge reported that Ch 8.4 was assigned nowhere, when in fact the live
# site had already split L14/L15 and assigned it.  The cartridge was a stale
# reference and there was nothing in the repo that was not.
#
# This pulls the live state into a committed file, so `git diff` shows what
# changed on Canvas since the last pull, and --check reports where the
# schedule and the site disagree about readings.
#
# STRICTLY READ-ONLY.  It issues GET requests and nothing else; there is no
# code path here that writes to Canvas.  Course content is edited on the site
# by hand, and this only ever observes it.
#
# One tool, three targets, because the Canvas plumbing (token, pagination,
# retries) should exist once.  //CLAUDE.md already warns that the per-activity
# copies of rollover.year.sh in the sibling repos have to be kept in sync;
# this does not add a third instance of that problem.  Each target still
# writes its snapshot INTO the repo that owns the material:
#
#   lectures     course_biol240        F.YYYY/Syllabus/
#   recitations  discussions_biol240   YYYY/          (the R## pages)
#   homework     homework_biol240      YYYY/          (Canvas assignments)
#
# Usage:        canvas.api.pull.py [OPTIONS] [TARGET ...]
# Input:        Canvas REST API; token from ~/.api/canvas_token
# Output:       canvas.<target>_<year>.tsv in the owning repo
#
# Options:
#       --course ID     Canvas course id (default: 261062, Fall 2026)
#       --year YYYY     year stamp used in output names (default: 2026)
#   -o, --output PATH   write one target somewhere else
#       --check         compare readings against the schedule TSV, write
#                       nothing; exits 1 if anything differs
#       --schedule PATH schedule TSV for --check
#   -n, --dry-run       report what would be fetched and written
#   -v, --verbose       per-item detail
#   -h, --help          this message
