# Purpose:      Send a Canvas Conversations message to students, groups or staff
#
# Writes a message that recipients see as coming from the authenticated user.
# Intended for course correspondence that should live in Canvas rather than
# email -- submission queries, missing-work notes, group follow-ups.
#
# ALWAYS run with --dry-run first and read the rendered body.  A sent
# conversation cannot be recalled, and it goes out over the token owner's name.
#
# Recipients may be given as bare Canvas user ids, as group_<id> for a whole
# group, or as course_<id> for a whole course.  Resolve names to ids with
# canvas.api.list_courses.py or the /users endpoint before calling this.
#
# Usage:        send_message.py --subject S --body-file F --to ID [--to ID ...]
#                   [--course-id N] [--base-url URL]
#                   [--token TOKEN | --token-file FILE]
#                   [--separate] [--dry-run] [--verbose] [--help]
#
# Input:        Canvas API token; a plain-text file holding the message body
# Output:       Stdout: the rendered message and the resolved recipient list;
#               on send, the created conversation id
#
# Options:
#   --subject S       Message subject (required)
#   --body-file F     File containing the message body (required; use - for stdin)
#   --to ID           Recipient; repeatable. Bare id, group_<id>, or course_<id>
#   --course-id N     Course context, so the message files under that course
#   --separate        Send individual copies instead of one shared thread.
#                     Recipients then cannot see each other (like Bcc).
#   --base-url URL    Canvas instance URL (or base_url in ~/.canvas.api.conf)
#   --token TOKEN     Canvas API token (inline)
#   --token-file FILE Path to token file
#   -n, --dry-run     Render and resolve recipients; send nothing
#   -v, --verbose     Show the API request body
#   -h, --help        Show this help message
#
# Requirements:
#   - Python 3.7+
#   - Canvas API token for the account the message should come from
