# Script:       canvas.api.clear_late_status.py
# Version:      1.0.0
# Created:      2026-09-08
# Revised:      2026-09-08
# Purpose:      Clear the late flag on submissions whose lateness was waived
#
# Canvas computes `late` from submitted_at against due_at, and that field is
# NOT writable.  What IS writable is `late_policy_status`; setting it to
# "none" tells Canvas to apply no late deduction, which is what an instructor
# means by "the late penalty is waived".
#
# Written for HW01 F.2026, where three teams were given an extension after
# missing files were found: the work arrived on time by the agreed date, and
# Canvas flagging it late would take marks the instructor had already excused.
#
# TOUCHES STUDENT GRADE RECORDS.  It refuses to run without --apply, prints
# every change it would make first, and only ever touches submissions it was
# explicitly asked about -- by group name or by user id.  It never changes a
# grade, only the late-policy status.
#
# Usage:        clear_late_status.py COURSE_ID ASSIGNMENT_ID --base-url URL
#                   [--token-file FILE] [--group NAME]... [--user ID]...
#                   [--status none|late|missing|extended]
#                   [--apply] [--verbose] [--help]
# Input:        Canvas API
# Output:       A line per submission changed; a summary
#
# Options:
#   --base-url URL      Canvas instance URL (required)
#   --token-file FILE   File holding the API token
#   --group NAME        Canvas group (team) to clear, repeatable
#   --user ID           Canvas user id to clear, repeatable
#   --status VALUE      Status to set (default: none = no late penalty)
#   --apply             Actually write.  Without it, nothing is sent.
#   -v, --verbose       Show submissions considered but not changed
#   -h, --help          Show this help message
#
# Requirements:
#   - Python 3.7+, the canvas_http helper in this directory
#
# Session:      grading.interface.for.TAs
