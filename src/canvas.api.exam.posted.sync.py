#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.exam.posted.sync.py
# Version:      1.1.0
# Created:      2026-08-28
# Revised:      2026-10-13
# Purpose:      Make the Canvas course agree with F.2026/Exams/*/posted/ --
#               one questions PDF and one key per exam, named canonically.
#
# posted/ is the record of WHICH version of each prior-year exam is on Canvas
# (built by exams.link.prior.years.py from the posted.q / posted.key rows of
# exams.prior.manifest.tsv).  This script is the other half: it compares each
# Canvas file to the symlink that claims to describe it and reconciles them.
#
#   name differs   -> rename the Canvas file.  A rename KEEPS the file id, so
#                     the page links do not break.  The link TEXT is a
#                     separate copy and is deliberately left stale for now.
#   bytes differ   -> re-upload, unless the exam is in KEEP_CANVAS below.
#
# KEEP_CANVAS exists because "the tree and Canvas disagree" does not always
# mean the tree is right.  exam.2.18's posted build fixes a running header
# that still reads "BIOL240 Exam I" in every copy in the tree, so overwriting
# it with the local file would reintroduce the typo.  The 2018 final and the
# 2018 exam.3 key are different compiles of the same source that render
# identically -- checked page by page -- so replacing them would churn a
# student-facing file for nothing.
#
# HOLD exists for an exam that must NOT be synced yet: 2025 Exam I has
# corrected questions but no key rebuilt against them (the key still carries
# the as-given Q31/Q32 order), so Canvas keeps the self-consistent as-given
# pair until the key is rebuilt.
#
# Usage:        canvas.api.exam.posted.sync.py [--course-id N] [--course-config FILE] [--apply] [-v]
# Input:        canvas.course.json (folders.exams, paths.exams_dir, paths.course_root,
#               exam_posted_sync); Canvas API token
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import hashlib
import json
import mimetypes
import pathlib
import re
import sys
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http      # noqa: E402
import canvas_course    # noqa: E402

VERSION = "1.2.0"
BASE = COURSE = None        # set in main() from canvas.course.json
EXAMS_FOLDER = None
ROOT = None
POSTED = []

# KEEP_CANVAS (exam stems whose Canvas bytes are deliberately NOT replaced, and
# why) and HOLD (exams not to sync at all, and the Canvas name they keep
# meanwhile) are course-specific and live in canvas.course.json under
# "exam_posted_sync".  Reasons for the BIOL240 entries:
#   exam.2_2018.key.pdf: the posted build fixes a running header that still
#     reads "BIOL240 Exam I" in every copy in the tree, so overwriting it with
#     the local file would reintroduce the typo.
#   exam.3_2018.key.pdf: a different compile of the same source that renders
#     identically -- replacing it would churn a student-facing file for nothing.
# 2025 Exam I was held until 2026-08-28, when its key was rebuilt and verified
# to align 32/32.  An empty HOLD is the normal state.
KEEP_CANVAS = {}
HOLD = {}


def canvas_files(tok):
    fs = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/folders/{EXAMS_FOLDER}/files?per_page=100", tok)
    return {f["display_name"]: f for f in fs}


def fetch(f):
    return urllib.request.urlopen(f["url"]).read()


def upload(tok, path, name):
    data = path.read_bytes()
    ctype = mimetypes.guess_type(name)[0] or "application/pdf"
    init, _ = canvas_http.http_post_json(
        f"{BASE}/api/v1/courses/{COURSE}/files", tok,
        {"name": name, "size": len(data), "content_type": ctype,
         "on_duplicate": "overwrite", "parent_folder_id": EXAMS_FOLDER})
    body, hdrs = canvas_http.http_post_multipart_no_auth(
        init["upload_url"], init.get("upload_params", {}),
        {"file": (name, data, ctype)})
    f = json.loads(body) if body else None
    if not f or "id" not in f:
        loc = dict(hdrs or {}).get("Location")
        r = canvas_http.http_get_json(loc, tok)
        f = r[0] if isinstance(r, tuple) else r
    canvas_http.http_put_json(f"{BASE}/api/v1/files/{f['id']}", tok,
                              {"locked": False, "hidden": False})
    return f


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--version", action="version", version=VERSION)
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    global BASE, COURSE, EXAMS_FOLDER, ROOT, POSTED, KEEP_CANVAS, HOLD
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    try:
        EXAMS_FOLDER = cfg.folder_id("exams")
        ROOT = pathlib.Path(cfg.path("course_root"))
        exams_dir = pathlib.Path(cfg.path("exams_dir"))
    except canvas_course.CourseConfigError as e:
        sys.exit(f"[FAIL] {e}")
    ps = cfg.data.get("exam_posted_sync", {})
    POSTED = [exams_dir / d / "posted" for d in ps.get("posted_subdirs", [])]
    KEEP_CANVAS = dict(ps.get("keep_canvas", {}))
    HOLD = dict(ps.get("hold", {}))
    if not POSTED:
        sys.exit("[FAIL] no exam_posted_sync.posted_subdirs in "
                 f"{cfg.source or 'course config'}")
    have = canvas_files(tok)
    print(f"canvas.api.exam.posted.sync.py {VERSION}"
          f"{'' if a.apply else '  [DRY RUN]'}\n")

    renames = replaces = ok = held = kept = 0
    for d in POSTED:
        for link in sorted(d.iterdir()):
            name = link.name
            target = link.resolve()
            want = target.read_bytes()
            wmd5 = hashlib.md5(want).hexdigest()

            if name in HOLD:
                cur = HOLD[name]
                state = "present" if cur in have else "MISSING"
                print(f"  HOLD    {name:32s} Canvas keeps {cur} ({state})")
                held += 1
                continue

            f = have.get(name)
            if f is None:
                # find it under whatever name it currently carries.  The
                # course tree renamed exams to <exam>_<YYYY> on 2026-08-28, so
                # a file uploaded before that is still called <exam>.<YY> --
                # plus the historical oddments (-1, -as.given) that the same
                # exam picked up over the years.
                def _aliases(n):
                    m = re.match(r'^(midterm\.[123]|final)_(\d{4})(.*)$', n)
                    out = {n}
                    if m:
                        legacy = f"{m.group(1)}.{m.group(2)[2:]}{m.group(3)}"
                        out.add(legacy)
                        stem, _, ext = legacy.rpartition(".")
                        out.add(f"{stem}-1.{ext}")
                        out.add(legacy.replace(".pdf", "-as.given.pdf"))
                        out.add(legacy.replace(".key.pdf", "-as.given.key.pdf"))
                    return out
                want_any = _aliases(name)
                cands = [n for n in have if n in want_any and n != name]
                if len(cands) != 1:
                    print(f"  ?? {name}: no Canvas file and "
                          f"{len(cands)} rename candidates {cands}")
                    continue
                old = cands[0]
                f = have[old]
                print(f"  RENAME  {old:32s} -> {name}   (file {f['id']})")
                if a.apply:
                    canvas_http.http_put_json(f"{BASE}/api/v1/files/{f['id']}",
                                              tok, {"name": name})
                renames += 1

            got = fetch(f)
            if hashlib.md5(got).hexdigest() == wmd5:
                ok += 1
                if a.verbose:
                    print(f"  ok      {name:32s} matches {target.name}")
                continue
            if name in KEEP_CANVAS:
                print(f"  KEEP    {name:32s} Canvas bytes differ, kept: "
                      f"{KEEP_CANVAS[name]}")
                kept += 1
                continue
            print(f"  REPLACE {name:32s} {len(got):>9,}B -> "
                  f"{len(want):>9,}B  from {target.relative_to(ROOT)}")
            if a.apply:
                nf = upload(tok, target, name)
                print(f"            uploaded, file id {nf['id']}"
                      f"{' (same id)' if nf['id'] == f['id'] else ''}")
            replaces += 1

    print(f"\n{ok} already correct, {renames} rename(s), {replaces} replace(s), "
          f"{kept} kept on purpose, {held} held")
    if not a.apply:
        print("DRY RUN -- nothing written.  Re-run with --apply.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
