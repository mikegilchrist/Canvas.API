#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.deadline.events.py
# Version:      1.3.0
# Created:      2026-08-18
# Revised:      2026-10-13
# Purpose:      Show course deadlines on the Canvas calendar while the
#               assignments behind them are still unpublished.
#
# An UNPUBLISHED assignment is invisible to students, due date and all, so the
# printed schedule lists deadlines Canvas does not show.  A calendar event is
# visible regardless, so this mirrors each deadline as an event -- and REMOVES
# that event once its assignment goes live, so nothing is ever listed twice.
#
# A homework event is titled "Team Homework 01" and says which lectures it is
# EXPECTED to cover, plus the fact that one submission per team is enough.
# Expected is the operative word: the class routinely runs behind its own
# schedule, and the real assignment supersedes this placeholder the moment it
# is published.  The lecture range is not hand-listed here -- it is read from
# the hw_posted column ("HW01:L1-3") and the topics from that lecture's row,
# so the calendar cannot drift from the printed schedule.
#
# Titles are also how the script recognizes its own work.  Two earlier title
# forms -- "HW01 due (deadline)" and a bare "HW01" -- are recognized too, and
# replaced.
#
# Deadlines are mirrored per DEADLINE, not per assignment: the 26 discussion
# boards share 6 block dates, so they yield 6 events, not 26.
#
# Idempotent: every run reconciles the calendar against the current published
# state.  Run it again after publishing anything.
#
# Usage:        canvas.api.deadline.events.py [--course-id ID] [--course-config FILE]
#                                       [--year YYYY] [--apply] [-v]
# Input:        the schedule TSV named by canvas.course.json paths.schedule_tsv;
#               optional_homework (list of HW numbers) in the same file;
#               Canvas token (see canvas_course.py)
# Output:       Stdout: one line per create/update/delete, then a summary
#
# Options:
#   -a, --apply     Write the changes (default is a dry run)
#   -v, --verbose   Show events that are already correct
#   -h, --help      Show this help message
#
# Requirements: python3, Canvas.API/src on the path, teacher rights
#
# AI Model:     Claude Opus 5
# Attribution:  Generated by Michael Gilchrist in collaboration with
#               ClaudeAI Opus 5
# ============================================================================

import argparse
import csv
import html
import os
import pathlib
import re
import sys
import urllib.parse
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_api      # noqa: E402
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json
ET = ZoneInfo("America/New_York")
UTC = ZoneInfo("UTC")
TSV = None             # schedule TSV: cfg.path("schedule_tsv"), set in main()

# Title forms this script used before 2026-08-18.  Kept only so those events
# can be found and replaced.
OLD_TITLES = [re.compile(r" \(deadline\)$"), re.compile(r"^HW[0-9]+$"),
              re.compile(r"^DB L[0-9]+-[0-9]+$"),
              re.compile(r"^Team Homework [0-9]+$"),
              re.compile(r": (Initial|Responses to) Discussion Board Posts$")]

# Homeworks the syllabus makes optional: doing one replaces a lower homework
# score, skipping it costs nothing.  Said in the title, because a student
# scanning the calendar will not open a deadline they think is required.
# Read from canvas.course.json "optional_homework" (list of numbers) in main().
OPTIONAL_HW = set()

DUE_ONLY = "<p>Due at 11:59pm tonight.</p>"


# Deadlines are 11:59pm (MG, 2026-08-18), so the event is a point in time at
# 23:59 rather than a block running up to it.
DUE_TIME = "23:59"


def iso(d, hhmm):
    h, m = (int(x) for x in hhmm.split(":"))
    return (datetime.strptime(d, "%Y-%m-%d").replace(hour=h, minute=m, tzinfo=ET)
            .astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"))


def et_date(stamp):
    """A Canvas UTC stamp as its local calendar date."""
    return (datetime.strptime(stamp[:19] + "Z", "%Y-%m-%dT%H:%M:%SZ")
            .replace(tzinfo=UTC).astimezone(ET).strftime("%Y-%m-%d"))


def plain(s):
    """Description text with markup and whitespace normalized away.

    Canvas rewrites the HTML it is given, so comparing the raw strings would
    report a difference on every run and rewrite all 18 events forever.
    """
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html.unescape(s or ""))).strip()


def db_block(label):
    """'L5-9' -> ('L05-L09', 5, 9).

    Zero-padded because the Canvas group names are (L05-09 DB Participation);
    the schedule writes the same block unpadded.
    """
    lo, hi = (int(x) for x in re.match(r"L(\d+)-(\d+)", label).groups())
    return f"L{lo:02d}-L{hi:02d}", lo, hi


# Exactly what each half of a block's participation is (MG, 2026-08-18).
DB_INITIAL = "Your two (2) initial posts on the material."
DB_FINAL = "Your two (2) final responses to other posts"


def db_description(what):
    """One line naming which half of a block's participation is due."""
    return f"<p>{what}</p>\n<p>Due at 11:59pm tonight.</p>"


def hw_description(lo, hi, topics, optional=False):
    """What the homework is expected to cover, plus the one-submission rule.

    The lectures are listed one per line and labelled, rather than joined into
    a sentence: L4's own topic contains a semicolon ("Mutation & Alleles;
    Dominance Categories"), so any joined form reads as one lecture too many.
    """
    span = f"lecture {lo}" if lo == hi else f"lectures {lo}-{hi}"
    items = "".join(f"<li>L{n}: {html.escape(topics[n])}</li>"
                    for n in range(lo, hi + 1) if n in topics)
    note = ("<p>This one is OPTIONAL: completing it replaces a lower homework "
            "score.</p>\n" if optional else "")
    return (f"<p>Expected to cover {span}:</p>\n"
            f"<ul>{items}</ul>\n"
            f"{note}"
            "<p>This is a team assignment -- only one team member needs to "
            "submit it.</p>\n"
            "<p>Due at 11:59pm tonight.</p>")


def build_targets(A, groups):
    """[(title, date, published, description)] -- one entry per deadline."""
    rows = [r for r in csv.DictReader(open(TSV), delimiter="\t") if r.get("date")]

    # Lecture number -> topic, and homework label -> its lecture range, both
    # straight out of the schedule.
    topics, spans, lecture_day = {}, {}, {}
    for r in rows:
        lec = r["lecture"].strip()
        if lec.isdigit():
            topics[int(lec)] = r["topic"].strip()
            lecture_day[int(lec)] = r["date"]
        post = r["hw_posted"].strip()
        m = re.match(r"(HW\d+)\s*:\s*L(\d+)-(\d+)", post)
        if m:
            spans[m.group(1)] = (int(m.group(2)), int(m.group(3)))

    out = []
    for r in rows:                                    # homework
        hw = r["hw_due"].strip()
        if not hw:
            continue
        m = [a for a in A if a["name"].startswith(hw + ":")]
        n = int(re.sub(r"\D", "", hw))
        lo, hi = spans.get(hw, (0, 0))
        opt = n in OPTIONAL_HW
        title = f"Team Homework {n:02d}" + (" (Optional)" if opt else "")
        out.append((title, r["date"],
                    all(x["published"] for x in m) if m else True,
                    hw_description(lo, hi, topics, opt) if lo else DUE_ONLY))
    for r in rows:                                    # discussion-board blocks
        lab = r["db"].strip()
        if not lab:
            continue
        blk, lo, hi = db_block(lab)
        want = [f"L{n:02d}:" for n in range(lo, hi + 1)]
        m = [a for a in A if any(a["name"].startswith(w) for w in want)]
        live = all(x["published"] for x in m) if m else True
        # A block has TWO deadlines (MG, 2026-08-18): initial posts, then
        # final posts.  Only the closing date is in the schedule.  The initial
        # date is the day the block's LAST lecture is taught -- a student
        # cannot post about a lecture that has not happened yet -- and that is
        # read from the schedule, not offset by a fixed number of days.  A
        # fixed -2 days put block L10-L13 on Tue Oct 6, which is Fall Break.
        first = lecture_day.get(hi)
        if first:
            # PERMANENT, not a placeholder.  Every DB assignment carries only
            # the block's FINAL date, so no assignment ever represents the
            # initial-post deadline -- publishing the boards cannot make it
            # visible.  Passing published=False keeps this event for good;
            # only the Final Posts mirror stands down when the boards go live.
            out.append((f"{blk}: Initial Posts", first, False,
                        db_description(DB_INITIAL)))
        out.append((f"{blk}: Final Posts", r["date"], live,
                    db_description(DB_FINAL)))
    for a in A:                                       # Pre-Exam Q&A (Canvas only)
        if groups.get(a["assignment_group_id"]) == "Pre-Exam Q&A" and a["due_at"]:
            out.append((a["name"].split(":", 1)[-1].strip(),
                        et_date(a["due_at"]), a["published"], DUE_ONLY))
    return out


def owned(title, mine):
    return title in mine or any(p.search(title) for p in OLD_TITLES)


def main():
    global BASE, COURSE, TSV, OPTIONAL_HW
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-a", "--apply", action="store_true", help="perform the writes")
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="also report events that are already correct")
    canvas_course.add_arguments(ap)
    a = ap.parse_args()
    tag = "" if a.apply else "[DRY-RUN] "
    cfg, BASE, tok = canvas_course.setup(a)
    COURSE = cfg.course_id
    try:
        TSV = cfg.path("schedule_tsv")
    except canvas_course.CourseConfigError as e:
        sys.exit(f"[FAIL] {e}")
    if not os.path.isfile(TSV):
        sys.exit(f"[FAIL] schedule file not found: {TSV}")
    OPTIONAL_HW = {int(n) for n in cfg.data.get("optional_homework", [])}

    A = canvas_api.get_assignments(BASE, tok, COURSE)
    groups = {g["id"]: g["name"] for g in canvas_api.get_assignment_groups(BASE, tok, COURSE)}
    q = urllib.parse.urlencode({"context_codes[]": f"course_{COURSE}",
                                "all_events": "true", "type": "event", "per_page": 100})
    have = {e["title"]: e for e in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/calendar_events?" + q, tok)}

    targets = build_targets(A, groups)
    mine = {t[0] for t in targets}                     # every title we can own
    want = {t[0]: (t[1], t[3]) for t in targets if not t[2]}   # unpublished

    created = updated = removed = kept = 0

    # 1. Reconcile what is already there.
    for title, ev in sorted(have.items(), key=lambda kv: kv[1].get("start_at") or ""):
        if not owned(title, mine):
            continue
        on = et_date(ev["start_at"]) if ev.get("start_at") else "?"
        if title in want and on == want[title][0]:
            date, desc = want[title]
            at = iso(date, DUE_TIME)
            fix = {}
            if (ev.get("start_at") or "") != at or (ev.get("end_at") or "") != at:
                fix.update(start_at=at, end_at=at)
            if plain(ev.get("description")) != plain(desc):
                fix["description"] = desc
            if not fix:
                kept += 1
                if a.verbose:
                    print(f"          {on}  {title:<44} already correct")
            else:
                print(f"  {tag}UPDATE  {on}  {title:<44} "
                      f"({', '.join(sorted(fix))})")
                updated += 1
                if a.apply:
                    canvas_http.http_put_json(
                        f"{BASE}/api/v1/calendar_events/{ev['id']}", tok,
                        {"calendar_event": fix})
            continue
        why = ("deadline moved" if title in want else
               "superseded title" if title not in mine else
               "assignment now published")
        print(f"  {tag}DELETE  {on}  {title:<44} ({why})")
        removed += 1
        if a.apply:
            canvas_http.http_delete(f"{BASE}/api/v1/calendar_events/{ev['id']}", tok)
        if title in want:
            have.pop(title, None)                      # force the recreate below

    # 2. Create what is missing.
    for title, (date, desc) in sorted(want.items(), key=lambda kv: kv[1][0]):
        if title in have and et_date(have[title]["start_at"]) == date:
            continue
        print(f"  {tag}CREATE  {date}  {title}")
        created += 1
        if a.apply:
            canvas_http.http_post_json(
                f"{BASE}/api/v1/calendar_events", tok,
                {"calendar_event": {"context_code": f"course_{COURSE}",
                                    "title": title,
                                    "start_at": iso(date, DUE_TIME),
                                    "end_at": iso(date, DUE_TIME),
                                    "description": desc}})

    print(f"\n{tag}{created} created, {updated} updated, {removed} removed, "
          f"{kept} already correct")
    if not a.apply:
        print("re-run with --apply to write; re-run any time after publishing.")


if __name__ == "__main__":
    main()
