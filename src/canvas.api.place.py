#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.place.py
# Version:      1.1.0
# Created:      2026-08-13
# Revised:      2026-10-13
# Purpose:      Fill a named placeholder on the Canvas course with the real
#               file, once that file has been reviewed.
#
# The 2025 homework and recitation material was removed from Canvas because
# all of it is being remade for 2026.  Each slot kept a placeholder naming the
# file that will replace it:
#
#     Not yet posted: HW03_2026_lifecycles.cell.cycles.mitosis.and.meiosis.pdf
#
# Naming it is what makes this script possible.  A bare "not yet posted" would
# leave someone hunting for the right page; a placeholder carrying the exact
# filename turns the update into a lookup -- hand this script the file, it
# finds the placeholder that names it, uploads, and swaps in the link.
#
# --list is the other half: it reports every outstanding placeholder and
# whether a matching file already exists in the homework/discussions repos, so
# "what is ready to go up?" is a query rather than an audit.  That is the
# whole point of standardising the names.
#
# UPLOADS NOTHING WITHOUT --execute.  Material is uploaded only after it has
# been reviewed (MG, 2026-08-13), so the default is a dry run, and a file with
# no placeholder naming it is REFUSED rather than uploaded to a guessed home.
#
# Usage:        canvas.api.place.py [OPTIONS] [FILE ...]
# Input:        local file(s); Canvas token from ~/.api/canvas_token
# Output:       uploaded file(s) and relinked placeholders, with --execute
#
# Options:
#       --list          report outstanding placeholders and what is ready
#       --course ID     Canvas course id (default 261062, Fall 2026)
#       --folder PATH   Canvas folder to upload into (default "Uploaded Media")
#       --execute       actually upload and relink; omit for a dry run
#       --no-verify     skip the read-back check on each placement.  The check
#                       runs by DEFAULT because everything it catches fails
#                       SILENTLY: a PUT Canvas stored differently, a
#                       placeholder that survived because its text was edited
#                       by hand, or a link to a file id that no longer
#                       resolves.  None of those raise on their own.
#   -v, --verbose       per-object detail
#   -h, --help          this message
#
# Requirements: python3, beautifulsoup4
#
# Session:      Claude Code session (roll call, recitation penalty, syllabus)
# AI Model:     Claude Opus 5
