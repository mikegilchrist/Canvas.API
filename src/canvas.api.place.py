import argparse
import glob
import json
import mimetypes
import os
import re
import sys
import time
import urllib.request
import uuid

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import canvas_course  # noqa: E402

from bs4 import BeautifulSoup

VERSION = "1.1.0"
BASE = None    # set in main() from canvas.course.json
REPOS = []     # set in main(): every directory under repos in canvas.course.json
PREFIX = "Not yet posted: "
FOLDER = "Uploaded Media"

# (REPOS: where a reviewed file is likely to be found, for --list; see main())


class PlaceError(Exception):
    pass


def api(course, path, tok, method="GET", payload=None):
    data = json.dumps(payload).encode() if payload else None
    url = f"{BASE}/api/v1/courses/{course}/{path}"
    r = urllib.request.Request(url, data=data, method=method,
                               headers={"Authorization": f"Bearer {tok}",
                                        "Content-Type": "application/json"})
    with urllib.request.urlopen(r, timeout=60) as h:
        return json.load(h)


def placeholders(course, tok):
    """name -> [(kind, key, object title)] for every outstanding placeholder."""
    out = {}

    def scan(kind, key, title, html):
        for m in re.finditer(re.escape(PREFIX) + r"([^<\s]+)", html or ""):
            out.setdefault(m.group(1), []).append((kind, key, title))

    for a in api(course, "assignments?per_page=100", tok):
        scan("assignment", a["id"], a["name"], a.get("description"))
    for p in api(course, "pages?per_page=100", tok):
        body = api(course, f"pages/{p['url']}", tok).get("body")
        scan("page", p["url"], p["title"], body)
    return out


_INDEX = None


def local_index():
    """basename -> path, built ONCE.

    A recursive glob per placeholder walked these trees 37 times over, and the
    course material runs to tens of gigabytes; one walk answers every lookup.
    Prior-year directories are skipped, since a 2026 name will not be in them
    and descending costs more than the rest of the scan.
    """
    global _INDEX
    if _INDEX is not None:
        return _INDEX
    _INDEX = {}
    for root in REPOS:
        for dirpath, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs
                       if d not in (".git", "Figures", "Old", "Archive")
                       and not re.fullmatch(r"(19|20)\d\d", d)]
            for f in files:
                _INDEX.setdefault(f, os.path.join(dirpath, f))
    return _INDEX


def find_local(name):
    return local_index().get(name)


def upload(course, tok, path, folder):
    """Canvas' three-step upload: ask, POST the bytes, take the file back."""
    name = os.path.basename(path)
    ctype = mimetypes.guess_type(name)[0] or "application/octet-stream"
    init = api(course, "files", tok, "POST",
               {"name": name, "size": os.path.getsize(path),
                "content_type": ctype, "parent_folder_path": folder,
                "on_duplicate": "overwrite"})
    b = "----%s" % uuid.uuid4().hex
    body = b""
    for k, v in init["upload_params"].items():
        body += (f'--{b}\r\nContent-Disposition: form-data; name="{k}"'
                 f'\r\n\r\n{v}\r\n').encode()
    body += (f'--{b}\r\nContent-Disposition: form-data; name="file"; '
             f'filename="{name}"\r\nContent-Type: {ctype}\r\n\r\n').encode()
    body += open(path, "rb").read() + f"\r\n--{b}--\r\n".encode()
    r = urllib.request.Request(init["upload_url"], data=body, method="POST",
                               headers={"Content-Type":
                                        f"multipart/form-data; boundary={b}"})
    with urllib.request.urlopen(r, timeout=300) as h:
        return json.load(h)


def verify_placed(course, tok, kind, key, name, fid):
    """Re-read the object from Canvas and prove the placement took.

    On by default, because every failure mode here is SILENT: a PUT that
    Canvas accepted but stored differently, a placeholder that survived
    because its text had been edited by hand, or a link pointing at a file id
    that no longer resolves.  None of those raise; the object just quietly
    still says "not yet posted", or worse, links nothing.

    Returns a list of problems, empty when the placement is sound.
    """
    bad = []
    if kind == "assignment":
        html = api(course, f"assignments/{key}", tok).get("description") or ""
    else:
        html = api(course, f"pages/{key}", tok).get("body") or ""
    if PREFIX + name in html:
        bad.append(f"placeholder for {name} is still present")
    if f"/files/{fid}" not in html:
        bad.append(f"no link to file {fid} in the object")
    # and the id has to resolve to the file we just uploaded, not a tombstone
    try:
        r = urllib.request.Request(
            f"{BASE}/api/v1/files/{fid}",
            headers={"Authorization": f"Bearer {tok}"})
        with urllib.request.urlopen(r, timeout=30) as h:
            f = json.load(h)
        if f.get("display_name") != name:
            bad.append(f"file {fid} is named {f.get('display_name')!r}, "
                       f"expected {name!r}")
        # `hidden` is NOT a problem here and must not be flagged: a hidden
        # file is merely absent from the Files index and stays reachable by
        # direct link, which is exactly how every linked course file works --
        # the same property that made hiding the answer keys useless.  Uploads
        # inherit it from the hidden "Uploaded Media" folder.  `locked` is the
        # flag that actually denies students, so that is what is checked.
        if f.get("locked") or f.get("lock_at") or f.get("unlock_at"):
            bad.append(f"file {fid} is locked (locked={f.get('locked')}, "
                       f"lock_at={f.get('lock_at')}, "
                       f"unlock_at={f.get('unlock_at')}); students cannot open it")
    except Exception as exc:
        bad.append(f"file {fid} does not resolve: {exc}")
    return bad


def relink(html, name, course, fid):
    """Swap the placeholder paragraph for a link to the uploaded file."""
    soup = BeautifulSoup(html or "", "html.parser")
    hit = False
    for el in soup.find_all(string=re.compile(re.escape(PREFIX + name))):
        p = el.find_parent(["p", "li"]) or el.parent
        a = soup.new_tag("a", href=(f"{BASE}/courses/"
                                    f"{course}/files/{fid}?wrap=1"))
        a["title"] = name
        a["class"] = "instructure_file_link inline_disabled"
        a["target"] = "_blank"
        a["data-api-endpoint"] = (f"{BASE}/api/v1/courses/"
                                  f"{course}/files/{fid}")
        a["data-api-returntype"] = "File"
        a.string = name
        p.clear()
        p.append(a)
        hit = True
    return (str(soup), True) if hit else (None, False)


def do_list(course, tok, verbose=False):
    ph = placeholders(course, tok)
    ready = 0
    print(f"{len(ph)} outstanding placeholder(s)\n")
    print("%-64s %-8s %s" % ("expected file", "local?", "slot(s)"))
    for name in sorted(ph):
        local = find_local(name)
        ready += bool(local)
        where = ", ".join(sorted({t.split(":")[0] for _, _, t in ph[name]}))
        print("%-64s %-8s %s" % (name[:62], "READY" if local else "-",
                                 where[:40]))
        if verbose and local:
            print(f"        {local}")
    print(f"\n{ready} of {len(ph)} have a file present and could be placed")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Fill a named Canvas placeholder with its reviewed file.")
    ap.add_argument("files", nargs="*")
    ap.add_argument("--list", action="store_true")
    canvas_course.add_arguments(ap)
    ap.add_argument("--folder", default=FOLDER)
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--no-verify", action="store_true",
                    help="skip the read-back check (which runs by default)")
    ap.add_argument("-v", "--verbose", action="store_true")
    a = ap.parse_args(argv)
    global BASE, REPOS
    cfg, BASE, tok = canvas_course.setup(a)
    a.course = cfg.course_id
    REPOS = [d for k in cfg.data.get("repos", {}) for d in cfg.repo_dirs(k)]

    if a.list or not a.files:
        return do_list(a.course, tok, a.verbose)

    ph = placeholders(a.course, tok)
    tag = "" if a.execute else "[dry-run] "
    rc = 0
    for path in a.files:
        name = os.path.basename(path)
        if not os.path.exists(path):
            print(f"  MISSING: {path}", file=sys.stderr)
            rc = 1
            continue
        if name not in ph:
            # Refusing is the point: a file nothing asked for would otherwise
            # be uploaded into a guessed home and never linked.
            print(f"  REFUSED: no placeholder names {name!r}", file=sys.stderr)
            rc = 1
            continue
        where = ph[name]
        print(f"{tag}{name}  -> {len(where)} placeholder(s)")
        for kind, key, title in where:
            print(f"      {kind:<10} {title[:56]}")
        if not a.execute:
            continue
        f = upload(a.course, tok, path, a.folder)
        for kind, key, title in where:
            if kind == "assignment":
                obj = api(a.course, f"assignments/{key}", tok)
                new, hit = relink(obj.get("description"), name, a.course, f["id"])
                if hit:
                    api(a.course, f"assignments/{key}", tok, "PUT",
                        {"assignment": {"description": new}})
            else:
                obj = api(a.course, f"pages/{key}", tok)
                new, hit = relink(obj.get("body"), name, a.course, f["id"])
                if hit:
                    api(a.course, f"pages/{key}", tok, "PUT",
                        {"wiki_page": {"body": new}})
            time.sleep(0.2)
            if a.no_verify:
                continue
            bad = verify_placed(a.course, tok, kind, key, name, f["id"])
            if bad:
                rc = 1
                for b in bad:
                    print(f"      FAILED: {b}", file=sys.stderr)
            elif a.verbose:
                print(f"      verified {kind} {title[:44]}")
        print(f"      uploaded as file {f['id']} and linked"
              + ("" if a.no_verify else ", verified"))
    if not a.execute:
        print("\ndry run; nothing uploaded (pass --execute once reviewed)")
    return rc


if __name__ == "__main__":
    try:
        sys.exit(main())
    except PlaceError as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(2)
