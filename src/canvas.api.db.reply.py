#!/usr/bin/env python3
# ============================================================================
# Script:       canvas.api.db.reply.py
# Version:      1.1.0
# Created:      2026-08-28
# Revised:      2026-10-13
# Purpose:      Deliver the notes MG has APPROVED on a discussion board review
#               file -- either as a reply in the student's own thread, or as a
#               comment on their discussion board submission.
#
# THIS IS THE ONLY SCRIPT IN THE SET THAT WRITES TO CANVAS, and everything a
# student sees comes out of here.  It therefore does nothing on its own: it
# posts only rows whose `decision` column MG has filled in, it is a dry run
# unless given --apply, and it refuses to invent a message body -- the wording
# comes from a template, so what students receive is reviewable as a file in
# the repo rather than as a string buried in code.
#
# TWO DELIVERY MODES, for two different jobs.
#
#   --mode thread   a reply under the student's own post, visible to their
#                   recitation section.  This is the redundancy note, sent
#                   BEFORE the deadline, while the student can still act on
#                   it.  Its whole purpose is to let them fix the post and
#                   keep full credit, so the wording is supportive by
#                   requirement, not by taste.
#
#   --mode comment  a comment on the student's submission, visible to that
#                   student and to the TAs and no one else.  This is for
#                   flags raised AFTER the final deadline, when the point is
#                   a record the grading team can see rather than a nudge the
#                   student can act on.
#
# GROUP-ASSIGNMENT TRAP.  The 26 DB assignments are group assignments against
# the recitation-section set.  A submission comment on a group assignment
# defaults to group_comment=1, which would deliver a note about ONE student's
# post to all ~20 students in their section.  This always sends
# comment[group_comment]=false.  Do not remove that.
#
# IDEMPOTENT, VIA THE LEDGER.  Every delivery is appended to a .ledger.tsv
# beside the review file, and that ledger -- not Canvas -- is what a re-run
# checks before posting.
#
# It used to embed an HTML comment in each note and look for that instead.
# CANVAS STRIPS HTML COMMENTS from a discussion entry, so the marker was never
# stored and the check could never fire; on 2026-08-28 a student received the
# same note twice because of it.  Do not reintroduce a marker-based check
# without first confirming the marker survives a round trip.
#
# The ledger is keyed on (entry_id, mode), so the same post can still get a
# thread reply AND a submission comment, but not two of either.
#
# Usage:        canvas.db.reply.py [OPTIONS] REVIEW_TSV
# Input:        a db.duplicate.search-*_*.tsv or db.aiflags_*.tsv with `decision`
#               column filled in; the matching db.posts_*.json for routing
# Output:       Canvas replies or submission comments; a .ledger.tsv beside
#               the review file
#
# Options:
#       --mode MODE       thread | comment       (default: thread)
#       --template FILE   message template; {placeholders} are filled from the
#                         review row.  Defaults to the built-in template for
#                         the review file's kind.
#       --course-id ID    Canvas course id (default: canvas.course.json)
#       --course-config F course config (default: found upward from cwd)
#       --year YYYY       year stamp (default: taken from the review file name)
#       --postdir DIR     where canvas.db.fetch.py wrote its JSON (default:
#                         every <BLOCK>/Posts directory, all boards)
#       --yes VALUES      decision values that count as approval
#                         (default: y,yes,ok,approve,post)
#   -a, --apply           actually post; omitting this is a dry run
#   -v, --verbose         show the full message body for every row
#   -h, --help            this message
#
# Requirements: python3 (stdlib only), a Canvas API token, teacher rights
#
# AI Model:     Claude Opus 5
