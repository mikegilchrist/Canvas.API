MARKER = "biol240-db-note"

# The redundancy note.  Sent while the student can still edit, so it is an
# offer of a way to keep full credit, not a citation.  MG asked for kind and
# supportive language; that is what this wording is for, and it is a template
# on disk precisely so it can be reworded without touching code.
TEMPLATE_DUPLICATES = """\
Hi {flag_first} -- good question, and you are clearly digging into the right \
part of the lecture.

Worth knowing before the deadline, though: it lands very close to \
{prior_ref}, from {prior_when} --

"{prior_quote}"

Credit for a thread is for putting something new in front of the section, so \
two posts covering the same ground tend to count as one between them. There \
is still time to change that, and any of these does it:

- reply to {prior_short} instead and push it somewhere it has not gone yet -- \
replies count toward your participation as well;
- revise yours to ask the part {prior_short} does not reach; or
- swap in a different question altogether.

None of this is a penalty, and you are welcome to leave the post exactly as \
it is. I would just rather you got full credit for thinking you have already \
done.

-- Dr. G
"""

# The post-deadline flag.  Delivered as a submission comment so the student
# and the TAs see it and the section does not.  Deliberately describes the
# EVIDENCE and asks, rather than asserting a conclusion about authorship --
# the markup shows text was pasted out of a chat tool, which is not the same
# claim as the work being AI-written.
TEMPLATE_AIFLAGS = """\
Hi {flag_first} -- a note on your {board} discussion board post.

The submitted HTML for this post carries formatting left behind by a copy and \
paste out of an AI chat interface ({signatures}). That markup is not something \
typing into Canvas produces.

Pasting text from a chat tool is not automatically a problem, and the course \
does not forbid using one to think with. What the discussion board is graded \
on is your own question about the lecture, in your own words, so I want to \
check: was the wording of this post yours?

Please reply here so we can settle it. If a tool wrote the post, say so and we \
will sort out the credit without further consequence. Let me know either way.

-- Dr. G
"""

TEMPLATES = {
    "duplicates": TEMPLATE_DUPLICATES,
    "aiflags": TEMPLATE_AIFLAGS,
    # misplaced posts have no built-in template: the wording is MG's own,
    # already used on other students, and is passed with --template.
    "misplaced": None,
    # what db.course.structure.screen.py produces. Same wording, same
    # --template; the name says which of the two off-topic kinds it is.
    "course.structure": None,
}

KIND_RX = re.compile(
    r"db\.(?:duplicate\.search-(?P<cmp>wording|conceptual)"
    r"|(?P<other>aiflags|misplaced|course\.structure))_(\d{4})_(\S+)\.tsv$")


# ------------------------------------------------------------- helpers ----

def get_json(url, token):
    return canvas_http.http_get_json(url, token)[0]


def post_form(url, token, fields):
    """POST an application/x-www-form-urlencoded body.

    Canvas takes both JSON and form bodies; form encoding is used here because
    the comment endpoint's bracketed parameter names (comment[text_comment])
    are what its docs specify and what its examples exercise.
    """
    import urllib.request
    data = urllib.parse.urlencode(fields, doseq=True).encode("utf-8")
    req = urllib.request.Request(url, data=data, method="POST")
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Content-Type", "application/x-www-form-urlencoded")
    with urllib.request.urlopen(req) as resp:
        return json.loads(resp.read().decode("utf-8"))


def classify(path):
    m = KIND_RX.search(os.path.basename(path))
    if not m:
        raise SystemExit(
            f"cannot tell what {os.path.basename(path)} is; expected a name "
            "like db.duplicate.search-wording_2026_L01-L04.tsv, "
            "db.duplicate.search-conceptual_2026_L01-L04.tsv or "
            "db.aiflags_2026_L01-L04.tsv"
        )
    # Both comparison passes -- post-wording (lexical) and post-conceptual
    # (model-judged) -- produce the same columns and want the same note, so
    # they share the "duplicates" template.  Only the aiflags file is a
    # different kind of message.
    other = m.group("other")
    kind = other if other else "duplicates"
    return kind, m.group(3), m.group(4)


def first_name(full):
    return (full or "").split()[0] if full else "there"


def load_routing(postdirs, year):
    """entry_id -> routing, and board -> section -> (group_id, topic_id).

    Everything needed to address a post -- which group's board it is on, which
    child topic, which student -- already sits in the fetch snapshot, so this
    makes no API calls to work it out.
    """
    entries, boards = {}, {}
    if isinstance(postdirs, str):
        postdirs = [postdirs]
    files = []
    for pd in postdirs:
        if os.path.isdir(pd):
            files += [os.path.join(pd, p) for p in sorted(os.listdir(pd))]
    for path in files:
        m = re.match(rf"db\.posts_{year}_(L\d\d)\.json$",
                     os.path.basename(path))
        if not m:
            continue
        with open(path) as fh:
            b = json.load(fh)
        boards[b["board"]] = {
            "sections": b["sections"],
            "topic_id": b["topic_id"],
            "title": b["title"],
        }
        for e in b["entries"]:
            entries[str(e["id"])] = {
                "board": b["board"], "section": e["section"],
                "user_id": e["user_id"], "root_id": e["root_id"],
                "group_id": b["sections"][e["section"]]["group_id"],
                "child_topic_id": b["sections"][e["section"]]["child_topic_id"],
            }
    return entries, boards


def load_ledger(path):
    """(entry_id, mode) pairs already delivered, read from the ledger on disk.

    Canvas is not asked, because Canvas cannot answer: it strips the HTML
    comment this used to rely on.  The ledger is written by this script and is
    the only durable record that a note went out.
    """
    done = set()
    if not os.path.exists(path):
        return done
    try:
        with open(path) as fh:
            for row in csv.DictReader(fh, delimiter="\t"):
                done.add((str(row.get("entry_id", "")).strip(),
                          (row.get("mode") or "thread").strip()))
    except OSError:
        pass
    return done


def assignment_for_topic(token, course, topic_id, cache):
    if topic_id in cache:
        return cache[topic_id]
    t = get_json(
        f"{BASE}/api/v1/courses/{course}/discussion_topics/{topic_id}", token)
    cache[topic_id] = t.get("assignment_id")
    return cache[topic_id]


def render(template, row, kind):
    """Fill the template from a review row, tolerating absent columns."""
    fields = dict(row)
    fields.setdefault("flag_author", "")
    fields["flag_first"] = first_name(row.get("flag_author"))
    if kind == "duplicates":
        # A student can duplicate THEMSELVES -- two threads minutes apart on
        # one board.  Naming them in the third person reads as a mistake, so
        # the self case gets its own phrasing.
        same = (row.get("flag_author") or "") == (row.get("prior_author") or "")
        if same:
            fields["prior_ref"] = "your own earlier post"
            fields["prior_short"] = "that earlier post"
        else:
            fields["prior_ref"] = f"{row.get('prior_author')}'s earlier post"
            fields["prior_short"] = \
                f"{first_name(row.get('prior_author'))}'s post"
        # Not every student writes a Subject: line; fall back to their words.
        fields["prior_quote"] = (row.get("prior_subject")
                                 or row.get("prior_excerpt") or "")
        fields["prior_when"] = (row.get("prior_created") or "")[:10]
    fields.setdefault("signatures", row.get("signatures", ""))
    fields.setdefault("board", row.get("board", ""))
    try:
        return template.format(**fields)
    except KeyError as e:
        raise SystemExit(f"template refers to unknown field {e}")


def to_html(text, entry_id):
    paras = [p.strip() for p in text.split("\n\n") if p.strip()]
    body = []
    for p in paras:
        if p.lstrip().startswith("- "):
            items = [ln.strip()[2:] for ln in p.splitlines()
                     if ln.strip().startswith("- ")]
            body.append("<ul>" + "".join(f"<li>{i}</li>" for i in items)
                        + "</ul>")
        else:
            body.append("<p>" + p.replace("\n", " ") + "</p>")
    return f"<!-- {MARKER}:{entry_id} -->\n" + "\n".join(body)


# ---------------------------------------------------------------- main ----

def main():
    ap = argparse.ArgumentParser(
        description="Post approved discussion board notes to Canvas.")
    ap.add_argument("review", metavar="REVIEW_TSV")
    ap.add_argument("--mode", choices=("thread", "comment"), default="thread")
    ap.add_argument("--template", default=None)
    ap.add_argument("--postdir", default=None)
    ap.add_argument("--yes", default="y,yes,ok,approve,post")
    ap.add_argument("-a", "--apply", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    args = ap.parse_args()
    global BASE, COURSE
    cfg, BASE, token = canvas_course.setup(args)
    COURSE = cfg.course_id
    args.course = cfg.course_id

    kind, year, block = classify(args.review)
    approve = {v.strip().lower() for v in args.yes.split(",") if v.strip()}
    # Routing spans ALL boards, so scan every block's Posts/ directory.
    postdir = args.postdir or db_paths.all_posts_dirs(year)

    if args.template:
        with open(args.template) as fh:
            template = fh.read()
    else:
        template = TEMPLATES[kind]

    with open(args.review) as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    approved = [r for r in rows
                if (r.get("decision") or "").strip().lower() in approve]

    print(f"{args.review}")
    print(f"  {len(rows)} row(s), {len(approved)} approved, "
          f"mode={args.mode}, {'APPLY' if args.apply else 'DRY RUN'}")
    if not approved:
        print("  nothing to do -- fill in the `decision` column "
              f"(one of: {', '.join(sorted(approve))})")
        return 0

    # One note per student per board: a post can match several priors, and a
    # student should hear about it once.
    seen, deduped = set(), []
    for r in approved:
        key = (r.get("flag_entry_id") or r.get("entry_id"), args.mode)
        if key in seen:
            print(f"  skip duplicate approval for entry {key[0]}")
            continue
        seen.add(key)
        deduped.append(r)

    entries, boards = load_routing(postdir, year)
    ledger_done = load_ledger(re.sub(r"\.tsv$", ".ledger.tsv", args.review))
    acache = {}
    ledger_path = re.sub(r"\.tsv$", ".ledger.tsv", args.review)
    new_ledger, posted, skipped, failed = [], 0, 0, 0

    for r in deduped:
        eid = str(r.get("flag_entry_id") or r.get("entry_id") or "").strip()
        route = entries.get(eid)
        if not route:
            print(f"  ERROR entry {eid} not in the snapshot in {postdir}; "
                  "re-run canvas.db.fetch.py")
            failed += 1
            continue
        body = render(template, r, kind)
        who = r.get("flag_author") or r.get("author")
        head = (f"  {route['board']} sec{route['section']} {who} "
                f"entry={eid}")

        if (eid, args.mode) in ledger_done:
            print(f"{head}: already sent a {args.mode} note (see ledger), "
                  "skipping")
            skipped += 1
            continue

        if args.mode == "thread":
            target = route["root_id"] or eid
            url = (f"{BASE}/api/v1/groups/{route['group_id']}/"
                   f"discussion_topics/{route['child_topic_id']}/"
                   f"entries/{target}/replies")
            fields = {"message": to_html(body, eid)}
        else:
            aid = assignment_for_topic(token, args.course,
                                       boards[route["board"]]["topic_id"],
                                       acache)
            if not aid:
                print(f"{head}: board has no assignment; cannot comment")
                failed += 1
                continue
            url = (f"{BASE}/api/v1/courses/{args.course}/assignments/"
                   f"{aid}/submissions/{route['user_id']}")
            # group_comment=false is load-bearing: see the header.
            fields = {"comment[text_comment]": body,
                      "comment[group_comment]": "false"}

        if not args.apply:
            print(f"{head}: would post ({args.mode})")
            if args.verbose:
                print("      " + body.replace("\n", "\n      "))
            continue

        try:
            res = post_form(url, token, fields)
            print(f"{head}: posted ({args.mode}) id="
                  f"{res.get('id') or res.get('user_id')}")
            posted += 1
            new_ledger.append([
                datetime.datetime.now().isoformat(timespec="seconds"),
                kind, args.mode, route["board"], route["section"], eid,
                who, route["user_id"], str(res.get("id") or ""), "",
            ])
        except urllib.error.HTTPError as e:
            print(f"{head}: FAILED {e.code} {e.read().decode()[:200]}")
            failed += 1

    if args.apply and new_ledger:
        fresh = not os.path.exists(ledger_path)
        with open(ledger_path, "a", newline="") as fh:
            w = csv.writer(fh, delimiter="\t", lineterminator="\n")
            if fresh:
                w.writerow(["when", "kind", "mode", "board", "section",
                            "entry_id", "author", "user_id", "posted_id",
                            "note"])
            w.writerows(new_ledger)
        print(f"  ledger -> {ledger_path}")

    print(f"\n  {posted} posted, {skipped} already noted, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
