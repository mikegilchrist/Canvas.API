# Revised:      2026-10-13 -- course-agnostic: course id, base URL and token come
#               from canvas.course.json (canvas_course.py); --course-id/--course-config.
# Purpose:      Make the 26 graded BIOL240 discussion boards section specific,
#               so a student posts among ~20 recitation peers rather than 129.
#
# syllabus_2026.tex line 441 promises "DBs are administered separately for each
# discussion section."  Canvas has no way to make a GRADED discussion section
# specific -- `specific_sections` is accepted only on announcements -- so the
# promise is kept the other way round: a group set whose groups ARE the six
# cross-listed recitation sections, and each DB marked as a group discussion
# against it.  Canvas then gives every section its own sub-discussion while the
# assignment, and therefore the gradebook column, stays single.  26 columns
# before, 26 columns after; bin/grade.gradebook.config.json is untouched.
#
# This also repairs a live defect.  24 of the 26 topics arrived from the
# cartridge already bound to group set 44679 "Project Groups" -- the FOUR-PERSON
# TEAM set that HW04 and HW08 use -- which currently contains no groups at all.
# A group discussion with no groups has no child topic to route anyone to
# (`group_topic_children` is empty on all 24), so the four published boards are
# unpostable right now, and would scope posts to a student's team, not their
# section, once the teams are built.
#
# Every DB assignment also gets `grade_group_students_individually = true`.  All
# 26 currently have it FALSE, which on a group assignment means one score
# propagates to every member of the group -- here, all 25 students in a section.
#
# TIMING IS THE WHOLE RISK.  Canvas refuses to change group settings once anyone
# has submitted ("students have already submitted to this discussion, so group
# settings cannot be changed").  Measured 2026-08-18: 0 entries and 0 submitted
# submissions across all 26, so nothing is lost today.  The script re-checks
# that per topic on every run and SKIPS any board that has activity rather than
# attempting a change Canvas would either refuse or honour destructively.
#
# Section membership is not maintained by Canvas -- a group set does not track
# enrollments.  This script is the sync: re-run it after every add/drop.
#
# Idempotent: every run reconciles the live course against the intended state.
#
# Usage:        canvas.api.db.sections.enable.py [--course-id N] [--course-config FILE] [--apply] [-v]
# Input:        Canvas course from canvas.course.json or --course-id; token via
#               canvas_course (~/.canvas.api.conf, else ~/.api/canvas_token)
# Output:       Stdout: one line per intended change, then a summary
