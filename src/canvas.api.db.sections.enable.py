import argparse
import os
import re
import pathlib
import sys
import urllib.error

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json

# The group set the DBs are moved ONTO.  Deliberately not 44679 "Project
# Groups", which is the team set HW04/HW08 grade against.
CATEGORY_NAME = None   # set in main(): canvas.course.json db_sections.category_name

# The 26 graded boards, recognized by title.  Anything else in the course --
# HW threads, contested-question boards, the R## recitation boards -- is left
# alone.
DB_TITLE_RX = None   # set in main(): db_sections.title_regex
EXPECTED_TOPICS = None   # set in main(): db_sections.expected_boards


def get(url, tok):
    r = canvas_http.http_get_json(url, tok)
    return r[0] if isinstance(r, tuple) else r


class Runner:
    """Counts intended changes and performs them only under --apply."""

    def __init__(self, apply_changes, verbose):
        self.apply = apply_changes
        self.verbose = verbose
        self.changes = 0
        self.skips = 0
        self.errors = []

    def change(self, msg, fn):
        self.changes += 1
        print(f"  {'CHANGE' if self.apply else 'WOULD '}  {msg}")
        if not self.apply:
            return None
        try:
            return fn()
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")[:300]
            self.errors.append(f"{msg}: HTTP {e.code} {detail}")
            print(f"  FAILED  {msg}: HTTP {e.code} {detail}")
            return None

    def ok(self, msg):
        if self.verbose:
            print(f"  ok      {msg}")

    def skip(self, msg):
        self.skips += 1
        print(f"  SKIP    {msg}")


def ensure_category(tok, run):
    """Return the id of the section group set, creating it if absent."""
    cats = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/group_categories", tok)
    for c in cats:
        if c["name"] == CATEGORY_NAME:
            run.ok(f"group set {CATEGORY_NAME!r} exists (id {c['id']})")
            return c["id"]

    res = run.change(
        f"create group set {CATEGORY_NAME!r}",
        lambda: canvas_http.http_post_json(
            f"{BASE}/api/v1/courses/{COURSE}/group_categories", tok,
            {"name": CATEGORY_NAME}))
    if isinstance(res, tuple):
        res = res[0]
    return res["id"] if res else None


def section_key(name):
    """Match a group to its section by the trailing digits of both names.

    The groups in the live set are named '07' ... '12' while the sections are
    named 'BIOL240 Section 007' ... , so matching on the full name finds
    nothing and every group looks missing.  Creating the "missing" six would
    not merely add clutter: a student belongs to at most one group per set, so
    re-adding all 128 would empty the groups the existing child boards are
    built on.  canvas.api.group.sync.py, which maintains these memberships daily,
    has always matched on trailing digits; this now agrees with it.
    """
    m = re.search(r"(\d+)\s*$", (name or "").strip())
    return int(m.group(1)) if m else None


def ensure_groups(tok, run, cat_id, sections):
    """One group per course section.  Returns {section_id: group_id}."""
    groups = []
    if cat_id:
        groups = canvas_http.paginated_get_all(
            f"{BASE}/api/v1/group_categories/{cat_id}/groups", tok)
    by_key = {}
    for g in groups:
        k = section_key(g["name"])
        if k is None:
            run.skip(f"group {g['name']!r} has no section number in its name; "
                     f"not matched to any section")
            continue
        by_key[k] = g

    mapping = {}
    for s in sections:
        g = by_key.get(section_key(s["name"]))
        if g:
            run.ok(f"group {g['name']!r} covers section {s['name']!r} "
                   f"(id {g['id']})")
            mapping[s["id"]] = g["id"]
            continue
        res = run.change(
            f"create group {s['name']!r} in {CATEGORY_NAME!r}",
            lambda cid=cat_id, nm=s["name"]: canvas_http.http_post_json(
                f"{BASE}/api/v1/group_categories/{cid}/groups", tok,
                {"name": nm, "join_level": "invitation_only"}))
        if isinstance(res, tuple):
            res = res[0]
        mapping[s["id"]] = res["id"] if res else None
    return mapping


def add_members(tok, group_id, members):
    """Set a group's membership to `members`.

    `members` is the FULL intended list, not the additions: the working call is
    PUT /groups/:id, which replaces the roster.  POSTing {"members": [...]} to
    /groups/:id/memberships answers HTTP 400 -- that endpoint takes a single
    `user_id` -- which is how two add/drop moves were silently left unapplied
    on 2026-08-19.  Same call, and same per-student fallback, as the daily
    canvas.api.group.sync.py; if these two ever disagree, the sync is the one that
    runs every morning and wins.
    """
    try:
        return canvas_http.http_put_json(
            f"{BASE}/api/v1/groups/{group_id}", tok, {"members": members})
    except urllib.error.HTTPError:
        print(f"          bulk PUT failed; adding per student")
        for uid in members:
            try:
                canvas_http.http_post_json(
                    f"{BASE}/api/v1/groups/{group_id}/memberships", tok,
                    {"user_id": uid})
            except urllib.error.HTTPError as e:
                print(f"          user {uid}: HTTP {e.code}")
        return None


def sync_memberships(tok, run, mapping, enrollments, sections):
    """Make each group's membership exactly its section's active students."""
    want = {sid: set() for sid in mapping}
    for e in enrollments:
        want.setdefault(e["course_section_id"], set()).add(e["user_id"])

    names = {s["id"]: s["name"] for s in sections}
    for sid, gid in mapping.items():
        label = names.get(sid, str(sid))
        if gid is None:
            if run.apply:
                run.skip(f"{label}: group was not created, cannot sync "
                         f"{len(want.get(sid, ()))} membership(s)")
            else:
                # The group does not exist yet, so every member is an add.
                run.change(f"{label}: add {len(want.get(sid, ()))} student(s) "
                           f"to the new group", lambda: None)
            continue
        have = {u["id"] for u in canvas_http.paginated_get_all(
            f"{BASE}/api/v1/groups/{gid}/users?per_page=100", tok)}
        add = sorted(want.get(sid, set()) - have)
        drop = sorted(have - want.get(sid, set()))
        if not add and not drop:
            run.ok(f"{label}: {len(have)} members, in sync")
            continue
        if add:
            run.change(
                f"{label}: add {len(add)} student(s) to group {gid}",
                lambda g=gid, m=sorted(want.get(sid, set())):
                    add_members(tok, g, m))
        for uid in drop:
            run.change(
                f"{label}: remove user {uid} from group {gid} "
                f"(no longer enrolled in this section)",
                lambda g=gid, u=uid: canvas_http.http_delete(
                    f"{BASE}/api/v1/groups/{g}/users/{u}", tok))


def topic_is_locked(tok, topic, assignment):
    """Canvas forbids group changes once anyone has submitted.  Detect that.

    Two cheap signals rather than paging 130 submission rows per topic: the
    topic's own replies, and the assignment's `has_submitted_submissions` flag,
    which Canvas maintains for exactly this question.
    """
    if assignment and assignment.get("has_submitted_submissions"):
        return "the assignment already has submissions"
    entries = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/discussion_topics/{topic['id']}"
        f"/entries", tok)
    if entries:
        return f"{len(entries)} reply/replies already posted"
    return None


def retarget_topics(tok, run, cat_id, topics, assignments):
    for t in sorted(topics, key=lambda x: x["title"]):
        a = assignments.get(t.get("assignment_id"))
        title = t["title"][:44]
        lock = topic_is_locked(tok, t, a)
        if lock:
            run.skip(f"{title}: {lock} -- Canvas will not change group "
                     f"settings; leaving as is")
            continue

        if t.get("group_category_id") == cat_id and cat_id is not None:
            run.ok(f"{title}: already on {CATEGORY_NAME!r}")
        else:
            old = t.get("group_category_id") or "none"
            new = cat_id if cat_id is not None else "(to be created)"
            run.change(
                f"{title}: group set {old} -> {new} ({CATEGORY_NAME!r})",
                lambda tid=t["id"], c=cat_id: canvas_http.http_put_json(
                    f"{BASE}/api/v1/courses/{COURSE}/discussion_topics/{tid}",
                    tok, {"group_category_id": c}))

        if a is None:
            run.skip(f"{title}: no assignment behind this topic")
        elif a.get("grade_group_students_individually"):
            run.ok(f"{title}: already graded per student")
        else:
            run.change(
                f"{title}: grade_group_students_individually false -> true",
                lambda aid=a["id"]: canvas_http.http_put_json(
                    f"{BASE}/api/v1/courses/{COURSE}/assignments/{aid}", tok,
                    {"assignment":
                        {"grade_group_students_individually": True}}))


def main():
    p = argparse.ArgumentParser(
        description="Make the graded discussion boards section specific.")
    p.add_argument("-a", "--apply", action="store_true",
                   help="write the changes (default is a dry run)")
    p.add_argument("-v", "--verbose", action="store_true",
                   help="also show items that are already correct")
    canvas_course.add_arguments(p)
    args = p.parse_args()

    global BASE, COURSE, CATEGORY_NAME, DB_TITLE_RX, EXPECTED_TOPICS
    cfg, BASE, tok = canvas_course.setup(args)
    COURSE = cfg.course_id
    sec = cfg.data.get("db_sections")
    if not isinstance(sec, dict) or not all(k in sec for k in ("category_name", "title_regex", "expected_boards")):
        sys.exit("[FAIL] canvas.course.json needs db_sections with keys: category_name, title_regex, expected_boards")
    CATEGORY_NAME = sec["category_name"]
    DB_TITLE_RX = re.compile(sec["title_regex"])
    EXPECTED_TOPICS = int(sec["expected_boards"])
    run = Runner(args.apply, args.verbose)

    print(f"{cfg.name or COURSE} discussion boards -> section specific   "
          f"[{'APPLY' if args.apply else 'DRY RUN'}]")
    print(f"course {COURSE} at {BASE}\n")

    sections = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/sections", tok)
    enrollments = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/enrollments"
        f"?type[]=StudentEnrollment&state[]=active&per_page=100", tok)
    topics = [t for t in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/discussion_topics?per_page=100", tok)
        if DB_TITLE_RX.match(t["title"])]
    assignments = {a["id"]: a for a in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/assignments?per_page=100", tok)}

    print(f"{len(sections)} sections, {len(enrollments)} active student "
          f"enrollments, {len(topics)} graded DB topics\n")
    if len(topics) != EXPECTED_TOPICS:
        print(f"  WARNING: expected {EXPECTED_TOPICS} DB topics, found {len(topics)}")

    print("[1] group set")
    cat_id = ensure_category(tok, run)
    print("\n[2] one group per recitation section")
    mapping = ensure_groups(tok, run, cat_id, sections)
    print("\n[3] memberships from section enrollments")
    sync_memberships(tok, run, mapping, enrollments, sections)
    print("\n[4] point each DB at the section group set, grade per student")
    retarget_topics(tok, run, cat_id, topics, assignments)

    verb = "made" if args.apply else "pending"
    print(f"\n{run.changes} change(s) {verb}, {run.skips} skipped")
    if run.errors:
        print(f"{len(run.errors)} error(s):")
        for e in run.errors:
            print(f"  {e}")
        return 1
    if not args.apply and run.changes:
        print("Dry run only.  Re-run with --apply to write.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
