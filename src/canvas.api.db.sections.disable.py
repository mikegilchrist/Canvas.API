# Script:       canvas.api.db.sections.disable.py
# Version:      1.2.0
# Created:      2026-08-18
# Revised:      2026-10-13 -- course-agnostic: course id, base URL and token come
#               from canvas.course.json (canvas_course.py); --course-id/--course-config.
# Revised:      2026-08-19
# Purpose:      Turn the per-section discussion boards back into ordinary
#               course-wide boards.
#
# The inverse of canvas.api.db.sections.enable.py.  Detaching a board from its
# group set deletes the section-level child boards Canvas generated from it
# (six per board, one per recitation section).  The group set, its groups and
# their memberships, the assignment, the module items and the pages are all
# untouched, and re-running the enable script rebuilds the children.
#
# DETACHING IS DESTRUCTIVE ONCE ANYONE HAS POSTED: the replies live in the
# child boards, and the children are deleted.  So this refuses any board whose
# assignment has submissions or whose children hold entries, rather than
# leaving that to Canvas -- Canvas blocks the change only for SUBMITTED work,
# not for unsubmitted replies.
#
# VERIFIED 2026-08-19 against board L26 (unpublished, no entries): detached,
# six children removed, rebound, six children and all memberships restored.
# The 2026-08-18 HTTP 404 was the PAYLOAD, not the endpoint: Canvas reads
# {"group_category_id": ""} as a lookup of the group set named "" and answers
# "The specified resource does not exist."  JSON null detaches and returns 200.
#
# Usage:        canvas.api.db.sections.disable.py [--course-id N] [--course-config FILE] [OPTIONS]
# Input:        Canvas course from canvas.course.json or --course-id; token via
#               canvas_course (~/.canvas.api.conf, else ~/.api/canvas_token)
# Output:       Stdout: one line per intended change, then a summary
#
# Options:
#   -a, --apply      Write the changes (default is a DRY RUN)
#   -o, --only RX    Act only on boards whose title matches this regex
#   -v, --verbose    Show boards that are already course-wide
#   -h, --help       Show this help message
#
# Requirements: python3, Canvas.API/src on the path, teacher rights
#
# AI Model:     Claude Opus 5
