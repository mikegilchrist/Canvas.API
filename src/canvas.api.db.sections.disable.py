import argparse
import os
import re
import pathlib
import sys
import urllib.error

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import canvas_http     # noqa: E402
import canvas_course  # noqa: E402

BASE = COURSE = None   # set in main() from canvas.course.json

# The same graded boards canvas.api.db.sections.enable.py recognizes (title
# regex = db_sections.title_regex in canvas.course.json).  Matched
# on title so HW threads, contested-question boards and the R## recitation
# boards are never touched.
DB_TITLE_RX = None   # set in main() from canvas.course.json db_sections.title_regex


def entries_in_children(tok, topic):
    """Total replies across a board's section-level children.

    The parent of a group discussion holds no entries -- students post in the
    child board for their section -- so counting the parent's entries, which is
    what a single cheap check would do, always returns zero and always says it
    is safe to delete them.
    """
    total = 0
    for child in topic.get("group_topic_children") or []:
        total += len(canvas_http.paginated_get_all(
            f"{BASE}/api/v1/groups/{child['group_id']}"
            f"/discussion_topics/{child['id']}/entries", tok))
    return total


def unsafe(tok, topic, assignment):
    """Reason this board must not be detached, or None."""
    if assignment and assignment.get("has_submitted_submissions"):
        return "the assignment already has submissions"
    n = entries_in_children(tok, topic)
    if n:
        return f"{n} reply/replies in its section boards would be deleted"
    return None


def main():
    p = argparse.ArgumentParser(
        description="Turn the section-specific discussion boards back "
                    "into ordinary course-wide boards.")
    p.add_argument("-a", "--apply", action="store_true",
                   help="write the changes (default is a dry run)")
    p.add_argument("-o", "--only", default=None,
                   help="act only on boards whose title matches this regex")
    p.add_argument("-v", "--verbose", action="store_true",
                   help="also show boards that are already course-wide")
    canvas_course.add_arguments(p)
    args = p.parse_args()

    global BASE, COURSE, DB_TITLE_RX
    cfg, BASE, tok = canvas_course.setup(args)
    COURSE = cfg.course_id
    sec = cfg.data.get("db_sections")
    if not isinstance(sec, dict) or not all(k in sec for k in ("title_regex",)):
        sys.exit("[FAIL] canvas.course.json needs db_sections with keys: title_regex")
    DB_TITLE_RX = re.compile(sec["title_regex"])
    only = re.compile(args.only) if args.only else None
    tag = "" if args.apply else "[DRY-RUN] "

    print(f"{cfg.name or COURSE} discussion boards -> course-wide   "
          f"[{'APPLY' if args.apply else 'DRY RUN'}]")
    print(f"course {COURSE} at {BASE}\n")

    topics = [t for t in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/discussion_topics?per_page=100", tok)
        if DB_TITLE_RX.match(t["title"])]
    assignments = {a["id"]: a for a in canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{COURSE}/assignments?per_page=100", tok)}
    if only:
        topics = [t for t in topics if only.search(t["title"])]
        print(f"--only {args.only!r} selects {len(topics)} board(s)\n")

    detached = kids = skipped = 0
    errors = []
    for t in sorted(topics, key=lambda x: x["title"]):
        title = t["title"][:44]
        if not t.get("group_category_id"):
            if args.verbose:
                print(f"  ok      {title}: already course-wide")
            continue
        reason = unsafe(tok, t, assignments.get(t.get("assignment_id") or 0))
        if reason:
            print(f"  SKIP    {title}: {reason}")
            skipped += 1
            continue
        c = len(t.get("group_topic_children") or [])
        print(f"  {tag}DETACH  {title:<44} set {t['group_category_id']} "
              f"-> none  ({c} child board(s) removed)")
        detached += 1
        kids += c
        if args.apply:
            try:
                # JSON null, NOT "" -- see the header.  An empty string is a
                # group-set lookup and answers 404.
                canvas_http.http_put_json(
                    f"{BASE}/api/v1/courses/{COURSE}/discussion_topics"
                    f"/{t['id']}", tok, {"group_category_id": None})
            except urllib.error.HTTPError as e:
                body = e.read().decode("utf-8", "replace")[:250]
                errors.append(f"{title}: HTTP {e.code} {body}")
                print(f"  FAILED  {title}: HTTP {e.code} {body}")
                detached -= 1
                kids -= c

    verb = "detached" if args.apply else "would be detached"
    print(f"\n{detached} board(s) {verb}, {kids} child board(s) removed, "
          f"{skipped} skipped")
    if errors:
        print(f"{len(errors)} error(s):")
        for e in errors:
            print(f"  {e}")
        return 1
    if not args.apply and detached:
        print("Dry run only.  Re-run with --apply to write.")
        print("canvas.api.db.sections.enable.py --apply is the way back.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
