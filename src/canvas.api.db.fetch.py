# Script:       canvas.api.db.fetch.py
# Version:      1.4.0
# Created:      2026-08-28
# Revised:      2026-10-13
# Purpose:      Snapshot the student posts on one block of BIOL240 discussion
#               boards into a single normalized JSON per board, so the posts
#               can be summarized, deduplicated and replied to offline.
#
# WHY A CHILD-TOPIC WALK.  canvas.db.sections.enable.py made all 26 graded
# boards GROUP discussions against the "Recitation Sections" set, so a student
# posts among their ~20 section peers rather than all 129.  The consequence for
# any reader is that the COURSE-level topic holds nothing: every one of the 26
# reports discussion_subentry_count == 0 while the posts sit in six child
# topics under /api/v1/groups/<gid>/.  A tool that reads the course topic sees
# an empty board and reports no activity.  This walks group_topic_children.
#
# STRICTLY READ-ONLY.  GET requests only; posting replies is canvas.db.reply.py.
#
# The message bodies are not clean HTML.  Students paste out of Canvas's own
# rendered DOM and out of AI chat interfaces, so a single one-sentence question
# can arrive wrapped in 40 nested <div>s carrying Tailwind and vendor classes.
# Every entry therefore gets a `text` field (tags stripped, entities resolved,
# whitespace collapsed) beside the original `message`, and the raw HTML is kept
# so nothing is lost and the stripper can be improved later without refetching.
#
# Usage:        canvas.db.fetch.py [OPTIONS] BLOCK
# Input:        the Canvas course named by canvas.course.json (--course-id /
#               --course-config); token via canvas_course.setup
# Output:       <outdir>/db.posts_<year>_<board>.json, one per board in BLOCK
#
# Arguments:
#   BLOCK           a posting block: L01-L04, L05-L09, L10-L13, L13-L18,
#                   L19-L22, L23-L26; or ALL; or an explicit range L02-L03
#
# Options:
#       --course-id ID  Canvas course id (default: canvas.course.json)
#       --course-config FILE  course config (default: found upward from cwd)
#       --year YYYY     year stamp used in output names (default: config year)
#   -o, --outdir DIR    output directory
#                       (default: F.<year>/Discussion.Boards/<BLOCK>/Posts)
#       --no-archive    do not archive the file being overwritten.  A re-fetch
#                       normally copies the outgoing snapshot into
#                       <outdir>/Archive/ first, stamped with ITS fetch time,
#                       so an edited or deleted post is still recoverable.
#   -n, --dry-run       list the boards and child topics, write nothing
#   -v, --verbose       per-entry detail
#   -h, --help          this message
#
# Requirements: python3 (stdlib only), a Canvas API token, teacher rights
#
