BASE = COURSE = None   # set in main() from canvas.course.json

# The graded lecture boards, recognized by title.  Anything else in the course
# -- the R## recitation boards, HW threads, contested-question boards -- is
# left alone, exactly as canvas.db.sections.enable.py leaves them alone.
# "L13: ..." and the renamed "L13 - DB Group 13-18" both count; the colon-only
# form silently dropped the renamed boards.
DB_TITLE_RX = re.compile(r"^(L[0-2][0-9])\b")

# The posting blocks the course actually grades against.  A block is a
# half-open span of lecture numbers; the DB participation cap (16 points) is
# per block, so a block is the natural unit for both the summary and the
# duplicate check.
import db_paths as _dbp   # the block table lives in ONE place
BLOCKS = dict(_dbp.BLOCK_BOUNDS)

RANGE_RX = re.compile(r"^L(\d{2})-L(\d{2})$")


# ---------------------------------------------------------------- html ----

class _Stripper(HTMLParser):
    """Collect visible text, dropping tags, <style>/<script>, and attributes.

    Block-level tags become newlines so paragraph structure survives; the
    caller collapses runs of blank lines.  Deliberately tolerant -- these
    messages are pasted DOM, not authored markup, and must never raise.
    """

    BLOCK = {
        "p", "div", "br", "li", "tr", "h1", "h2", "h3", "h4", "h5", "h6",
        "blockquote", "pre", "table", "ul", "ol",
    }
    SKIP = {"style", "script"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self._skip_depth = 0

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self._skip_depth += 1
        elif tag in self.BLOCK:
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in self.SKIP and self._skip_depth:
            self._skip_depth -= 1
        elif tag in self.BLOCK:
            self.parts.append("\n")

    def handle_data(self, data):
        if not self._skip_depth:
            self.parts.append(data)


def strip_html(raw):
    """Return the visible text of a Canvas message body."""
    if not raw:
        return ""
    p = _Stripper()
    try:
        p.feed(raw)
        p.close()
    except Exception:
        # Malformed markup: fall back to a blunt tag strip rather than lose
        # the post entirely.
        return _collapse(html.unescape(re.sub(r"<[^>]*>", " ", raw)))
    text = "".join(p.parts)
    text = text.replace(" ", " ")
    return _collapse(text)


def _collapse(text):
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" *\n *", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


# ---------------------------------------------------------------- api -----

def get_json(url, token):
    """canvas_http.http_get_json returns (body, headers); we want the body."""
    return canvas_http.http_get_json(url, token)[0]


def resolve_block(name):
    """Return (lo, hi) lecture numbers for a block name, ALL, or a range."""
    key = name.upper()
    if key == "ALL":
        return (1, 26)
    if key in BLOCKS:
        return BLOCKS[key]
    m = RANGE_RX.match(key)
    if m:
        lo, hi = int(m.group(1)), int(m.group(2))
        if lo <= hi:
            return (lo, hi)
    raise SystemExit(
        f"unknown block {name!r}; expected one of "
        f"{', '.join(sorted(BLOCKS))}, ALL, or a range like L02-L03"
    )


def list_boards(token, course, lo, hi, block=None):
    """Course-level graded lecture boards whose number falls inside [lo, hi]."""
    topics = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/courses/{course}/discussion_topics?per_page=100", token
    )
    out = []
    for t in topics:
        m = DB_TITLE_RX.match(t.get("title") or "")
        if not m:
            continue
        if re.search(r"\bCopy\s*$", t.get("title") or ""):
            print("  skipping a duplicate board: %s" % t["title"])
            continue
        n = int(m.group(1)[1:])
        if not (lo <= n <= hi):
            continue
        # Board 13 exists twice (one per block).  A named block takes only
        # its own; an explicit range that would take both is refused rather
        # than writing two boards into one file.
        if n == 13 and block:
            if db_paths.block_of_title(t.get("title")) != block:
                continue
        out.append((m.group(1), t))
    labels = [l for l, _ in out]
    dup = sorted({l for l in labels if labels.count(l) > 1})
    if dup:
        raise SystemExit("two boards match %s; name the block (L10-L13 or "
                         "L13-L18) instead of a range" % ", ".join(dup))
    return sorted(out, key=lambda x: x[0])


def group_names(token, category_id):
    groups = canvas_http.paginated_get_all(
        f"{BASE}/api/v1/group_categories/{category_id}/groups?per_page=100",
        token,
    )
    return {g["id"]: g["name"] for g in groups}


def flatten(entries, section, parent=None, depth=0):
    """Depth-first walk of a view tree into flat records.

    A top-level entry (parent_id null) is a THREAD -- the student's question.
    Everything below it is a REPLY.  The distinction is what the 16-point cap
    is stated in ("2 threads + 2 responses"), and the duplicate check applies
    to threads only.
    """
    out = []
    for e in entries or []:
        rec = {
            "id": e.get("id"),
            "parent_id": e.get("parent_id"),
            "root_id": parent["root_id"] if parent else e.get("id"),
            "depth": depth,
            "kind": "thread" if depth == 0 else "reply",
            "section": section,
            "user_id": e.get("user_id"),
            "created_at": e.get("created_at"),
            "updated_at": e.get("updated_at"),
            "deleted": bool(e.get("deleted")),
            "message": e.get("message") or "",
            "text": strip_html(e.get("message") or ""),
        }
        out.append(rec)
        out.extend(flatten(e.get("replies"), section, rec, depth + 1))
    return out


def fetch_checkpoints(token, course, assignment_id):
    """The two published deadlines for a checkpointed board.

    These boards are CHECKPOINTED discussions: the threads and the responses
    are separate sub-assignments with separate due dates, which is how the
    syllabus's two-deadline promise is actually implemented.  Neither date is
    on the topic -- `due_at` is None on every board -- and neither is in the
    intro text, so anything reading the topic alone sees one date or none and
    concludes the initial-post deadline was never published.  It was.  It
    lives here, and only `include[]=checkpoints` returns it.
    """
    if not assignment_id:
        return {}
    url = ("%s/api/v1/courses/%s/assignments/%s?include[]=checkpoints"
           % (BASE, course, assignment_id))
    try:
        a = get_json(url, token)
    except Exception as e:                  # a board with no assignment yet
        print("  WARNING: no checkpoints for assignment %s: %s"
              % (assignment_id, e), file=sys.stderr)
        return {}
    return {c.get("tag"): c.get("due_at") for c in (a.get("checkpoints") or [])
            if c.get("tag")}


def fetch_board(token, course, label, topic, gnames, verbose=False):
    """One board -> one dict holding every section's posts."""
    children = topic.get("group_topic_children") or []
    if not children:
        print(f"  WARNING {label}: no group_topic_children; is it a group "
              f"discussion?  Skipping.", file=sys.stderr)
        return None

    assignment = topic.get("assignment") or {}
    board = {
        "board": label,
        "title": topic.get("title"),
        "fetched_at": datetime.datetime.now(
            datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "topic_id": topic.get("id"),
        "published": topic.get("published"),
        "due_at": assignment.get("due_at"),
        "points_possible": assignment.get("points_possible"),
        # whether the board closes.  A response can only be late if posting
        # was still possible after the response deadline, so the grading
        # sheet needs to know: lock_at None and locked False means open.
        "lock_at": topic.get("lock_at") or assignment.get("lock_at"),
        "locked": bool(topic.get("locked")),
        "assignment_id": assignment.get("id") or topic.get("assignment_id"),
        # {"reply_to_topic": <initial-post deadline>,
        #  "reply_to_entry": <response deadline>}, both ISO-8601 UTC
        "checkpoints": fetch_checkpoints(
            token, course, assignment.get("id") or topic.get("assignment_id")),
        "group_category_id": topic.get("group_category_id"),
        "intro_html": topic.get("message") or "",
        "intro_text": strip_html(topic.get("message") or ""),
        "sections": {},
        "participants": {},
        "entries": [],
    }

    for ch in children:
        gid, cid = ch["group_id"], ch["id"]
        section = gnames.get(gid, str(gid))
        view = get_json(
            f"{BASE}/api/v1/groups/{gid}/discussion_topics/{cid}/view", token
        )
        for p in view.get("participants") or []:
            board["participants"][str(p["id"])] = {
                "name": p.get("display_name"),
                "section": section,
            }
        rows = flatten(view.get("view"), section)
        board["sections"][section] = {"group_id": gid, "child_topic_id": cid}
        board["entries"].extend(rows)
        n_t = sum(1 for r in rows if r["kind"] == "thread" and not r["deleted"])
        n_r = sum(1 for r in rows if r["kind"] == "reply" and not r["deleted"])
        print(f"  {label} section {section}: {n_t} threads, {n_r} replies")
        if verbose:
            for r in rows:
                if r["kind"] == "thread":
                    who = board["participants"].get(
                        str(r["user_id"]), {}).get("name", "?")
                    print(f"      [{r['id']}] {who}: {r['text'][:90]}")

    board["entries"].sort(key=lambda r: (r["section"], r["created_at"] or ""))
    return board


# ---------------------------------------------------------------- main ----

def main():
    ap = argparse.ArgumentParser(
        description="Snapshot a course's discussion board posts to JSON.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("block", metavar="BLOCK",
                    help="L01-L04 | L05-L09 | L10-L13 | L13-L18 | L19-L22 | "
                         "L23-L26 | ALL | an explicit range like L02-L03")
    ap.add_argument("-o", "--outdir", default=None, help="output directory")
    ap.add_argument("--no-archive", action="store_true",
                    help="do not archive the file being overwritten")
    ap.add_argument("-n", "--dry-run", action="store_true",
                    help="list boards and child topics, write nothing")
    ap.add_argument("-v", "--verbose", action="store_true")
    canvas_course.add_arguments(ap)
    args = ap.parse_args()
    global BASE, COURSE
    cfg, BASE, token = canvas_course.setup(args)
    COURSE = cfg.course_id
    args.course = cfg.course_id
    if cfg.year is None:
        sys.exit("[FAIL] no year: pass --year or set \"year\" in canvas.course.json")
    args.year = str(cfg.year)

    lo, hi = resolve_block(args.block)

    outdir = args.outdir or db_paths.posts_dir(
        args.year, "L%02d-L%02d" % (lo, hi))

    blk = args.block.upper()
    boards = list_boards(token, args.course, lo, hi,
                         blk if blk in BLOCKS else None)
    if not boards:
        raise SystemExit(f"no discussion boards found in L{lo:02d}-L{hi:02d}")
    print(f"{len(boards)} board(s) in L{lo:02d}-L{hi:02d}")

    cat_ids = {t.get("group_category_id") for _, t in boards
               if t.get("group_category_id")}
    gnames = {}
    for cid in cat_ids:
        gnames.update(group_names(token, cid))

    if args.dry_run:
        for label, t in boards:
            kids = t.get("group_topic_children") or []
            print(f"  {label} topic={t['id']} published={t.get('published')} "
                  f"children={len(kids)} -> "
                  f"{os.path.join(outdir, f'db.posts_{args.year}_{label}.json')}")
            for ch in kids:
                print(f"      section {gnames.get(ch['group_id'], '?')} "
                      f"group={ch['group_id']} child={ch['id']}")
        return 0

    os.makedirs(outdir, exist_ok=True)
    archive = not args.no_archive
    total_t = total_r = 0
    for label, t in boards:
        board = fetch_board(token, args.course, label, t, gnames, args.verbose)
        if board is None:
            continue
        live = [r for r in board["entries"] if not r["deleted"]]
        total_t += sum(1 for r in live if r["kind"] == "thread")
        total_r += sum(1 for r in live if r["kind"] == "reply")
        path = os.path.join(outdir, f"db.posts_{args.year}_{label}.json")
        # Archive the OUTGOING file before overwriting it.  A student who
        # edits or deletes a post after being warned leaves no trace on
        # Canvas -- the entry simply reads differently, or stops existing --
        # so the only record that the earlier version ever existed is the one
        # kept here.  db.compare.py reads these.
        if archive and os.path.exists(path):
            try:
                with open(path) as fh:
                    prev = json.load(fh)
                stamp = (prev.get("fetched_at") or "")[:16].replace(
                    ":", "").replace("-", "-") or "unknown"
            except (OSError, ValueError):
                stamp = "unknown"
            adir = os.path.join(outdir, "Archive")
            os.makedirs(adir, exist_ok=True)
            apath = os.path.join(
                adir, f"db.posts_{args.year}_{stamp}_{label}.json")
            if not os.path.exists(apath):
                shutil.copy2(path, apath)
                print(f"  archived previous -> {apath}")

        with open(path, "w") as fh:
            json.dump(board, fh, indent=1, ensure_ascii=True, sort_keys=False)
            fh.write("\n")
        print(f"  wrote {path}")

    print(f"\n{total_t} threads and {total_r} replies across "
          f"{len(boards)} board(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
